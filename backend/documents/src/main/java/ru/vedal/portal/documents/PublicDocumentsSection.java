package ru.vedal.portal.documents;

/**
 * Открыт ли публичный раздел документов наружу.
 *
 * <p><b>Зачем понадобилось.</b> Витрину документов погасили решением заказчика
 * ({@code VEDAL_PUBLIC_DOCUMENTS_ENABLED=false}): страница {@code /documents/}
 * отдаёт 404, пункт меню скрыт, общая вкладка документов на карточках
 * не строится, Ведалина про документы молчит. Публичное HTTP API при этом
 * оставалось открытым: {@code GET /api/public/v1/documents} отдавал перечень
 * с рабочими ссылками, а {@code /documents/{slug}/file} — сами файлы, включая
 * каталог продукции и сертификат. Выключатель гасил витрину, но не файлы,
 * и кто знал адрес — скачивал.
 *
 * <p><b>Почему свой тип, а не тот же, что у ассистента.</b> У Ведалины этот же
 * выключатель живёт в {@code ru.vedal.portal.assistant.PublicDocuments}.
 * Переиспользовать его здесь нельзя: модуль ассистента зависит от модуля
 * документов, и обратная зависимость замкнула бы круг. Поэтому объектов два,
 * а переменная окружения одна — {@code VEDAL_PUBLIC_DOCUMENTS_ENABLED}.
 * Один рубильник в окружении, два выключателя внутри; заводить второе имя
 * переменной значило бы получить состояние «витрина скрыта, файлы открыты»
 * ещё раз, только теперь по недосмотру в {@code .env}.
 *
 * <p><b>Точечное исключение.</b> С 18 сентября карточка A-2000 отдельно
 * предлагает согласованный заказчиком PDF. Контроллер разрешает только его
 * точный слаг, не открывая перечень и остальные файлы.
 *
 * <p><b>Чего он не касается.</b> Админки: сотрудник видит и скачивает
 * документы, как раньше, — скрыт публичный раздел, а не работа с документами.
 * Индекса ассистента тоже: он ходит в {@link DocumentQuery} внутри процесса,
 * а не через публичную дверь.
 *
 * @param enabled {@code true} — публичные двери документов работают как прежде.
 */
public record PublicDocumentsSection(boolean enabled) {

    /** Раздел открыт: перечень и файлы отдаются посетителю. */
    public static final PublicDocumentsSection OPEN = new PublicDocumentsSection(true);

    /** Раздел скрыт: перечня и общих публичных дверей к документам нет. */
    public static final PublicDocumentsSection HIDDEN = new PublicDocumentsSection(false);

    /** Прятать ли документы от посетителя. */
    public boolean hidden() {
        return !enabled;
    }
}

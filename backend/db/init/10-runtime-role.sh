#!/bin/sh
# Роль, под которой приложение ходит в базу. Права ей выдаёт миграция V16,
# а заводится она здесь.
#
# Почему не миграцией: у роли есть пароль, а пароль в миграции проезжает
# текстом запроса и оседает в pg_stat_activity и в логах Flyway. Сверх того
# в Managed PostgreSQL владельцу схемы не выдают CREATEROLE, и CREATE ROLE
# из миграции там просто не прошёл бы. Существование роли и пароль — забота
# окружения, права — забота миграции.
#
# Скрипт выполняется entrypoint'ом образа postgres и ТОЛЬКО при создании
# кластера, то есть на пустом томе. На уже существующем томе он не запустится,
# и V16 остановит накат с требованием завести роль руками — это лучше, чем
# молча оставить приложение работать владельцем схемы:
#
#   docker exec -it vedal-db psql -U vedal -d vedal \
#     -c "create role vedal_app login password '…'"
#
# В облаке роль заводится консолью, и этот файл там не нужен вовсе.

set -eu

RUNTIME_USER="${VEDAL_RUNTIME_USER:-vedal_app}"
RUNTIME_PASSWORD="${VEDAL_RUNTIME_PASSWORD:-vedal-app-local}"

# Подстановка через переменные psql, а не в текст скрипта: :'pwd' экранирует
# значение как строковый литерал, :"role" — как идентификатор. Пароль со
# кавычкой внутри иначе развалил бы запрос, а в худшем случае дописал бы к нему
# свой.
psql -v ON_ERROR_STOP=1 \
     --username "$POSTGRES_USER" \
     --dbname "$POSTGRES_DB" \
     -v role="$RUNTIME_USER" \
     -v pwd="$RUNTIME_PASSWORD" <<'SQL'
create role :"role" login password :'pwd';

-- Ничего больше здесь не выдаётся намеренно: все права роли живут в миграции,
-- и искать их надо в одном месте, а не в двух.
SQL

echo "Роль рантайма $RUNTIME_USER заведена; права выдаст миграция V16."

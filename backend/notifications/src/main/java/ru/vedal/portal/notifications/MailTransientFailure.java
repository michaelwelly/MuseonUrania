package ru.vedal.portal.notifications;

// Отказ, который имеет смысл повторить: сервер недоступен, соединение отвалилось
// по таймауту, SMTP ответил временным отказом (коды 4xx), учётные данные пока
// не приняты. Письмо остаётся в очереди и ждёт следующей попытки.
//
// Отдельный тип, а не флаг в общем исключении: разница между «повторить»
// и «не повторять» — это разница между письмом, которое дойдёт через час,
// и письмом, которое пять раз подряд получит тот же отказ и займёт собой
// место в очереди.
public class MailTransientFailure extends RuntimeException {

    public MailTransientFailure(String message, Throwable cause) {
        super(message, cause);
    }
}

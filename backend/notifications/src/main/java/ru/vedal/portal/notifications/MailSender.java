package ru.vedal.portal.notifications;

// Порт наружу. Ранняя реализация — запись в лог, полная — SMTP Яндекс 360.
public interface MailSender {

    void send(String to, String subject, String body);

    /**
     * Есть ли куда отправлять.
     *
     * <p>Ложь означает, что SMTP не настроен: письма некуда девать, и очередь
     * трогать нельзя. Раньше в этом случае письмо помечалось отправленным —
     * на стенде так и стояли две записи со статусом {@code sent}, которых
     * никто не получал. Заявка при этом в базе есть, а человек, который ждёт
     * её письмом, не знает о ней ничего.
     *
     * <p>Теперь письмо остаётся в очереди и дождётся настроенной почты:
     * заявки, пришедшие до неё, дойдут задним числом. Это лучше и отметки
     * «отправлено», и отказа: отказ израсходовал бы попытки и похоронил
     * письмо там, где виновата настройка, а не адресат.
     */
    default boolean configured() {
        return true;
    }
}

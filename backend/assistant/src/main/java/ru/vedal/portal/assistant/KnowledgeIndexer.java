package ru.vedal.portal.assistant;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import ru.vedal.portal.common.DomainEventConsumer;
import ru.vedal.portal.common.Outbox;

/**
 * Очередь индексации: документ правят — индекс догоняет сам.
 *
 * <p><b>Зачем потребитель, а не вызов из редактора.</b> Индексация — это
 * сеть и деньги: разбор файла, десяток вызовов модели, секунды. Позвать её
 * прямо из двери правки значит заставить редактора ждать облако, пока он
 * жмёт «опубликовать», и уронить публикацию, если облако молчит.
 * Событие уже пишется в ту же транзакцию, что и сама правка, — значит,
 * «документ опубликован» и «его надо переиндексировать» не могут разъехаться.
 *
 * <p><b>Почему одинаково на все действия с документом.</b> Событие говорит,
 * что документ изменился; каким он стал, знает перечень. Публикация,
 * снятие, замена файла и правка заголовка сходятся к одному вопросу —
 * «что теперь должно лежать в индексе», — и разные ответы на него в четырёх
 * ветках однажды разъедутся. {@link KnowledgeIndex#indexDocument} смотрит
 * перечень заново: документ там есть — индексируем, нет — забываем.
 *
 * <p><b>Идемпотентность.</b> Требование интерфейса, но здесь она даровая:
 * повторная индексация неизменившегося материала сверяет отпечаток
 * и не тратит ни одного вызова модели.
 *
 * <p><b>Про транзакцию.</b> Доставка раздаёт событие внутри своей
 * транзакции, и обращения к модели идут внутри неё же: соединение с базой
 * занято, пока отвечает облако. Это осознанная цена — доставка идёт
 * в фоновом потоке по одному событию, а документов в перечне десяток.
 * Станет их сотни — событие надо будет откладывать в очередь индексации
 * и разбирать отдельным потоком, и это первое, что здесь придётся менять.
 *
 * <p><b>Отказ не глотается.</b> Молчание облака или битый файл обязаны
 * долететь до доставки: она повторит, а после повторов положит событие
 * в DLQ. Проглоченное здесь означало бы индекс, тихо отставший от сайта,
 * — то есть ассистента, который рассказывает про снятый документ.
 */
public class KnowledgeIndexer implements DomainEventConsumer {

    private static final Logger log = LoggerFactory.getLogger(KnowledgeIndexer.class);
    private static final String DOCUMENT_EVENT = "vedal.documents.v1";

    private final KnowledgeIndex index;

    public KnowledgeIndexer(KnowledgeIndex index) {
        this.index = index;
    }

    @Override
    public String name() {
        return "assistant.knowledge";
    }

    @Override
    public boolean handles(String type) {
        return DOCUMENT_EVENT.equals(type);
    }

    @Override
    public void consume(Outbox event) {
        // Ключ события документа — его slug: тот же идентификатор, которым
        // документ зовётся в перечне и в индексе. Разбирать ради него тело
        // события незачем — это был бы второй способ узнать то же самое,
        // и однажды они разошлись бы.
        var slug = event.getAggregateId();

        var outcome = index.indexDocument(slug);
        log.info("Индекс Ведалины: документ {} — {}", slug, outcome);
    }
}

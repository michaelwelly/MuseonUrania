package ru.vedal.portal.assistant;

import io.swagger.v3.oas.annotations.media.Schema;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

/**
 * Заготовки Ведалины: что она отвечает на кнопки виджета.
 *
 * <p>Зачем понадобились. Кнопки в виджете были подписаны «Подобрать
 * оборудование», «Запросить КП», «Специалист VEDAL», а нажатие отправляло
 * эту самую подпись как вопрос — и поиск отвечал на неё каталогом.
 * «Специалист VEDAL» при этом никого не звал: разговор оставался открытым.
 * Кнопка, делающая не то, что на ней написано, хуже отсутствующей кнопки:
 * отсутствующую человек обходит, а этой он верит.
 *
 * <p><b>Почему выбор по намерению, а не по тексту.</b> Виджет присылает
 * {@code intent} — какую кнопку нажали, — а не полагается на совпадение строк.
 * Подпись кнопки живёт в интерфейсе и меняется вместе с ним; совпадение
 * по ней разъехалось бы на первой же правке текста, и разъехалось бы молча:
 * ответ просто перестал бы находиться, а вопрос ушёл бы в поиск.
 *
 * <p><b>Почему свободный текст сюда не попадает.</b> Соблазн узнавать
 * намерение по словам («хочу КП» → заготовка про КП) велик, но такая догадка
 * ошибается на отрицаниях и уточнениях — «пока не нужно КП» получило бы тот
 * же ответ, что и «нужно КП». Свободный текст идёт обычным путём: ограничения,
 * поиск по опубликованному, передача человеку, если ничего не нашлось.
 *
 * <p><b>Почему в коде, а не в базе.</b> Правка текстов ассистента редактором
 * без релиза — правильная цель, но она требует согласования: поле ввода,
 * в котором можно написать цену или срок поставки, обходит правила проекта
 * ровно так же, как их обошла бы модель. Пока текстов пять и меняются они
 * реже, чем раз в релиз, они живут здесь.
 *
 * <p>Когда встанет YandexGPT, заготовки останутся быстрым путём для кнопок:
 * на «Запросить КП» незачем ходить в модель, ответ известен заранее.
 */
public final class ScriptedReplies {

    /** Что делает кнопка: спросить Ведалину или позвать человека. */
    public static final String ASK = "ask";
    public static final String HANDOFF = "handoff";

    @Schema(name = "AssistantPrompt", description = """
            Кнопка быстрого ответа в виджете. Список приходит с портала, а не
            переписан в интерфейс: подпись и заготовка, разложенные по двум
            местам, расходятся на первой же правке.
            """)
    public record Prompt(

            @Schema(description = "Что нажали. Именно это виджет присылает обратно.",
                    example = "quote")
            String intent,

            @Schema(description = "Подпись на кнопке.", example = "Запросить КП")
            String label,

            @Schema(description = """
                    Что делать при нажатии. `ask` — отправить в чат как вопрос
                    с этим намерением, `handoff` — позвать специалиста отдельной
                    дверью.
                    """, allowableValues = {"ask", "handoff"}, example = "ask")
            String action) {}

    // LinkedHashMap: порядок кнопок в виджете — это порядок здесь.
    private static final Map<String, String> ANSWERS = new LinkedHashMap<>();

    static {
        ANSWERS.put("equipment",
                "Уточните отделение — неонатология, реанимация, анестезиология, мониторинг "
                        + "или интенсивная терапия — и задачу. Покажу подходящие изделия "
                        + "из каталога со ссылками на карточки.");

        ANSWERS.put("document",
                "Назовите модель, например VEDAL A-2000. Покажу, какие документы по ней "
                        + "есть в перечне на сайте. Часть документов выдаётся по запросу — "
                        + "тогда позову специалиста.");

        // Цену и условия ассистент не называет — правило проекта, и здесь оно
        // сказано вслух, а не обойдено молчанием: человек, нажавший «Запросить
        // КП», должен понимать, почему цифры в ответе не будет.
        ANSWERS.put("quote",
                "Коммерческое предложение готовит специалист: цену, сроки и условия "
                        + "ассистент не называет. Опишите задачу здесь и позовите специалиста — "
                        + "или оставьте заявку формой на сайте, там можно указать контакты.");

        // «При необходимости оформим выезд» отсюда убрано ещё во фронтенде
        // 19 августа: выезд к заказчику ни одним документом не подтверждён,
        // а ассистент обещал его от имени компании. Здесь того же обещания нет.
        ANSWERS.put("service",
                "Опишите изделие и что происходит. По сервису отвечает специалист — "
                        + "позовите его, и он подключится к этому разговору.");
    }

    private static final List<Prompt> PROMPTS = List.of(
            new Prompt("equipment", "Подобрать оборудование", ASK),
            new Prompt("document", "Найти документ", ASK),
            new Prompt("quote", "Запросить КП", ASK),
            new Prompt("service", "Сервис", ASK),
            new Prompt("human", "Позвать специалиста", HANDOFF));

    /**
     * Что Ведалина пишет, когда позвали человека.
     *
     * <p>Ни времени ответа, ни обещания, что специалист сейчас на месте:
     * дежурство портал не хранит (нет ни таблицы, ни двери), и «ответит
     * в течение получаса» было бы обязательством, которого никто не давал.
     * Сказано только то, что произошло на самом деле: разговор встал
     * в очередь. Контакты виджет показывает рядом — их отдаёт `handoff`.
     */
    public static final String CALLING_HUMAN =
            "Зову специалиста VEDAL. Разговор встал в очередь — ответ придёт в это же окно. "
                    + "Опишите задачу здесь, чтобы специалисту не пришлось переспрашивать.";

    private ScriptedReplies() {}

    /** Кнопки виджета по порядку. */
    public static List<Prompt> prompts() {
        return PROMPTS;
    }

    /**
     * Заготовка по намерению. Пусто — намерения такого нет, и вопрос идёт
     * обычным путём: незнакомое намерение не повод отказать, виджет мог
     * остаться от прошлой версии в открытой вкладке.
     */
    public static Optional<String> answerFor(String intent) {
        return intent == null ? Optional.empty()
                : Optional.ofNullable(ANSWERS.get(intent.trim()));
    }
}

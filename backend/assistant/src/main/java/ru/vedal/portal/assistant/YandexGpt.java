package ru.vedal.portal.assistant;

import java.util.List;
import java.util.function.Consumer;

/**
 * Разговор с моделью: отправили сообщения — получили текст.
 *
 * <p><b>Зачем интерфейс.</b> За ним стоит сеть, деньги и чужая доступность —
 * то есть всё, чего в тесте быть не должно. Правила ответа (что показывать
 * модели, что делать с её ответом, когда её вообще не спрашивать) живут
 * в {@link YandexGptEngine} и проверяются подставным собеседником; сам HTTP
 * проверяется отдельно, поднятым на месте сервером.
 *
 * <p>Второе назначение — сменяемость. Сегодня это YandexGPT, завтра может
 * быть другая модель: у неё будут свои поля запроса и свой адрес, но
 * «отправить реплики и получить текст» останется тем же.
 */
public interface YandexGpt {

    /** Роль реплики. Системная задаёт правила, пользовательская несёт вопрос. */
    enum Role { SYSTEM, USER }

    record Message(Role role, String text) {}

    /**
     * Спросить модель.
     *
     * @param onChunk куда отдавать текст по мере готовности. Модель считает
     *                секундами, и посетитель всё это время смотрит в окно:
     *                куски уходят ему сразу, не дожидаясь конца ответа.
     * @return ответ целиком — он и записывается в переписку. Склейка кусков
     *         равна ему же: показанный черновик и сохранённый ответ обязаны
     *         совпадать.
     */
    String complete(List<Message> messages, Consumer<String> onChunk);
}

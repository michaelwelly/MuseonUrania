-- Ключ в хранилище больше не несёт область в себе: область — параметр порта
-- FileStorage, и она же выбирает бакет. Ключ 'documents/opisanie.pdf' после
-- этого разрешался бы в documents/documents/opisanie.pdf.
--
-- В сиде V11 ни у одного документа файла нет, поэтому строк для правки может
-- не оказаться вовсе. Миграция всё равно нужна: в средах разработки файлы
-- уже загружали руками, и молча сломать им ссылку — худший из вариантов.
update document
   set storage_key = substring(storage_key from 11)
 where storage_key like 'documents/%';

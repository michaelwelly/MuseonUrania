package ru.vedal.portal.common;

// Сверка версии редактируемой карточки.
//
// Первая линия защиты от того, что двое правят одно и то же. Она ловит самый
// частый случай: карточку открыли утром, сохранили вечером, а между этим её
// правил кто-то ещё. @Version в сущности — вторая линия, для настоящей
// одновременной записи двумя транзакциями; без явной проверки он бы не
// сработал, потому что версия читается из базы в той же транзакции и всегда
// совпадает сама с собой.
//
// Живёт в common, а не в одном из доменов: правило одно на всех, и домен,
// вызывающий соседа ради общей проверки, — это тот самый клубок, ради
// распутывания которого модули и разведены.
public final class Versions {

    private Versions() {}

    public static void check(Long sent, long current, String what) {
        if (sent == null) {
            throw new ConflictException(what + " отправили без версии. Перечитайте карточку "
                    + "и повторите: сохранить вслепую значит затереть чужую правку.");
        }
        if (sent != current) {
            throw new ConflictException(what + " уже изменил другой редактор, пока карточка "
                    + "была открыта у вас. Перечитайте её и внесите правку заново — иначе "
                    + "его изменения пропадут без следа.");
        }
    }
}

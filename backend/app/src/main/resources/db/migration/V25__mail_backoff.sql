-- Выдержка между попытками отправки письма.
--
-- Что было. Отправитель раз в пять секунд забирал из очереди всё, у чего
-- статус 'queued', и пробовал отправить. Пока реализацией MailSender была
-- запись в лог, этого хватало: лог не отказывает. С настоящим SMTP
-- недоступность почтового сервера в течение двадцати пяти секунд исчерпывала
-- все пять попыток и переводила в 'failed' сразу всю очередь — вместе
-- с письмами, которые ушли бы через минуту. Заявка при этом уже принята,
-- и клиент остаётся без подтверждения.
--
-- Что стало. У письма есть время следующей попытки. Отправитель берёт только
-- те, у которых оно наступило, а после отказа сдвигает его вперёд с нарастающим
-- шагом (ряд — в MailAttempt.BACKOFF).
--
-- Уже лежащие в таблице письма получают now(): их очередь наступает сразу,
-- поведение для них не меняется. Это важно для наката на работающую базу —
-- письмо, отложенное миграцией на час, выглядело бы как потерянное.
alter table outbound_mail
    add column next_attempt_at timestamptz not null default now();

-- Частичный индекс переписывается под новый порядок выборки. Старый был
-- по created_at, и для запроса «что пора отправлять» он бесполезен:
-- планировщику пришлось бы читать всю очередь и фильтровать по времени
-- следующей попытки. Условие where оставляем — отправленные письма
-- накапливаются, а ищем всегда только среди ожидающих.
drop index outbound_mail_queued_idx;
create index outbound_mail_due_idx on outbound_mail (next_attempt_at)
    where status = 'queued';

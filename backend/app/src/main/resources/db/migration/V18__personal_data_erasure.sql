-- Удаление персональных данных: по обращению человека и по истечении срока.
--
-- Формы собирают ФИО, телефон и почту, то есть портал — оператор персональных
-- данных. Из этого следуют две обязанности, которых в схеме до сих пор не было:
-- удалить данные по обращению субъекта и не хранить их дольше заявленного срока.
--
-- ————— почему обезличивание, а не удаление строки —————
--
-- Удалить строку заявки нельзя, не сломав три вещи сразу:
--
--   * сделка ссылается на заявку (deal.lead_id), и разбор заявки в сделку
--     закреплён индексом deal_lead_idx — «заявка разбирается в сделку один раз»;
--   * аналитика считает воронку по источнику, языку и кампании: исчезнувшая
--     заявка уменьшает знаменатель задним числом, и конверсия прошлого квартала
--     меняется сама собой;
--   * журнал ссылается на идентификатор заявки, а журнал неизменяем — ссылка
--     осталась бы, а цель исчезла.
--
-- Обезличивание закрывает требование и не ломает ничего: персональные данные
-- уничтожаются, заявка остаётся единицей учёта. После него строка не позволяет
-- опознать человека, то есть перестаёт быть персональными данными.
--
-- Что уничтожается: имя, телефон, почта, текст обращения, а также тема и тело
-- записей истории переписки. Что остаётся: форма, источник, язык, кампания,
-- статус, время — по ним человек не опознаётся.
--
-- Организация (company, ИНН, КПП) не трогается: юридическое лицо персональными
-- данными не является.
--
-- ————— что журнал —————
--
-- Проверено по коду: в журнал по заявке уходят только form и source, а в топик
-- Kafka — то же самое. Персональных данных там нет, поэтому неизменяемость
-- журнала не спорит с обязанностью удалить данные. Спорила бы — пришлось бы
-- выбирать между двумя требованиями, и выбор был бы плохим в любую сторону.

-- ————— заявка —————

alter table lead add column erased_at     timestamptz;
alter table lead add column erasure_basis text;

comment on column lead.erased_at is
    'Когда персональные данные заявки уничтожены. NULL — не уничтожались.';
comment on column lead.erasure_basis is
    'Основание: обращение субъекта или истечение срока хранения.';

-- Обезличенная заявка обязана помнить основание, иначе через год не ответить,
-- почему данных нет. Обратное тоже: основание без отметки времени — след
-- операции, которая не выполнена.
alter table lead add constraint lead_erasure_has_basis
    check ((erased_at is null and erasure_basis is null)
        or (erased_at is not null and erasure_basis is not null));

-- Отбор для автоочистки: «созданные раньше срока и ещё не обезличенные».
-- Частичный индекс, потому что обезличенные из выборки уходят навсегда и место
-- под них в индексе держать незачем — а их со временем становится большинство.
create index lead_retention_idx on lead (created_at) where erased_at is null;

-- ————— клиент —————
--
-- Карточка организации, но почта и телефон в ней — контактного лица.

alter table client add column erased_at     timestamptz;
alter table client add column erasure_basis text;

alter table client add constraint client_erasure_has_basis
    check ((erased_at is null and erasure_basis is null)
        or (erased_at is not null and erasure_basis is not null));


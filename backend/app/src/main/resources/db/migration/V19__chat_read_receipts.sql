-- Отметка прочтения сообщения.
--
-- ————— почему это в базе, а набор текста — нет —————
--
-- «Печатает прямо сейчас» живёт секунды и интересно только тому, кто смотрит
-- в экран в эту минуту. Записывать его значит писать в базу несколько раз
-- на каждое сообщение ради факта, который протухает раньше, чем доедет.
-- Он уходит событием мимо базы.
--
-- «Прочитано» — наоборот: это факт, и он обязан пережить перезагрузку
-- страницы, смену сотрудника и перезапуск приложения. Менеджер, вернувшийся
-- к разговору через час, должен видеть, дошёл ли его ответ, а не гадать.
--
-- ————— почему отметка на сообщении, а не на разговоре —————
--
-- На разговоре хватило бы одной колонки «докуда прочитано», и так делают
-- ради экономии. Но тогда «прочитано» становится свойством ленты, а не
-- сообщения, и ответить на вопрос «увидел ли он именно это» нельзя: между
-- двумя ответами сотрудника посетитель мог уйти.
--
-- Здесь важно именно посообщенчно: сотрудник смотрит, дошёл ли конкретный
-- ответ, прежде чем звонить.

alter table chat_message add column read_at timestamptz;

comment on column chat_message.read_at is
    'Когда сообщение прочитано ПРОТИВОПОЛОЖНОЙ стороной. NULL — не прочитано.';

-- Отметку ставит тот, кому сообщение адресовано, читая ленту. Поэтому
-- запрос всегда одинаковый: «непрочитанные сообщения этого разговора,
-- написанные не мной». Частичный индекс: прочитанные из выборки уходят
-- навсегда, и со временем их становится подавляющее большинство.
create index chat_message_unread_idx
    on chat_message (conversation_id, author)
    where read_at is null;


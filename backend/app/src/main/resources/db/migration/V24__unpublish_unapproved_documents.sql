-- Снять с публикации документы, которые никто не разрешал публиковать.
--
-- §7.6 плана заказчика от 18 августа 2026: «Не публиковать документы, пока
-- нет явного согласования». §7.3 — финальный список документов для открытого
-- доступа — до сих пор не получен, то есть согласовано пока ничто.
--
-- Что было опубликовано и как. По журналу оба документа опубликовал редактор
-- 13 и 14 августа, то есть до встречи, на которой записали §7.6. Это была
-- проверка загрузки файлов, а не публикация по решению заказчика, — и она
-- пережила встречу.
--
--   * «Каталог продукции 2026» — настоящий PDF на 3 МБ;
--   * «Лицензия на производство медицинских изделий» — файл на 19 байт
--     с содержимым «%PDF-1.7 проба».
--
-- Второй хуже первого. Публичная страница предлагала скачать лицензию на
-- производство медицинских изделий и отдавала заглушку. Это не утечка —
-- утекать там нечему, — но посетитель, которому нужна лицензия, получал
-- сломанный файл вместо ответа «выдаётся по запросу».
--
-- Почему миграцией, а не переключателем в админке. Переключатель чинит одну
-- базу, а состояние повторяется в каждой: на стенде, на ВМ и у любого, кто
-- поднимет стек. Тот же приём, что в V20, где девять изделий без датащитов
-- снимались с публикации.
--
-- Почему точечно, а не «снять всё». Правило §7.6 — про отсутствие
-- согласования, а не про запрет публикации вообще. Миграция, снимающая
-- с публикации всё подряд, откатывала бы работу редактора при каждом
-- развёртывании: заказчик согласует список, редактор опубликует, следующий
-- деплой погасит. Поэтому названы ровно те две строки, которые опубликованы
-- по недосмотру.
--
-- Обратно включается одним update, когда придёт список из §7.3.
update document
set published = false
where slug in ('katalog-produkcii-2026',
               'licenziya-na-proizvodstvo-medicinskih-izdeliy')
  and published;


-- Заявка, заведённая прямо из разговора.
--
-- ————— зачем отдельный источник —————
--
-- Источников было три: сайт, Яндекс Форма, почта. Разговор — четвёртый,
-- и записать его как 'site' было бы удобно ровно один раз: при первой же
-- сводке «откуда приходят заявки» чат растворился бы в форме на сайте.
-- А это разные вещи — форму заполняют по своей воле, в чат приходят
-- с вопросом, и превращается он в заявку только если разговор к этому привёл.
-- Разрез по источнику существует, чтобы такие вещи различать.
--
-- ————— почему check, а не справочник —————
--
-- Значений четыре, и растут они раз в год. Таблица-справочник дала бы
-- внешний ключ и join к каждой выборке заявок ради четырёх строк, которые
-- редактировать некому: новый источник появляется вместе с кодом, который
-- его пишет, а не вместе со строкой, заведённой менеджером.

alter table lead drop constraint lead_source_check;

alter table lead add constraint lead_source_check
    check (source in ('site', 'yandex_form', 'email', 'chat'));

comment on column lead.source is
    'Откуда пришла заявка: site — форма на сайте, chat — разговор с Ведалиной, '
    'yandex_form — Яндекс Форма, email — разбор почты.';

-- ————— номер обращения в разговоре —————
--
-- Разговор уже ссылается на заявку через lead_id. Номер рядом с ним —
-- не дубль этой связи, а снимок: chat и crm друг о друге не знают намеренно,
-- и достать номер по идентификатору модулю разговора нечем. Ходить за ним
-- через соседа значило бы завести зависимость ради одной строки на экране.
--
-- Снимок и по второй причине, той же, что у источников ответа: переписка
-- обязана остаться такой, какой её видел человек. Номер он унёс с собой —
-- в письме, в записной книжке, в разговоре по телефону.
alter table conversation add column lead_number text;

comment on column conversation.lead_number is
    'Номер заявки, заведённой из разговора: снимок для показа в ленте. '
    'NULL — разговор до заявки не дорос.';

-- Закрытый документ не может стоять в публичном перечне. §12.4 плана
-- от 18 августа 2026: confidential-документы не индексируются и не
-- показываются.
--
-- Что было. Уровень секретности обязателен с V10, и `document_public_only`
-- не даёт опубликовать непубличный документ — файл был защищён. Но перечень
-- на сайте отбирается по флагу `listed`, а он с секретностью никак не связан:
-- достаточно было пометить закрытый документ как «в перечне», и наружу
-- уезжали название, раздел, предмет и привязка к изделию. Файла по такой
-- строке не получить, но «Отчёт об испытаниях VEDAL R2» в открытом списке
-- говорит о продукте ровно то, чего говорить не должен.
--
-- Тот же перечень читает ассистент — значит утечка попадала бы и в ответы,
-- со ссылкой на источник.
--
-- Ограничение, а не только правка запроса. Запрос поправлен тоже, но он
-- защищает один путь чтения. Строка в базе, которой быть не должно, рано
-- или поздно найдёт второй: отчёт, выгрузку, новый эндпоинт. Дешевле
-- не пускать её в таблицу.
--
-- На существующие данные не влияет: все десять документов из V11 —
-- public, и ни один не менял уровень.
alter table document
    add constraint document_listed_only_public
        check (not listed or sensitivity = 'public');

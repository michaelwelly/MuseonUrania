-- Разговор посетителя: виджет на сайте, ответ Урании, вход сотрудника.
--
-- ————— почему это не четвёртая дверь —————
--
-- В архитектуре правило: дверей три, четвёртая не заводится. Чат — запись
-- снаружи, и на первый взгляд он это правило нарушает. Не нарушает:
-- POST /api/assistant/v1/ask уже принимает свободный текст от анонимного
-- посетителя и уже стоит под лимитом частоты. Разговор — та же дверь
-- ассистента, у которой ответ перестал быть разовым, а в переписку получил
-- возможность войти человек. Новых правил проверки периметра не появляется.
--
-- ————— кто собеседник —————
--
-- Посетитель анонимен, и это решение, а не упрощение. Форма «представьтесь»
-- перед первым сообщением отсекает большую часть тех, кто хотел быстро
-- спросить, — а спросивший и есть будущая заявка. Контакты берутся тогда,
-- когда разговор переходит в заявку, и тогда же берётся согласие на обработку
-- персональных данных.
--
-- Следствие для 152-ФЗ: пока контактов нет, персональных данных в разговоре
-- нет вовсе. Опознаётся посетитель случайным ключом в браузере, который
-- ничего о нём не сообщает и живёт до очистки хранилища.
--
-- Текст сообщений при этом персональными данными стать МОЖЕТ: человек волен
-- написать «я Иванов Иван, мой телефон…» в свободном поле. Поэтому разговор
-- обезличивается тем же механизмом, что и заявка, — колонки те же.

create table conversation (
    id             uuid primary key,

    -- Ключ посетителя: случайный, живёт в браузере, ничего о человеке
    -- не сообщает. По нему виджет находит свой разговор после перезагрузки
    -- страницы. Не идентификатор человека — идентификатор вкладки.
    visitor_key    text        not null,

    -- Откуда пришёл. Те же поля, что у заявки, и по той же причине: без них
    -- разрезы аналитики «по языку» и «по кампании» посчитать нечем, а снимать
    -- их потом уже неоткуда.
    language       text,
    campaign       text,
    page           text,

    -- open      — идёт, ответы даёт ассистент;
    -- waiting   — ассистент передал человеку, сотрудник ещё не подключился;
    -- attended  — сотрудник в разговоре;
    -- closed    — разговор завершён.
    --
    -- waiting отделён от attended намеренно: это единственное состояние,
    -- где человек ждёт живого ответа, и очередь работы на сводке строится
    -- по нему. Слив его с open превратил бы очередь в список всех разговоров.
    status         text        not null default 'open'
                   check (status in ('open', 'waiting', 'attended', 'closed')),

    -- Кто из сотрудников ведёт. Пусто — никто не взял.
    owner          text,

    -- Разговор, переросший в заявку. Связь односторонняя: заявка о разговоре
    -- не знает, потому что заявка может прийти и без него.
    lead_id        uuid        references lead (id),

    -- Обезличивание: те же две колонки и то же правило, что у заявки (V18).
    erased_at      timestamptz,
    erasure_basis  text,

    started_at     timestamptz not null default now(),

    -- Время последнего сообщения. Денормализация ради списка в админке:
    -- сортировать разговоры по «кто написал последним» иначе значит считать
    -- max(at) по всей таблице сообщений на каждое открытие списка.
    last_at        timestamptz not null default now(),

    version        bigint      not null default 0,

    constraint conversation_erasure_has_basis
        check ((erased_at is null and erasure_basis is null)
            or (erased_at is not null and erasure_basis is not null)),

    -- Завершённый разговор обязан помнить, кто его вёл: «закрыт неизвестно кем»
    -- в разборе жалобы бесполезно.
    constraint conversation_attended_has_owner
        check (status <> 'attended' or owner is not null)
);

-- Виджет ищет свой разговор по ключу браузера, и ищет часто — на каждой
-- загрузке страницы. Открытый разговор у ключа один: второй означал бы, что
-- посетитель пишет в одно окно, а сотрудник отвечает в другое.
create unique index conversation_visitor_open_idx
    on conversation (visitor_key)
    where status <> 'closed';

-- Очередь сотрудника: кто ждёт живого ответа дольше всех.
create index conversation_waiting_idx
    on conversation (last_at)
    where status = 'waiting';

create index conversation_owner_idx on conversation (owner) where owner is not null;


create table chat_message (
    id              uuid        primary key,
    conversation_id uuid        not null references conversation (id) on delete cascade,

    -- visitor   — написал посетитель;
    -- assistant — ответила Урания;
    -- staff     — ответил сотрудник.
    --
    -- Три значения, а не флаг «наш/не наш»: посетитель обязан видеть разницу
    -- между ответом машины и ответом человека. Скрыть её — значит выдать
    -- ответ поиска за консультацию сотрудника, а этого не должно быть
    -- ни при каких обстоятельствах.
    author          text        not null check (author in ('visitor', 'assistant', 'staff')),

    -- Логин сотрудника для author='staff'. У посетителя и ассистента пусто.
    actor           text,

    body            text        not null,

    -- Ссылки на опубликованные источники, которыми ответила Урания. JSON,
    -- потому что это снимок ответа: изделие могли переименовать или снять
    -- с публикации, а переписка обязана остаться такой, какой её видел человек.
    sources         jsonb,

    at              timestamptz not null default now(),

    constraint chat_message_staff_has_actor
        check (author <> 'staff' or actor is not null),

    -- Пустое сообщение не несёт ничего и ломает ленту.
    constraint chat_message_not_blank check (length(btrim(body)) > 0)
);

-- Лента разговора читается по порядку и только так.
create index chat_message_thread_idx on chat_message (conversation_id, at);

-- Историю переписки не правят: сообщение, которое можно исправить задним
-- числом, перестаёт быть историей ровно тогда, когда оно понадобилось.
-- Тем же правилом живёт interaction в CRM и журнал аудита.
--
-- Удаление строк при этом остаётся: обезличивание по 152-ФЗ стирает тела
-- сообщений, а каскад от conversation убирает разговор целиком.

-- ————— права —————
--
-- V16 выдала права роли рантайма на таблицы, существовавшие на тот момент,
-- и поставила ALTER DEFAULT PRIVILEGES на будущие. Эти две таблицы права
-- получают по умолчанию — дописывать grant сюда не нужно.
--
-- А вот отзыв TRUNCATE по умолчанию не наследуется: у новой таблицы права
-- владельца снова полные. Без этих двух строк LeastPrivilegeTest уронит
-- сборку, и это ровно то, ради чего он написан.
revoke truncate on conversation from public, current_user;
revoke truncate on chat_message from public, current_user;

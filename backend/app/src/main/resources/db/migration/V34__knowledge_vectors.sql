-- Хранилище векторов Ведалины: место, куда ляжет корпус документов.
--
-- ————— почему схема заводится раньше корпуса —————
--
-- Корпуса у VEDAL ещё нет: датащиты, буклеты и описания изделий заказчик
-- передаёт по частям (GitHub issue #38). Схема при этом от содержимого
-- не зависит — она зависит от модели эмбеддингов и от того, как устроен
-- поиск, а это решения наши, и принять их можно сейчас.
--
-- Пустой индекс — рабочее состояние, а не заготовка. Поиск по пустой
-- таблице возвращает ноль строк, ассистент отвечает тем же детерминированным
-- поиском по словам, что и до этой миграции, и ни одна дверь не меняет
-- поведения. Именно поэтому таблицы можно завести до корпуса: они ничего
-- не ломают, пока пусты.
--
-- ————— расширение —————
--
-- `vector` — это pgvector: тип вектора, операторы расстояния и индексы
-- приблизительного поиска. Ставится расширение здесь, а не руками на
-- машине, по правилу проекта «схема меняется только миграциями».
--
-- Две оговорки, и обе надо знать.
--
-- Первая: расширение обязано быть в образе базы. Обычный `postgres:16`
-- его не несёт, и на нём эта строка падает с «extension "vector" is not
-- available». Стек переведён на `pgvector/pgvector:pg16` — тот же
-- PostgreSQL 16, плюс расширение; тесты поднимают тот же образ.
--
-- Вторая: в Managed PostgreSQL расширение включается в консоли облака,
-- а не запросом. Там эта строка выполнится вхолостую — `if not exists`
-- ровно для этого случая и написан.
create extension if not exists vector;

-- ————— источник —————
--
-- Одна строка — один материал портала: карточка изделия, новость, документ
-- или страница сайта. Не файл: у документа файл может смениться, а материал
-- останется тем же, и переиндексация не должна заводить второй источник.
create table knowledge_source (
    id           uuid        primary key,

    -- Что это за материал. Тот же словарь, что у источников в ответе
    -- ассистента (`LlmEngine.Source.kind`): по нему виджет решает, как
    -- показать ссылку.
    kind         text        not null,

    -- Как материал зовётся у своего модуля: slug изделия, slug новости,
    -- slug документа. Внешнего ключа нет намеренно — материалы живут
    -- в четырёх разных таблицах четырёх модулей, и ссылка на любую из них
    -- означала бы, что индекс знает их внутренности. Он не знает: он
    -- получает материалы через запросные интерфейсы соседей.
    external_id  text        not null,

    -- Что показать под ответом. Заголовок и адрес хранятся здесь, а не
    -- добираются из модуля в момент ответа: поиск по близости обязан
    -- отвечать одним запросом, а не N+1 походами по модулям.
    title        text        not null,
    url          text        not null,

    -- Кому материал виден. Два уровня, ровно как у областей ассистента:
    -- public — посетителю сайта, internal — сотруднику после входа.
    --
    -- Confidential здесь отсутствует как значение, и это не упущение,
    -- а граница: §7.4 отдаёт такие документы «только по отдельному
    -- разрешению», и вход в админку разрешением не является. Материал
    -- этого уровня в индекс не попадает вовсе — не фильтруется на выдаче,
    -- а физически отсутствует. Фильтр на выдаче однажды забыли бы
    -- в новом запросе; отсутствующей строки забыть нельзя.
    visibility   text        not null,

    -- Язык материала. Нужен на выдаче: отвечать русскоязычному посетителю
    -- английским чанком того же изделия — худший вид «нашлось».
    language     text        not null,

    -- Отпечаток текста, из которого нарезаны чанки. Совпал — материал
    -- не изменился, и переиндексировать его незачем: нарезка та же,
    -- а эмбеддинги стоят денег и времени. Не совпал — чанки заменяются
    -- целиком.
    --
    -- Считается по тексту, а не по файлу: у PDF меняются метаданные
    -- и дата, а текст остаётся тем же, и отпечаток по байтам файла
    -- заставлял бы переиндексировать неизменившееся.
    checksum     text        not null,

    indexed_at   timestamptz not null default now(),

    -- Материал в индексе один. Вторая строка про то же изделие означала бы
    -- два набора чанков и удвоенную выдачу по одному и тому же вопросу.
    constraint knowledge_source_identity unique (kind, external_id),

    constraint knowledge_source_kind_check
        check (kind in ('product', 'news', 'document', 'page')),

    constraint knowledge_source_visibility_check
        check (visibility in ('public', 'internal')),

    constraint knowledge_source_title_not_blank
        check (length(btrim(title)) > 0)
);

comment on table knowledge_source is
    'Материал портала, попавший в индекс Ведалины. Одна строка — один '
    'материал; чанки лежат в knowledge_chunk.';

-- ————— чанк —————
--
-- Фрагмент текста и его вектор. Нарезка нужна не ради базы, а ради ответа:
-- вектор целого буклета — это вектор «вообще про VEDAL», и ближайшим он
-- окажется к любому вопросу. Фрагмент отвечает за один сюжет, и близость
-- к нему что-то значит.
create table knowledge_chunk (
    id         uuid        primary key,

    -- Удаление источника уносит его чанки. Осиротевший чанк — это выдача
    -- со ссылкой на снятый с публикации материал, то есть ровно то, чего
    -- правило «наружу уходит только опубликованное» не допускает.
    source_id  uuid        not null
                   references knowledge_source (id) on delete cascade,

    -- Порядковый номер внутри материала. Нужен для сборки контекста:
    -- соседние фрагменты читаются подряд, и перепутанный порядок делает
    -- из выдержки бессвязицу.
    position   int         not null,

    -- Текст фрагмента. Он же и есть то, что увидит модель: всё, чего
    -- здесь нет, для неё не существует.
    text       text        not null,

    -- Чем посчитан вектор. Не украшение: векторы разных моделей несравнимы
    -- между собой, и чанк, посчитанный вчерашней моделью, соседствуя
    -- с сегодняшними, тихо портит выдачу — расстояние до него считается,
    -- а смысла не имеет. Колонка позволяет это увидеть и переиндексировать
    -- отставшее, а не гадать, почему поиск стал хуже.
    model      text        not null,

    -- Вектор.
    --
    -- 256 — размерность эмбеддингов Yandex Foundation Models
    -- (`emb://<каталог>/text-search-doc/latest` и парная ему
    -- `text-search-query`). Число прошито в типе колонки, потому что
    -- pgvector требует размерность для индекса: колонка без неё
    -- проиндексирована быть не может, а без индекса поиск по близости —
    -- это перебор всей таблицы.
    --
    -- Портал не верит этому числу на слово: при индексации длина вектора,
    -- пришедшего от модели, сверяется с ожидаемой, и расхождение роняет
    -- индексацию с внятным сообщением. Иначе смена модели была бы заметна
    -- не по отказу, а по тому, что ответы стали хуже.
    --
    -- Сменится модель — сменится размерность, и это отдельная миграция
    -- с полной переиндексацией. Дописать сюда вторую колонку нельзя:
    -- сравнивать векторы разных моделей всё равно нечем.
    embedding  vector(256) not null,

    created_at timestamptz not null default now(),

    -- Два фрагмента с одним номером — это либо потерянная нарезка, либо
    -- недоудалённая старая. И то и другое даёт дубли в выдаче.
    constraint knowledge_chunk_position_unique unique (source_id, position),

    constraint knowledge_chunk_text_not_blank
        check (length(btrim(text)) > 0)
);

comment on table knowledge_chunk is
    'Фрагмент материала и его вектор. Поиск Ведалины идёт по этой таблице.';

-- ————— индексы —————
--
-- HNSW по косинусному расстоянию. Косинус, а не L2: длина вектора у моделей
-- поиска несёт длину текста, а не смысл, и по L2 длинный фрагмент оказывается
-- «дальше» просто потому, что он длинный.
--
-- HNSW, а не IVFFlat, и причина прямо про эту задачу: IVFFlat строит списки
-- по существующим данным и на пустой таблице бессмыслен — его пришлось бы
-- создавать после появления корпуса, то есть отдельной миграцией в тот день,
-- когда заказчик передаст документы. HNSW строится на пустой таблице
-- и наполняется вместе с ней.
create index knowledge_chunk_embedding_idx
    on knowledge_chunk using hnsw (embedding vector_cosine_ops);

-- Чанки материала читаются и удаляются пачкой: переиндексация заменяет их
-- целиком. Без индекса это обход таблицы на каждый переиндексированный
-- материал.
create index knowledge_chunk_source_idx on knowledge_chunk (source_id);

-- ————— права —————
--
-- Права рантайма на новые таблицы приезжают сами: V16 поставила
-- ALTER DEFAULT PRIVILEGES на будущие объекты владельца схемы.
--
-- Отзыв TRUNCATE не наследуется — у новой таблицы права владельца снова
-- полные. Без этих строк LeastPrivilegeTest уронит сборку, и это ровно то,
-- ради чего он написан.
revoke truncate on knowledge_source from public, current_user;
revoke truncate on knowledge_chunk from public, current_user;

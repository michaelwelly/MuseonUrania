-- Права роли приложения: то, чего она не должна уметь вовсе.
--
-- До этой миграции журнал сторожили триггеры BEFORE UPDATE и BEFORE DELETE,
-- а про TRUNCATE в документах было записано, что триггер от него не спасает.
-- Это неверно: PostgreSQL поддерживает BEFORE TRUNCATE ... FOR EACH STATEMENT,
-- и такой триггер оператор останавливает. Проверено на PostgreSQL 16 —
-- и здесь же проверяется тестом, а не обещанием.
--
-- Почему обе меры, а не одна:
--
--   * триггер держится независимо от прав: чтобы его обойти, надо явно
--     выполнить ALTER TABLE ... DISABLE TRIGGER, а это уже не опечатка
--     в консоли и не подстановка в запрос;
--   * отзыв прав держится независимо от триггера — и станет настоящей
--     границей в тот день, когда рантайм перестанет ходить в базу под
--     владельцем схемы.
--
-- Чего эта миграция НЕ делает, и это важнее того, что делает.
--
-- 1. Приложение ходит в базу под владельцем схемы — под той же ролью, которой
--    Flyway накатывает миграции. Владелец может выдать себе отозванное обратно
--    одной строкой, поэтому отзыв ловит ошибку, а не злой умысел.
--
-- 2. Отзыв прав вообще ничего не значит для суперпользователя: проверки прав
--    он не проходит, он их не проходит вовсе. Образ `postgres` заводит
--    POSTGRES_USER именно суперпользователем, то есть в локальном стеке и в
--    тестах ACL декоративен, и держит там один триггер. В развёрнутой среде
--    роль приложения обязана быть обычной — иначе всё ниже написано впустую.
--
-- Настоящее разделение — отдельная роль для рантайма, не суперпользователь
-- и не владелец схемы. Оно трогает compose.yaml, compose.prod.yaml,
-- .env.example и PostgresTestBase, и делается отдельно.

-- ————— журнал —————

-- Журнал не правится, не чистится по строкам и не опустошается целиком.
create trigger audit_entry_no_truncate before truncate on audit_entry
    for each statement execute function audit_entry_append_only();

revoke update, delete, truncate on audit_entry from public, current_user;

-- ————— TRUNCATE вообще нигде —————

-- Приложение не опустошает ни одной таблицы целиком: чистка outbox, когда
-- она появится, будет удалять строки по возрасту, а не всё разом.
--
-- Отзыв покрывает таблицы, существующие на этот момент. У таблицы, заведённой
-- следующей миграцией, права владельца снова полные, и ALTER DEFAULT PRIVILEGES
-- этого не меняет: владельцу права не выдаются, а подразумеваются. Поэтому
-- строку надо дописывать в каждую миграцию, которая заводит таблицу, —
-- и забыть её не даёт LeastPrivilegeTest, иначе защита разъезжалась бы молча.
revoke truncate on all tables in schema public from public, current_user;

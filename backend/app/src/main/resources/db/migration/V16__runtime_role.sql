-- Отдельная роль для рантайма. То, что V15 назвала следующим шагом и не сделала.
--
-- До этой миграции приложение ходило в базу владельцем схемы — той же ролью,
-- которой Flyway накатывает миграции. Владелец возвращает себе отозванное одной
-- строкой, поэтому весь отзыв прав из V15 ловил опечатку, но не злой умысел,
-- а в локальном стеке, где роль ещё и суперпользователь, не ловил вообще ничего.
--
-- Граница проходит не по «какие таблицы правим»: приложение законно удаляет
-- строки почти отовсюду — категории, новости, характеристики изделия и позиции
-- КП заменяются целиком, часть через orphanRemoval. Отзыв DELETE поголовно
-- сломал бы первую же правку каталога, и заметил бы это редактор на проде,
-- а не сборка: тесты ходят суперпользователем.
--
-- Граница проходит по другому: рантайм меняет ДАННЫЕ, но не может изменить
-- ни СХЕМУ, ни ПРАВА, ни ЖУРНАЛ. Отсюда три следствия, каждое из которых
-- закрывает конкретную дыру:
--
--   * не владеет таблицами → DDL закрыт целиком, и вместе с ним закрыт обход
--     «снять ограничение, записать запрещённое, вернуть ограничение»;
--   * не владеет журналом → ALTER TABLE ... DISABLE TRIGGER недоступен,
--     и триггер audit_entry_append_only перестаёт быть обходимым;
--   * не имеет GRANT OPTION → отозванное себе не вернуть. Ровно это и отличает
--     роль рантайма от владельца, у которого отзыв прав был напоминанием.
--
-- Проверяется всё это RuntimeRolePrivilegesTest: он открывает вторую связь
-- именно этой ролью и сверяет отказы, а не записи в системном каталоге.
-- ACL, который никто не применял, — гипотеза того же сорта, что и
-- невосстановленный бэкап.

-- ————— роль обязана существовать —————
--
-- Миграция роль НЕ создаёт, и это решение, а не упущение. У роли есть пароль,
-- а пароль в миграции проезжает текстом запроса и оседает в pg_stat_activity
-- и в логах Flyway. Сверх того в Managed PostgreSQL владельцу схемы не выдают
-- CREATEROLE, и CREATE ROLE здесь просто не прошёл бы — миграция, работающая
-- только на своей машине, хуже её отсутствия.
--
-- Поэтому существование роли и её пароль — забота окружения (init-скрипт
-- в compose, консоль облака, PostgresTestBase в тестах), а права — забота
-- миграции. Отсутствие роли останавливает накат громко и с инструкцией:
-- молча пропущенная выдача прав означала бы приложение, которое поднялось
-- владельцем схемы и об этом никому не сказало.
do $$
begin
    if not exists (select 1 from pg_roles where rolname = 'vedal_app') then
        raise exception
            'Нет роли vedal_app, под которой приложение ходит в базу. %',
            'Заведите её до наката: create role vedal_app login password ''…''; '
            'в compose это backend/db/init/10-runtime-role.sh, в облаке — консоль.';
    end if;
end $$;

-- ————— что рантайму можно —————

-- Имя базы в GRANT обязано быть литералом, а оно разное в стеке, в тестах
-- и в облаке — отсюда подстановка вместо прямой строки.
do $$
begin
    execute format('grant connect on database %I to vedal_app', current_database());
end $$;

grant usage on schema public to vedal_app;

-- Данные — целиком. Отдельно оговаривается только журнал, ниже.
grant select, insert, update, delete on all tables in schema public to vedal_app;
grant usage, select on all sequences in schema public to vedal_app;

-- Таблицы следующих миграций. Без этого каждая новая таблица была бы невидима
-- рантайму до тех пор, пока кто-нибудь не вспомнит дописать сюда строку, —
-- то есть до первой ошибки на проде.
--
-- Работает это только для объектов, созданных ролью, указанной в FOR ROLE,
-- поэтому здесь стоит владелец схемы: под ним Flyway накатывает миграции.
alter default privileges for role current_user in schema public
    grant select, insert, update, delete on tables to vedal_app;
alter default privileges for role current_user in schema public
    grant usage, select on sequences to vedal_app;

-- TRUNCATE не выдан нигде и не выдаётся по умолчанию: приложение не опустошает
-- целиком ни одной таблицы, а TRUNCATE прошёл бы мимо построчных триггеров
-- и мимо внешних ключей.

-- ————— чего рантайму нельзя даже так —————

-- Журнал: только дописывание и чтение. Право UPDATE на него не нужно ни одному
-- сценарию, а его наличие означало бы, что запись о доступе к документу можно
-- переписать задним числом — и тогда журнал перестаёт быть журналом ровно
-- в тот момент, когда он понадобился.
revoke update, delete on audit_entry from vedal_app;

-- Создавать свои объекты в схеме рантайм не должен: схему ведёт только Flyway.
-- В PostgreSQL 15+ CREATE на public роли PUBLIC уже не выдаётся, но полагаться
-- на версию базы здесь незачем — строка ниже стоит копейку.
revoke create on schema public from public, vedal_app;

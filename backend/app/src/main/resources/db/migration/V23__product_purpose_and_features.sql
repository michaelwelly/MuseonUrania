-- §4.5 плана заказчика: на карточке изделия должны быть готовые места под
-- финальные тексты — короткое описание, назначение, ключевые особенности,
-- характеристики, комплектация, документы и фото. Из семи не хватало двух:
-- назначения и ключевых особенностей, класть их было некуда.
--
-- Места заводятся пустыми. Тексты придут от НН (§4.7), и до тех пор карточка
-- честно говорит «ожидает уточнения» — правило из CLAUDE.md запрещает
-- заполнять такие поля правдоподобной выдумкой.

-- ————— Назначение —————
--
-- Колонкой, а не строкой в product_spec: назначение у изделия одно и это
-- связный текст, а не элемент списка. В product_spec оно стало бы записью
-- с меткой «Назначение» и абзацем в поле value — то есть таблицей
-- характеристик из одной строки, растянутой на пять предложений.
--
-- Nullable намеренно: у всех четырёх изделий назначения сейчас нет, и
-- значение по умолчанию пришлось бы выдумать. NULL читается как «текста
-- нет», пустая строка — как «текст есть и он пустой».
alter table product
    add column purpose text;

-- ————— Ключевые особенности —————
--
-- Отдельная таблица, а не kind = 'feature' в product_spec. У особенности нет
-- пары «метка — значение»: это одно утверждение. В product_spec колонка value
-- объявлена not null, и особенность пришлось бы класть в label с пустой
-- строкой в value — то есть завести состояние, которого у сущности нет,
-- и попросить каждого читателя об этом помнить. Админка вдобавок рисует
-- строку спецификации двумя полями ввода, и второе было бы всегда пустым.
create table product_feature
(
    id         uuid primary key,
    product_id uuid not null references product (id) on delete cascade,
    position   int  not null,
    body       text not null
);

-- Индекс повторяет product_spec_product_idx: выборка всегда идёт по изделию
-- и сразу в порядке позиций, отдельной сортировки не нужно.
--
-- Уникальности на (product_id, position) здесь намеренно нет, хотя пара и
-- уникальна по смыслу. Редактор сохраняет список так же, как список
-- характеристик: чистит коллекцию и добавляет строки заново. Hibernate в
-- одной транзакции выполняет вставки раньше удалений, и новая строка с
-- position = 0 столкнулась бы со старой, ещё не удалённой. product_spec живёт
-- без такого ограничения по той же причине; заводить его только здесь значит
-- получить ошибку сохранения на первом же редактировании особенностей.
create index product_feature_product_idx on product_feature (product_id, position);

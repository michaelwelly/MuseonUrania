-- График дежурств: кто сегодня на линии.
--
-- ————— зачем это порталу —————
--
-- До этой таблицы портал знал два факта и ни одного из них не хватало.
--
-- Первый — часы работы поддержки (`vedal.support.*`): «Пн–Пт 9:00–17:30».
-- Это обещание, что кто-то ответит, и оно ничего не говорит о том, КТО.
--
-- Второй — присутствие: открыто ли сейчас хоть одно рабочее место. Это факт,
-- но факт про множество: «кто-то смотрит в экран». По нему нельзя ни передать
-- смену, ни спросить за неотвеченный вопрос — спрашивать не с кого.
--
-- Дежурство — третье и другое: названный человек на названный день. Именно
-- его не было, и именно поэтому в разделе «Разговоры» стояла плашка
-- «ожидает уточнения» (GitHub issue #51).
--
-- ————— почему день, а не интервал —————
--
-- Смена могла бы задаваться парой меток времени — тогда в одном дне их
-- помещается сколько угодно, и график покрывает круглосуточную поддержку
-- с пересменкой в три часа ночи. Такой поддержки здесь нет: часы работы
-- заданы одним отрезком на будний день, и вторая смена внутри него —
-- это не расписание, а дробление одного отрезка.
--
-- Цена интервала при этом настоящая: пересечения смен надо запрещать
-- ограничением исключения (btree_gist), «кто дежурит сейчас» перестаёт
-- быть чтением одной строки, а экран графика превращается из календаря
-- в диаграмму. Всё это окупится в тот день, когда появится ночная смена;
-- пока день — это ровно та единица, в которой о дежурстве говорят вслух.
--
-- День считается в зоне поддержки (`vedal.support.zone`), а не в зоне
-- сервера: «сегодня» у дежурного в Екатеринбурге и у машины в другом
-- часовом поясе — разные даты, и вторая здесь никого не интересует.
--
-- ————— почему один дежурный на день —————
--
-- Первичный ключ по дате, а не суррогатный идентификатор со свободой завести
-- второго. Два дежурных на один день — это два ответа на вопрос «с кого
-- спрашивать», то есть ни одного. Понадобится подстраховка вторым человеком
-- — это будет отдельная колонка с отдельным смыслом, а не вторая строка
-- с тем же.
--
-- Отсюда же передача смены: она не заводит новую строку, а меняет `login`
-- в сегодняшней. Кто дежурил до передачи, помнит журнал аудита — там
-- записано и «было», и «стало». Вторая история тех же событий в этой
-- таблице разошлась бы с журналом на первой же правке.

create table duty_shift (
    -- День дежурства в зоне поддержки. Он же ключ: дежурный на день один.
    on_date     date        primary key,

    -- Логин сотрудника в том виде, в каком его знает провайдер идентичности.
    -- Внешнего ключа нет и быть не может: сотрудники живут в Keycloak,
    -- а не в таблице портала. Проверку «такой логин существует» держит
    -- дверь, спрашивая справочник, — там же, где она держится у поля
    -- «ответственный» у заявки и сделки.
    login       text        not null,

    -- Чем эта смена отличается от обычной: «до 15:00, дальше Иванов»,
    -- «работаю из дома». Не обязательна и ничего не значит для портала —
    -- это записка людям, а не признак, по которому что-то решается.
    note        text,

    -- Кто назначил. Не «кто дежурит», а «кто поставил» — вопрос
    -- «почему я сегодня дежурю» задают именно об этом.
    assigned_by text        not null,
    assigned_at timestamptz not null default now(),

    version     bigint      not null default 0,

    -- Пустой логин — это не «дежурного нет», это строка-призрак: в графике
    -- день выглядит занятым, а на линии никого. «Никого» выражается
    -- отсутствием строки, и только им.
    constraint duty_shift_login_not_blank check (length(btrim(login)) > 0)
);

comment on table duty_shift is
    'Кто на линии в этот день. Одна строка — один день; отсутствие строки '
    'означает, что дежурного на день не назначили.';

-- ————— индексов нет, и это не упущение —————
--
-- График читается двумя способами: «кто сегодня» — это выборка по первичному
-- ключу, и «ближайшие две недели» — диапазон по нему же. Первичный ключ
-- в PostgreSQL и есть индекс; второго не нужно.
--
-- Выборка «все смены такого-то» пойдёт по таблице целиком. В ней строк
-- столько, сколько было рабочих дней, — несколько сотен в год, и спрашивают
-- её с карточки сотрудника, а не на каждое открытие виджета.

-- ————— права —————
--
-- Права рантайма на новую таблицу приезжают сами: V16 поставила
-- ALTER DEFAULT PRIVILEGES на будущие объекты владельца схемы.
--
-- А вот отзыв TRUNCATE по умолчанию не наследуется — у новой таблицы права
-- владельца снова полные. Без этой строки LeastPrivilegeTest уронит сборку,
-- и это ровно то, ради чего он написан.
revoke truncate on duty_shift from public, current_user;

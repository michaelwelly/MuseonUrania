-- Серийный номер изделия в сервисном обращении.
--
-- ————— почему отдельная колонка, а не строка в тексте —————
--
-- Номер можно было оставить в message: человек и так пишет его первой строкой.
-- Но тогда «найти заявку по номеру» превращается в поиск подстроки по
-- свободному тексту, который находит заодно номер счёта, номер палаты и номер
-- телефона. А ищут по нему часто и в худший момент: звонит заказчик, называет
-- номер аппарата, и по нему нужно поднять прошлые обращения.
--
-- ————— почему без формата —————
--
-- Вид серийного номера VEDAL в подтверждённых материалах не описан. Проверка
-- по придуманной маске отклоняла бы настоящие номера — а это хуже, чем принять
-- любую строку: обращение не уйдёт вовсе, и человек не поймёт почему.
-- Ограничена только длина, и это граница хранения, а не утверждение о том,
-- как устроен номер изделия.
--
-- ————— почему необязательная —————
--
-- Номер знают не всегда: шильдик закрыт, аппарат в другом отделении, звонит
-- не тот, кто рядом с изделием. Форма прямо разрешает оставить поле пустым,
-- и обращение без номера — обычное обращение, а не обращение с пропуском.
--
-- Проверки «serial_number только при form = service» здесь намеренно нет.
-- Ограничение живёт в интерфейсе, где ему и место: в форме запроса цены или
-- каталога изделия у человека ещё нет. В схеме такая проверка запретила бы
-- менеджеру дописать номер в заявку, принятую по телефону, — законный случай,
-- который схема не должна знать в лицо.

alter table lead add column serial_number text;

comment on column lead.serial_number is
    'Серийный номер изделия из сервисного обращения. NULL — не указан.';

-- Та же граница, что в LeadSubmission на бэкенде. Продублирована здесь
-- не для симметрии: через Forms API заявка приходит не единственным путём —
-- есть разбор почты и обмен с 1С, и они мимо проверок контроллера. Граница,
-- которая держится только в приложении, держится ровно до второго писателя.
alter table lead add constraint lead_serial_number_length
    check (serial_number is null or length(serial_number) <= 100);

-- ————— чего здесь нет —————
--
-- Индекса нет. Поиск по заявкам идёт через `like '%…%'` — совпадение по части
-- строки, — а такому запросу обычный btree-индекс не помогает: ведущий шаблон
-- не даёт по нему пройти. Имя, телефон и почта ищутся тем же способом и тоже
-- без индекса; заводить его одному полю значило бы сделать вид, что поиск
-- ускорен. Станет медленно на всей таблице — лечится триграммным индексом
-- сразу по всем полям поиска, отдельной миграцией и с расширением pg_trgm.
--
-- Обезличивания нет. V18 уничтожает имя, телефон, почту и текст обращения.
-- Серийный номер — характеристика аппарата, а не человека, и стоит в одном
-- ряду с организацией, которую V18 не трогает по той же причине. После
-- обезличивания заявка остаётся единицей учёта: по номеру изделия видно
-- историю обслуживания аппарата, а опознать по нему человека нельзя.
--
-- Прав не выдаётся. Новых таблиц миграция не заводит, а права из V15 и V16
-- выданы на таблицу, а не на колонку, — они действуют на новую колонку сами.

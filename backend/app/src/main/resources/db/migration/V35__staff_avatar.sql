-- Портрет сотрудника: то, что стоит вместо кружка с буквой.
--
-- ————— почему в базе, а не в объектном хранилище —————
--
-- Хранилищ у портала два, и ни одно не подходит.
--
-- `vedal-media` открыт на чтение анонимно — это его назначение: снимки
-- изделий раздаются мимо приложения, чтобы не гнать картинки через портал.
-- Положить туда лицо сотрудника значит опубликовать его. Контур закрытый,
-- портрет видят только свои — то есть бакет отпадает по смыслу, ещё до
-- того, как выясняется, что у сервисного ключа на него нет вообще никаких
-- прав (GitHub issue #37).
--
-- `vedal-documents` закрыт и доступен, но это хранилище документов: у него
-- своя дверь, которая проверяет публикацию и пишет обращение в журнал, и
-- свои ограничения (`document_published_has_file`, `document_public_only`).
-- Портрет — не документ, и второй род объектов в сейфе, про который правила
-- сейфа ничего не говорят, однажды разъедется с ними.
--
-- База подходит по тому же признаку, по которому обычно не подходит, —
-- по размеру. Здесь он ограничен и мал: одна строка на логин, она
-- заменяется, а не дописывается, и хранится приведённый портрет 256×256
-- в JPEG — десятки килобайт. Шестьдесят сотрудников — меньше одного
-- датащита.
--
-- Взамен получаем три вещи, которых у бакета нет:
--
--   1. бэкап. Ежедневный `pg_dump -Fc` с проверкой восстановлением есть
--      только у базы; бакеты не бэкапятся вовсе (docs/PROJECT.md, 5.9);
--   2. одна транзакция. Строка портрета и строка журнала коммитятся вместе —
--      то же рассуждение, что у транзакционного outbox. У бакета `put`
--      и запись строки расходятся, и разошедшись, молчат;
--   3. приватность по построению. Байты отдаёт дверь портала под токеном,
--      а не политика бакета, которую можно переписать мимо кода.
--
-- Цена названа прямо: bytea — не файловое хранилище, и обобщать этот приём
-- нельзя. Портрет проходит по трём условиям сразу — он мал, его размер
-- ограничен сверху проверкой ниже, и число строк равно числу сотрудников.
-- Появится что-то, где хоть одно условие не держится, — это будет отдельный
-- закрытый бакет, и к тому времени issue #37 всё равно придётся закрыть.

create table staff_avatar (
    -- Логин в том виде, в каком его знает провайдер идентичности. Он же ключ:
    -- портрет у человека один.
    --
    -- Внешнего ключа нет и быть не может — сотрудники живут в Keycloak,
    -- а не в таблице портала. Ровно то же у `duty_shift.login`,
    -- `deal.owner` и `audit_entry.actor`.
    login        text        primary key,

    -- `sub` из токена Keycloak — идентификатор учётной записи, который
    -- не меняется никогда, в отличие от логина.
    --
    -- Он здесь не для поиска, а против одного случая: учётную запись
    -- удалили, а освободившийся логин выдали другому человеку. Тогда новый
    -- сотрудник унаследовал бы чужое лицо, и заметить это было бы некому.
    -- Портал сверяет `subject` с токеном при каждом входе владельца
    -- и стирает портрет, который принадлежит не ему.
    --
    -- Пусто в запасном режиме `vedal.iam.mode=local`: там `sub` не бывает.
    subject      text,

    -- Всегда image/jpeg: портал не хранит то, что прислали, а перекодирует.
    -- Колонка есть, чтобы смена формата не потребовала миграции данных.
    content_type text        not null,

    bytes        bytea       not null,

    width        integer     not null,
    height       integer     not null,

    -- SHA-256 хранимых байтов. Отдаётся как ETag: портрет меняется раз
    -- в год, а запрашивается на каждой странице, где есть кружок.
    etag         text        not null,

    updated_at   timestamptz not null default now(),

    -- Верхняя граница — заявление о том, чем эта таблица не является.
    -- Рабочий размер решает код (портрет приводится к 256×256 JPEG,
    -- это десятки килобайт); мегабайт здесь — потолок, за которым
    -- «портрет» перестал быть портретом и таблица перестала быть тем,
    -- о чём написано выше.
    constraint staff_avatar_size check (octet_length(bytes) between 1 and 1048576),

    constraint staff_avatar_login_not_blank check (length(btrim(login)) > 0),

    -- Нулевая сторона означала бы кружок в ноль пикселей — то есть
    -- строку, которую нечем нарисовать.
    constraint staff_avatar_side_positive check (width > 0 and height > 0)
);

comment on table staff_avatar is
    'Портрет сотрудника для закрытого контура. Одна строка — один логин; '
    'отсутствие строки означает, что портрета нет и рисуется кружок с буквой.';

comment on column staff_avatar.subject is
    'sub из Keycloak. Ловит переиспользование освободившегося логина: '
    'портрет, чей subject не совпал с токеном владельца, стирается.';


-- Права рантайма на новую таблицу приезжают сами: V16 поставила
-- ALTER DEFAULT PRIVILEGES на будущие объекты владельца схемы. Отзыв
-- TRUNCATE не наследуется — без этой строки LeastPrivilegeTest уронит
-- сборку, и это ровно то, ради чего он написан.
revoke truncate on staff_avatar from public, current_user;

-- Помог ли ответ Ведалины.
--
-- ————— зачем это порталу —————
--
-- Разбор качества ответов сейчас строится по журналу: сколько раз ассистент
-- ответил, сколько раз не нашёл источников, сколько раз позвали человека.
-- Этого хватает, чтобы увидеть, что Ведалина молчит, и не хватает, чтобы
-- увидеть худшее: она ответила уверенно и не по делу. Такой ответ в журнале
-- неотличим от хорошего — источники нашлись, передачи не было.
--
-- Кто отличает — посетитель, и только он. Одно нажатие «не помог» стоит
-- дороже десяти замеров: оно указывает на конкретный ответ с конкретным
-- вопросом рядом.
--
-- ————— почему на сообщении, а не на разговоре —————
--
-- Разговор из шести реплик, оценённый одной кнопкой, отвечает на вопрос
-- «понравилось ли», а нужен ответ на «какой ответ был плохим». По оценке
-- на сообщении видно и то и другое; по оценке на разговоре — только первое,
-- и разбирать её приходится, перечитывая переписку целиком.
--
-- ————— почему boolean, а не звёзды —————
--
-- Шкала от одного до пяти требует от человека решить, что такое «три»,
-- и в ответ получает шум: одни ставят три хорошему ответу, другие —
-- плохому. Вопрос здесь ровно один и с двумя исходами: помог или нет.
--
-- NULL — не оценивали, и это большинство: кнопку нажимают единицы.
-- Отличать «не оценили» от «оценили плохо» обязательно, иначе средняя
-- по разговорам считается по тем, кто промолчал.

alter table chat_message add column helpful boolean;

comment on column chat_message.helpful is
    'Помог ли ответ, по мнению посетителя. NULL — не оценивал; оценка есть '
    'только у сообщений ассистента.';

-- ————— чего здесь нет —————
--
-- Проверки «helpful только у author = assistant». Ограничение живёт в коде,
-- где ему и место: кнопки стоят под ответом Ведалины, а дверь проверяет
-- автора. В схеме такая проверка запретила бы менеджеру когда-нибудь
-- отметить полезной реплику сотрудника — законный случай, который схема
-- не должна знать в лицо.
--
-- Индекса. Оценки читаются вместе с лентой разговора, по conversation_id,
-- и для этого индекс уже есть. Отдельная выборка «все плохие ответы»
-- пойдёт по таблице целиком, но случается она раз в неделю при разборе,
-- а не на каждое открытие виджета.
--
-- Времени оценки. Оно у сообщения уже есть — `at`, и оценку ставят сразу
-- после ответа: отдельная колонка означала бы вторую дату, отвечающую
-- на тот же вопрос с точностью до минут.
--
-- Прав. Колонка добавляется к существующей таблице, а права из V15 и V16
-- выданы на таблицу, а не на колонку.

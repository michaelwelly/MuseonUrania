-- Регистрационный статус перестаёт быть обещанием, а два документа наконец есть.
--
-- ————— 1. Регистрационное удостоверение —————
--
-- Что было. Три строки перечня стояли со статусом on_request — «высылаем
-- после обращения». То есть сайт обещал документ, который существует
-- и который мы вышлем.
--
-- Что выяснилось. Письмо от заказчика (INFO VEDAL, 10 августа 2026):
-- «Поступила информация по РУ. Сказали, что удостоверение не выдается,
-- есть только реестровая запись».
--
-- Обещать высылку документа, который не выдаётся, — это ровно то, что
-- запрещает правило контента: «не выдумывать сертификаты и статус
-- регистрации», «недостающие данные — ожидает уточнения, а не правдоподобная
-- выдумка». Ставим pending («Уточняется»).
--
-- Почему строки не удалены совсем. Правило предписывает именно «ожидает
-- уточнения», а не молчание. Регистрационный статус — первое, что смотрит
-- закупщик медицинского оборудования; пустое место на его вопрос не отвечает,
-- а «уточняется» отвечает честно. Когда придёт номер реестровой записи,
-- строка заполняется, а не заводится заново.
--
-- ————— 2. VEDAL R2 без собственной строки —————
--
-- Изделие «VEDAL R1, R2» разделено на два, и в каталоге сегодня четыре
-- опубликованных изделия: A-2000, R1, R2, Т-100. Строка регистрации при
-- разделении досталась одному из них: product_slug перевели на vedal-r1,
-- а подпись осталась «VEDAL R1, R2». Получилось, что R2 упомянут в подписи,
-- но своей строки не имеет — и вопрос о его регистрации на странице
-- не поднимается вовсе.
--
-- Подпись приводится к изделию, на которое строка указывает, и заводится
-- отдельная строка для R2.
--
-- Строка «Описание изделия / VEDAL R1, R2» имеет ту же болезнь и здесь
-- НЕ трогается: у неё access = pdf, то есть предполагается конкретный файл,
-- и есть ли отдельный датащит у R2 — вопрос к заказчику, а не к миграции.
-- Завести строку «на всякий случай» значило бы пообещать документ.
--
-- ————— 3. Сертификат ISO 13485 —————
--
-- Стоял pending («Уточняется»). Уточнился: заказчик прислал его письмом
-- от 7 августа 2026 под именем «Сертификат соответствия». Это он и есть —
-- ГОСТ ISO 13485-2017 (ISO 13485:2016), выдан ОС СМ ООО «Приоритет»
-- 20.10.2025, действует до 20.10.2028.
--
-- Ставим on_request, а не pdf. Файл в бакет ещё не загружен, а бейдж PDF
-- обещает скачивание сразу же. Ровно на этом обожглись в V24: лицензия
-- стояла опубликованной и отдавала файл на 19 байт. Схема этого больше
-- не допустит (document_published_has_file), но бейдж соврать всё ещё может.
--
-- ————— 4. Членский билет ТПП —————
--
-- Заказчик просил показать его «вместо РУ». Показываем — но НЕ на месте
-- регистрационного удостоверения и не в группе «Лицензирование».
--
-- Членский билет торгово-промышленной палаты не имеет отношения ни
-- к регистрации изделия, ни к разрешению на его обращение: это
-- принадлежность к деловому объединению. Поставленный в группу
-- разрешительных документов, он создаёт впечатление пройденной регистрации
-- — то есть заменяет одно неверное утверждение другим, менее заметным.
--
-- Поэтому для него заводится собственная группа «О компании».

-- Группа «О компании» — членство, реквизиты, сведения об организации.
-- Проверка перечисляет группы поимённо, поэтому её надо пересоздать.
alter table document drop constraint document_doc_group_check;
alter table document add constraint document_doc_group_check
    check (doc_group in ('Лицензирование',
                         'Система качества',
                         'Техническая документация',
                         'Коммерческие материалы',
                         'О компании'));

-- 1. Регистрация: обещание высылки → «уточняется».
update document
set access = 'pending'
where title = 'Регистрационное удостоверение'
  and access <> 'pending';

-- 2. Подпись строки приводится к изделию, на которое она указывает.
update document
set subject = 'VEDAL R1'
where slug = 'registracionnoe-udostoverenie-vedal-r1-r2'
  and subject = 'VEDAL R1, R2';

-- Своя строка для R2. Идентификатор задан явно, а не gen_random_uuid():
-- миграция обязана давать одинаковый результат в каждой базе, иначе строка
-- на стенде и строка в проде — разные документы с одинаковым смыслом.
insert into document (id, slug, title, doc_group, subject, product_slug,
                      sensitivity, access, listed, published)
values ('0d5a9d3f-4c1e-4a67-9b2e-7f0c8d1a5e64',
        'registracionnoe-udostoverenie-vedal-r2',
        'Регистрационное удостоверение',
        'Лицензирование',
        'VEDAL R2',
        'vedal-r2',
        'public',
        'pending',
        true,
        false)
on conflict (slug) do nothing;

-- 3. ISO 13485: документ получен, реквизиты записаны.
--
-- revision и source_owner на сайте не показываются — это поля для тех, кто
-- работает с документом в админке. Но записать их надо здесь: пока номер
-- сертификата живёт только в письме и в чьей-то папке «Загрузки», он
-- потеряется при первой же смене ответственного.
update document
set access       = 'on_request',
    revision     = 'РОСС RU.НА83.СМК00331',
    source_owner = 'ОС СМ ООО «Приоритет», аттестат RA.RU.13НА83'
where slug = 'sertifikat-iso-13485';


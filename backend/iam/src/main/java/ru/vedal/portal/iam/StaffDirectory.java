package ru.vedal.portal.iam;

import io.swagger.v3.oas.annotations.media.Schema;

import java.util.List;

/**
 * Кто работает в портале.
 *
 * Зачем понадобился. Ответственный за заявку, клиента и сделку до сих пор
 * был свободной строкой: менеджер писал логин руками. Опечатка в ней ничем
 * не отличалась от правильного логина — сделка просто оказывалась записана
 * на человека, которого нет, и не находилась ни в одном фильтре по
 * ответственному. Ошибка тихая: отказа нет, данные есть, они неверные.
 *
 * Почему это порт, а не таблица. Провайдер идентичности мы покупаем,
 * а не пишем — так записано в брифе собственника. Сотрудники живут
 * в Keycloak, и второй список в базе портала разошёлся бы с ним на первом
 * же увольнении.
 *
 * Долгое время здесь было только чтение, и в этом файле стояло: «завести
 * человека, выдать роль и отключить при увольнении — работа консоли
 * Keycloak, и дублировать её незачем». Решение изменено 26 августа 2026
 * по просьбе владельца продукта: роли выдаются из админки.
 *
 * Изменилось ровно одно действие. Завести человека, отключить его,
 * сменить пароль, включить второй фактор — по-прежнему консоль Keycloak.
 * Порталу дана возможность менять НАБОР ПОРТАЛЬНЫХ РОЛЕЙ и ничего больше.
 *
 * Цена решения названа прямо: служебной учётной записи портала пришлось
 * выдать manage-users, а это право менять любого пользователя realm'а.
 * Взломанный портал перестаёт быть ограничен ролью, под которой вошли.
 * Против этого поставлены четыре ограничения, и держатся они здесь
 * и в SecurityConfig, а не в интерфейсе:
 *
 *   1. дверь открыта только portal-admin (SecurityConfig, правило выше
 *      справочника);
 *   2. выдаются и снимаются только роли из PORTAL_ROLES — служебные роли
 *      Keycloak порталу недоступны, хотя manage-users их и позволяет;
 *   3. свои роли менять нельзя: иначе продавец, дорвавшийся до двери,
 *      поднимает себя до администратора одним запросом;
 *   4. каждое изменение попадает в журнал.
 *
 * Две реализации выбираются свойством `vedal.iam.mode`, как и остальные
 * порты проекта: `keycloak` — настоящий realm, `local` — таблица
 * `admin_user` запасного режима.
 */
public interface StaffDirectory {

    @Schema(name = "AdminStaffMember", description = """
            Сотрудник, на которого можно записать заявку, клиента или сделку.
            """)
    record Person(
            @Schema(description = "Логин. Он же попадает в поле «ответственный».",
                    example = "editor")
            String login,

            @Schema(description = "Как показывать в списке. Пусто у учётной записи "
                    + "без имени и фамилии — тогда показывается логин.",
                    example = "Анна Фёдорова", nullable = true)
            String name,

            @Schema(description = "Отключённые остаются в списке: на них есть старые "
                    + "сделки, и прятать их значит терять историю. Новое на них "
                    + "записать нельзя.")
            boolean enabled,

            @Schema(description = "Портальные роли в том виде, в каком они записаны "
                    + "в realm'е. Пусто — человек заведён, но в портал не пущен.",
                    example = "[\"portal-sales\"]")
            List<String> roles) {

        /** Что показать в списке: имя, а если его нет — логин. */
        public String label() {
            return name == null || name.isBlank() ? login : name;
        }
    }

    /**
     * Портальные роли — те же строки, что стоят в realm'е.
     *
     * Список закрытый и лежит здесь, а не выводится из SecurityConfig:
     * там роли записаны в форме Spring (PORTAL_ADMIN), а наружу и в Keycloak
     * они уходят в форме realm'а. Держать перевод в одну сторону в одном
     * месте, а список в другом — значит однажды их развести.
     *
     * Роли realm'а, не входящие сюда, справочник не показывает вовсе:
     * у Keycloak свои служебные роли, и сотруднику они ничего не говорят.
     */
    List<String> PORTAL_ROLES = List.of("portal-admin", "portal-sales", "portal-production");

    /** Все, кого знает провайдер идентичности, по алфавиту. */
    List<Person> staff();

    /**
     * Выдать человеку РОВНО ЭТОТ набор портальных ролей.
     *
     * Набор, а не «добавь одну»: снятие роли — такое же обычное действие,
     * как выдача, и разводить их на две двери значит получить третье
     * состояние — «добавили, снять забыли». Что прислали, то и стало.
     *
     * Роли вне PORTAL_ROLES отвергаются. Проверку делает реализация,
     * а не вызывающий: порт обещает, что чужой ролью через него
     * не распорядиться, и обещание должно держаться независимо от того,
     * кто его позовёт завтра.
     *
     * @throws Rejected если в наборе роль не из PORTAL_ROLES, логин неизвестен
     *                  или провайдер ролями не управляет
     */
    void assignRoles(String login, List<String> roles);

    /**
     * Отказ, который надо сказать человеку словами.
     *
     * Своё исключение, а не ConflictException из common: модуль iam от него
     * не зависит, и тащить сюда общий модуль ради одного класса значит
     * связать провайдера входа со всем остальным приложением. Переводит
     * его в 409 та дверь, которая порт зовёт.
     */
    class Rejected extends RuntimeException {
        public Rejected(String message) {
            super(message);
        }
    }
}

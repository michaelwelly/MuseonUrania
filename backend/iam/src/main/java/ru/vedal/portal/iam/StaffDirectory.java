package ru.vedal.portal.iam;

import io.swagger.v3.oas.annotations.media.Schema;

import java.util.List;

/**
 * Кто работает в портале.
 *
 * Зачем понадобился. Ответственный за заявку, клиента и сделку до сих пор
 * был свободной строкой: менеджер писал логин руками. Опечатка в ней ничем
 * не отличалась от правильного логина — сделка просто оказывалась записана
 * на человека, которого нет, и не находилась ни в одном фильтре по
 * ответственному. Ошибка тихая: отказа нет, данные есть, они неверные.
 *
 * Почему это порт, а не таблица. Провайдер идентичности мы покупаем,
 * а не пишем — так записано в брифе собственника. Сотрудники живут
 * в Keycloak, и второй список в базе портала разошёлся бы с ним на первом
 * же увольнении. Здесь только чтение: завести человека, выдать роль
 * и отключить при увольнении — работа консоли Keycloak, и дублировать
 * её незачем.
 *
 * Две реализации выбираются свойством `vedal.iam.mode`, как и остальные
 * порты проекта: `keycloak` — настоящий realm, `local` — таблица
 * `admin_user` запасного режима.
 */
public interface StaffDirectory {

    @Schema(name = "AdminStaffMember", description = """
            Сотрудник, на которого можно записать заявку, клиента или сделку.
            """)
    record Person(
            @Schema(description = "Логин. Он же попадает в поле «ответственный».",
                    example = "editor")
            String login,

            @Schema(description = "Как показывать в списке. Пусто у учётной записи "
                    + "без имени и фамилии — тогда показывается логин.",
                    example = "Анна Фёдорова", nullable = true)
            String name,

            @Schema(description = "Отключённые остаются в списке: на них есть старые "
                    + "сделки, и прятать их значит терять историю. Новое на них "
                    + "записать нельзя.")
            boolean enabled) {

        /** Что показать в списке: имя, а если его нет — логин. */
        public String label() {
            return name == null || name.isBlank() ? login : name;
        }
    }

    /** Все, кого знает провайдер идентичности, по алфавиту. */
    List<Person> staff();
}

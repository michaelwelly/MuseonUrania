// Заказчик прислал семнадцать фигур (архив «Анимация картинок для сайта»,
// 9 сентября 2026) — фрагменты, вырезанные из печатной брошюры и обведённые
// в вектор автоматически. Силуэты правильные, а контур в них идёт ступеньками
// по одному-двум пунктам: след растра, из которого их обводили. На мелких
// формах это незаметно, на крупных край выглядит бугристым — скруглённый угол
// распадается на цепочку горбиков.
//
// Сглаживать присланные пути напрямую бесполезно, и это стоит записать, чтобы
// не пробовать снова: срезание углов убирает ступеньки вместе с самой формой —
// квадраты становятся подушками, ветки амёбами. Мелкая сетка тоже не спасает:
// на ней ступенька просто мельчает и превращается в рябь по краю.
//
// Взято другое. В брошюре фигуры сложены из квадратов: все стороны прямые,
// все углы скруглены. Значит, в присланном контуре нужны только длинные
// стороны — они и есть стороны квадратов, — а всё короткое между ними шум.
// Углы восстанавливаются пересечением соседних длинных сторон и скругляются
// дугой: наружные наружу, внутренние внутрь.
//
// Радиус у каждого угла свой, и это здесь главное. По краю фигуры углы
// срезаны скупо, а внутренние сгибы, которыми квадраты переходят друг
// в друга, выведены широкой дугой — у большой ветки в тридцать с лишним
// пунктов против девяти по краю. Одна цифра на всю фигуру рвёт как раз эти
// переходы: ветка рассыпается на квадраты с белым волоском между ними.
// Замерить радиус можно по самой обводке — насколько стороны не доходят
// до своего пересечения.
//
// Пути лежат здесь, а не файлами в public, потому что поле собирается
// из полутора десятков фигур сразу: столько же файлов означало бы столько же

// Переводы содержательных текстов. Заполняет заказчик, не разработчик.
//
// Формат — `"русский оригинал": "перевод"`. Ключ это в точности та строка,
// что стоит в `content/*.ts` или приходит от портала; совпадение проверяется
// целиком, без нормализации пробелов. Разбор — в `lib/content-i18n.ts`,
// там же написано, почему ключ именно такой.
//
// ───────────────────────────────────────────────────────────────────────────
// Что сюда класть можно, а что нельзя
//
// Нельзя: перевод, сделанный переводчиком-машиной или разработчиком «чтобы
// было». Описание изделия, характеристика, статус регистрации, срок поставки
// и любое утверждение о клинических свойствах проходят то же согласование,
// что и русский текст. До согласования строки здесь нет, и страница
// показывает русский оригинал — это верное поведение, а не недоделка.
//
// Можно: текст, пришедший от заказчика или от его переводчика и прошедший
// согласование. Одна строка на один абзац.
//
// ───────────────────────────────────────────────────────────────────────────
// Почему словари пусты
//
// Потому что переводов ещё нет. Задача #54 отмечает это отдельной строкой —
// «Зависит от заказчика: переводы описаний, характеристик и документов».
// Механика собрана и работает: как только первая строка появится здесь,
// она появится и на странице, без правки кода.


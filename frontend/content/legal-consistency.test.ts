import { describe, expect, it } from "vitest";

import { contactsNotice } from "./contacts";
import { consent, privacy } from "./legal";
import { footer } from "./site";

// Политика обработки персональных данных опубликована 9 сентября 2026.
//
// До этого дня сайт в трёх местах обещал, что документ «готовится»: во врезке
// под формой на контактах, в примечании под подпиской в подвале и на самой
// странице политики. Публикация — одна правка в одном файле, а обещания
// живут в трёх других, и после неё сайт полдня спорил сам с собой: страница
// показывала готовый документ, а врезка рядом с формой отправляла человека
// ждать его. Причём ровно там, где человек решает, отдавать ли свои данные.
//
// Ошибка тихая: каждый текст по отдельности читается складно, увидеть
// расхождение можно только держа их рядом. Тест и держит их рядом.

const ОБЕЩАНИЯ = [
  "ожидает уточнения",
  "готовится",
  "будет опубликован",
  "до её публикации",
  "до его публикации",
  "после согласования",
];

/** Тексты, которые видит посетитель рядом с решением отдать свои данные. */
const ТЕКСТЫ: readonly [string, string][] = [
  ["врезка на контактах", contactsNotice.text],
  ["подпись согласия под формой", consent.note],
  ["примечание под подпиской в подвале", footer.subscribe.note],
  ["лид страницы политики", privacy.lead],
];

describe("сайт не обещает политику, которая уже опубликована", () => {
  for (const [где, текст] of ТЕКСТЫ) {
    it(где, () => {
      for (const обещание of ОБЕЩАНИЯ) {
        expect(текст.toLowerCase(), `«${обещание}» в тексте: ${текст}`).not.toContain(обещание);
      }
    });
  }
});

describe("путь к документу", () => {
  it("врезка на контактах ведёт туда же, куда подпись под формой", () => {
    // Два адреса на один документ разъезжаются молча: один поправят,
    // второй останется вести на страницу, которой уже нет.
    expect(contactsNotice.link.href).toBe(consent.href);
  });

  it("адрес — страница политики, а не корень раздела", () => {
    expect(consent.href).toBe("/legal/privacy/");
  });
});

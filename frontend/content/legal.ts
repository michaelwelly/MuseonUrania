//
// Здесь намеренно НЕТ текста самой политики. §14.7 плана требует, чтобы
// финальную редакцию проверил юрист или ответственный у заказчика, а §14.3 —
// чтобы её не копировали дословно с сайта Уральской ТПП, взятого за референс.
// Черновик по этому референсу готовит Михаил (§15).
//
// Страница существует, потому что §14.1 требует ссылку на политику в конце
// каждой страницы сайта, а ссылка обязана куда-то вести. Пустая заглушка
// или ссылка в никуда хуже, чем честная страница со статусом: посетитель,
// который ищет политику, должен увидеть, на каком она этапе и куда написать.
//
// На странице только то, что подтверждено: реквизиты оператора с бланка
// (docs/products/README.md) и фактическое поведение форм — проверенное по
// коду и по базе, а не по замыслу.
//
// Здесь до 19 августа стояло «формы сайта не отправляют персональные данные
// на сервер». Это было неправдой: submitLead шлёт POST /api/forms/v1/leads
// всегда, когда настроен адрес API, заявки лежат в таблице lead вместе
// с именем, телефоном, почтой и отметкой согласия. Текст написали до того,
// как формы подключили, и он пережил подключение.
//
// Хуже места для устаревшего утверждения не придумать: страница о защите
// персональных данных сообщала посетителю, что его данные никуда не уходят,
// пока они уходили. Правило «не выдумывать» относится и к утверждениям
// о самих себе.


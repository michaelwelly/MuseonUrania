// §14.5 плана: короткий текст про cookie, ссылка на политику, кнопка согласия.
//
// Текстов три, и выбирает между ними не редактор, а то, что на площадке
// действительно есть: счётчик Метрики (`NEXT_PUBLIC_YANDEX_METRIKA_ID`)
// и встроенная карта на контактах (`lib/maps.ts`). Есть оба — текст про
// оба, есть одна карта — текст про карту, нет ничего — спрашивать не о чем
// и выбор был бы бутафорией.
//
// Написать один текст «мы используем аналитику» на все случаи нельзя:
// на площадке без счётчика это неправда, а плашка про персональные данные —
// последнее место, где уместна формулировка «на всякий случай». По той же
// причине карта названа отдельной строкой, а не подразумевается словом
// «сервисы»: согласие на то, чего человеку не назвали, согласием не является.
//
// ————— почему два ответа, а не один —————
//
// Cookie самого сайта отклонить нельзя: без них не работают страницы,
// и «отклонить» означало бы «уйти». Метрику и карту отклонить можно: сайт
// без них работает целиком — у карты на месте кадра остаются адрес и ссылка
// «Построить маршрут», — а данные посетителя при них уезжают третьей стороне.
// Поэтому кнопка «Только необходимые» появляется вместе со сторонним ресурсом
// и вместе с ним исчезает.

const fallback =
  "Принял. Передам вопрос профильному специалисту VEDAL и вернусь с ответом в этом окне.";

/**
 * Ответ в режиме вёрстки, когда портал не поднят.
 *
 * Не заглушка «до появления API» — API есть с тех пор, как заведён модуль
 * ассистента, и на живом сайте отвечает он. Здесь остаётся ровно один
 * случай: страница собрана без адреса портала, и чат обязан хотя бы
 * открываться.
 */
export function answerFor(question: string): string {
  return answers[question.trim()] ?? fallback;
}

/** Какая доля коробки фигуры попадает внутрь поля. */
function доляВКадре(
  p: { x: number; y: number; w: number; h: number },
  width: number,
  height: number,
) {
  const пх = Math.max(0, Math.min(p.x + p.w, width) - Math.max(p.x, 0));
  const пу = Math.max(0, Math.min(p.y + p.h, height) - Math.max(p.y, 0));
  return (пх * пу) / (p.w * p.h);
}

describe("крупный узор", () => {
  it.each(ПОЛЯ)("$где: все семнадцать форм, каждая по разу", ({ опции }) => {
    const поле = buildField(опции);
    const формы = поле.map((p) => p.id);

    expect(формы).toHaveLength(Object.keys(SHAPES).length);
    expect(new Set(формы).size).toBe(формы.length);
  });

  it.each(ПОЛЯ)("$где: ни одной формы за кадром целиком", ({ опции }) => {
    const поле = buildField(опции);
    const запределом = поле
      .filter((p) => доляВКадре(p, опции.width, опции.height) === 0)
      .map((p) => p.id);

    // Форма имеет право уйти за обрез — так она и читается продолжением
    // большого поля. Не имеет права уйти целиком: место в наборе занято,
    // а на экране её нет.
    expect(запределом).toEqual([]);
  });

  it.each(ПОЛЯ)("$где: акценты не заходят в зоны текста", ({ опции }) => {
    const поле = buildField(опции);
    const зоны = опции.keepClear ?? [];
    const нарушители = поле
      .filter((p) => p.ink === "accent")
      .filter((p) =>
        зоны.some(
          (z) =>
            p.x < z.x2 && p.x + p.w > (z.x1 ?? -Infinity) && p.y + p.h > z.y1 && p.y < z.y2,
        ),
      )
      .map((p) => p.id);

    expect(нарушители).toEqual([]);
  });

  // Зерно в крупной раскладке не участвует, и это не оплошность, а следствие
  // приёма: заказчик хочет видеть все семнадцать форм без повторов, поэтому
  // место, размер и поворот назначены каждой поимённо, а случайности
  // в назначении нет вовсе.
  //
  // Тест закрепляет это письменно, чтобы никто не рассчитывал на обратное:
  // разные места сайта различаются размером поля и запретными зонами,
  // а не зерном. Понадобится различать их ещё и зерном — придётся менять
  // саму раскладку, и этот тест упадёт первым.
  it("при крупности от двойки не зависит от зерна", () => {
    const одно = buildField({ width: 1400, height: 330, seed: 1, boldness: 3 });
    const другое = buildField({ width: 1400, height: 330, seed: 999_999, boldness: 3 });

    expect(другое).toEqual(одно);
  });

  it("мелкое поле от зерна зависит", () => {
    const одно = buildField({ width: 900, height: 700, seed: 1 });
    const другое = buildField({ width: 900, height: 700, seed: 999_999 });

    expect(другое).not.toEqual(одно);
  });
});

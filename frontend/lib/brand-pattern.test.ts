// Раскладка крупного узора.
//
// Проверяется то, что ломается молча. Узор — фон: если из семнадцати форм
// встанут шестнадцать или одна уедет целиком за кадр, на экране это выглядит
// ровно так же, как задуманное поле, — «вроде бы фигуры, вроде бы стоят».
// Заметить разницу глазами нельзя, её видно только числом.
//
// Именно это и случилось на «Производстве»: коридор под текст шириной 620
// запирал мелкий акцент между собой и крупной веткой справа, тот не находил
// себе места ни в одном кольце обхода и не рисовался вовсе. Поле выглядело
// нормальным, в нём было шестнадцать форм.


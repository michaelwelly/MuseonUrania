import { DEFAULT_LANG, isLang, localePath, preferredLang, type Lang } from "@/lib/i18n";

// Память о выборе языка и автоопределение по браузеру.
//
// Чистые функции, отдельно от компонента: решение «куда вести посетителя»
// проверяется тестом, а не глазами на живом сайте, где ошибка выглядит
// как бесконечный редирект.
//
// ───────────────────────────────────────────────────────────────────────────
// Почему не middleware
//
// Заказчик просил подхватывать язык из браузера. Прямой способ — middleware
// Next, читающий `Accept-Language` и отвечающий редиректом. Он ломает
// свойство №1 архитектуры (`docs/PROJECT.md`, 5.3): «падение бэкенда не
// роняет сайт» — страницы уезжают в статику на сборке и отдаются готовыми,
// а middleware ставит серверный шаг перед каждым запросом к каждой странице.
// Ради определения языка мы бы завели зависимость от живого сервера у всего
// сайта целиком.
//
// Поэтому автоопределение живёт в браузере и работает только на русских
// адресах — на тех, где язык не назван явно. Поисковик, не выполняющий
// скрипты, видит русскую страницу и `hreflang` рядом; он и так умеет
// выбирать версию по языку запроса.
//
// ───────────────────────────────────────────────────────────────────────────
// Правило старшинства
//
//   выбор человека > адрес с префиксом > язык браузера > русский
//
// Выбор человека сильнее автоопределения — иначе посетитель, переключившийся
// на русский, получал бы английский на каждой новой странице.

export const LANG_STORAGE_KEY = "vedal.lang";

export type LangDecision =
  /** Ничего не делаем: язык страницы уже верный. */
  | { kind: "stay" }
  /** Запомнить язык: посетитель открыл адрес с префиксом, это явный выбор. */
  | { kind: "remember"; lang: Lang }
  /** Увести на другой язык. */
  | { kind: "go"; lang: Lang; href: string };

/**
 * Что делать при открытии страницы.
 *
 * @param pageLang язык открытой страницы
 * @param path путь без языкового префикса, например `/products/`
 * @param stored ранее сохранённый выбор или `null`
 * @param accepted `navigator.languages`
 */
export function decideLang(
  pageLang: Lang,
  path: string,
  stored: string | null,
  accepted: readonly string[],
): LangDecision {
  // Адрес с префиксом — это явное требование языка. Никуда не уводим:
  // увести отсюда значило бы спорить с тем, что человек только что набрал
  // или получил ссылкой. Заодно запоминаем — следующий заход на корень
  // откроется на том же языке.
  if (pageLang !== DEFAULT_LANG) {
    return stored === pageLang ? { kind: "stay" } : { kind: "remember", lang: pageLang };
  }

  // Дальше — только русские адреса, то есть те, где язык не назван.

  if (stored !== null) {
    // Сохранённый русский — это тоже выбор, и он выключает автоопределение.
    if (!isLang(stored) || stored === DEFAULT_LANG) return { kind: "stay" };
    return { kind: "go", lang: stored, href: localePath(stored, path) };
  }

  const wanted = preferredLang(accepted);
  if (wanted === null || wanted === DEFAULT_LANG) return { kind: "stay" };
  // Автоопределение намеренно не пишет выбор в хранилище: иначе оно
  // становится неотличимо от решения человека, и нажатие «Русский»
  // пришлось бы отменять дважды.
  return { kind: "go", lang: wanted, href: localePath(wanted, path) };
}

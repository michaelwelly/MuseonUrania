import type { Metadata } from "next";

// Метаданные для поисковиков и мессенджеров.
//
// Зачем это отдельным модулем, а не полем в каждой странице. Canonical и
// Open Graph — это девять почти одинаковых блоков по десять строк, и
// разъезжаются они молча: забытый siteName или og:url с чужим адресом
// не ломают ни сборку, ни страницу, их видно только в чужой ленте.

const trim = (value: string | undefined) => (value ?? "").replace(/\/+$/, "");

/**
 * Адрес сайта наружу.
 *
 * Отдельная переменная, а не NEXT_PUBLIC_API_URL, хотя сегодня значение
 * то же самое: сайт и API стоят за одним шлюзом. Поэтому API и служит
 * запасным значением — задавать две переменные с одинаковым содержимым
 * незачем. Но в день, когда API переедет на отдельный поддомен, canonical
 * обязан остаться на сайте, и разъедутся они без правки кода.
 *
 * Пусто — режим вёрстки без бэкенда. Тогда canonical и og:url остаются
 * относительными: подставить сюда localhost значило бы выкатить его
 * в разметку и увести поисковик на несуществующий адрес.
 */
export const siteUrl = trim(process.env.NEXT_PUBLIC_SITE_URL) || trim(process.env.NEXT_PUBLIC_API_URL);

/**
 * Боевой адрес — и только он.
 *
 * В отличие от {@link siteUrl}, к API не откатывается, и это главное:
 * поисковику нечего делать на стенде. Стенд отвечает по адресу-числу,
 * содержимое там черновое и неутверждённое, а Яндекс с Google найдут
 * его сами — по ссылке из переписки, по счётчику, по чему угодно.
 * Проиндексированный стенд потом соперничает с настоящим сайтом
 * за ту же выдачу и показывает клиенту незаконченные тексты.
 *
 * Поэтому карта сайта и robots.txt смотрят сюда: пока переменная пуста —
 * а на стенде и на машине разработчика она пуста, — индексирование
 * закрыто целиком, и карта не выдаётся вовсе.
 */
export const publicSite = trim(process.env.NEXT_PUBLIC_SITE_URL);

/**
 * Карточка ссылки — то, что видит человек, когда ссылку на сайт кидают
 * в мессенджер или соцсеть.
 *
 * Раньше здесь стояло квадратное дерево 512×512 и тип карточки `summary`:
 * своей карточки 1200×630 у сайта не было, а рисовать её «на глаз» —
 * работа заказчика, не вёрстки. Теперь карточка есть и собрана из того,
 * что у сайта уже своё: знак, фирменный узор и первая строка главной.
 * Ничего нового не выдумано.
 *
 * Пересобирается скриптом `scripts/build-og-cover.mjs` — он читает формы
 * узора из того же файла, что и сайт, поэтому карточка не разойдётся
 * с тем, что видно на страницах. Меняется текст главной — пересобирается
 * и она.
 *
 * Адрес абсолютный, когда база известна: соцсеть и мессенджер тянут
 * картинку со своей стороны, и относительный путь им не разрешить.
 * База пуста только в вёрстке без бэкенда — там разрешать некому,
 * и путь остаётся относительным, как у canonical рядом.
 */
/**
 * Метка версии в адресе картинки.
 *
 * Мессенджер и соцсеть кладут карточку в кэш по её адресу и держат там
 * неделями: пока адрес прежний, они не пойдут за файлом заново, даже если
 * на сервере он давно другой. Ссылку на сайт кидали ещё до того, как
 * карточка появилась, — и у всех, кто её тогда открывал, в кэше лежит
 * пустота. Меняем метку — меняется адрес, и кэш промахивается.
 *
 * Правило простое: перерисовали og-cover.png — подняли метку.
 */
const версияКарточки = "2";

const defaultImage = {
  url: `${siteUrl ?? ""}/brand/og-cover.png?v=${версияКарточки}`,
  width: 1200,
  height: 630,
  type: "image/png",
  alt: "VEDAL — медицинское оборудование, сделанное в России",
};

type PageSeo = {
  title: string;
  description: string;
  /**
   * Путь страницы со слэшем на конце: `/products/`.
   *
   * В next.config стоит trailingSlash, и адрес без слеша отдаёт 308.
   */
  path: string;
  /** Своя картинка страницы — снимок изделия или новости. */
  image?: { url: string; alt: string };
  type?: "website" | "article";
  publishedTime?: string;
};

export function pageMetadata({
  title,
  description,
  path,
  image,
  type = "website",
  publishedTime,
}: PageSeo): Metadata {
  const picture = image ? [{ url: image.url, alt: image.alt }] : [defaultImage];
  return {
    title,
    description,
    // Сайт доступен по нескольким адресам сразу: локально, по адресу стенда
    // и, позже, по домену. Без canonical это для поисковика три разных сайта
    // с одинаковым содержимым.
    //
    // `languages` (hreflang) здесь нет: сайт одноязычный, версий одной
    // страницы на разных языках не существует, и объявлять их поисковику
    // значило бы обещать адреса, которые отвечают редиректом на корень.
    alternates: { canonical: path },
    openGraph: {
      type,
      title,
      description,
      url: path,
      siteName: "VEDAL",
      locale: "ru_RU",
      images: picture,
      ...(publishedTime ? { publishedTime } : {}),
    },
    twitter: {
      // Обе картинки широкие: и снимок изделия, и карточка сайта.
      // Прежний `summary` достался квадратному дереву, которого здесь
      // больше нет.
      card: "summary_large_image",
      title,
      description,
      images: picture,
    },
  };
}

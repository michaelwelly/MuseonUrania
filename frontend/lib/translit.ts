// Адрес страницы из заголовка.
//
// Адрес — часть контракта: он уходит в ссылки, в поисковую выдачу и в ключ
// файла обложки. Набирать его руками латиницей означает делать это по разу
// на каждый материал и ошибаться в трети случаев — то заглавная буква,
// то пробел, то русская «с» вместо латинской.
//
// Правило перевода — практическое, а не ГОСТ: ГОСТ 7.79 даёт «shh» для «щ»
// и «`» для мягкого знака, и адрес получается нечитаемым. Здесь тот же набор,
// которым набраны существующие адреса каталога: `vedal-r1`, `hall-booklet`.
//
// Мягкий и твёрдый знаки пропадают, а не превращаются в апостроф: апостроф
// в адресе требует экранирования в половине мест, где адрес встречается.

const БУКВЫ: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh",
  з: "z", и: "i", й: "y", к: "k", л: "l", м: "m", н: "n", о: "o",
  п: "p", р: "r", с: "s", т: "t", у: "u", ф: "f", х: "h", ц: "c",
  ч: "ch", ш: "sh", щ: "sch", ъ: "", ы: "y", ь: "", э: "e",
  ю: "yu", я: "ya",
};

/**
 * Адрес из строки: латиница в нижнем регистре, цифры и дефис.
 *
 * Требование портала — `^[a-z0-9]+(?:-[a-z0-9]+)*$`, и функция обязана
 * ему удовлетворять на любом входе, включая заголовок из одних кавычек:
 * пустая строка допустима, а строка с ведущим дефисом — уже нет.
 */
export function slugify(text: string): string {
  const латиница = [...text.toLowerCase()]
    .map((знак) => {
      if (знак in БУКВЫ) return БУКВЫ[знак];
      // Латинские буквы и цифры остаются, всё прочее становится дефисом:
      // пробелы, кавычки, длинное тире, знаки препинания.
      return /[a-z0-9]/.test(знак) ? знак : "-";
    })
    .join("");

  // Дефисы схлопываются и обрезаются по краям: «Ведал R1 — обзор» иначе
  // даёт «vedal-r1----obzor», а «„Ведал“» — «-vedal-».
  return латиница.replace(/-+/g, "-").replace(/^-|-$/g, "");
}

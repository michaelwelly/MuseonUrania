import { describe, expect, it } from "vitest";
import { slugify } from "./translit";

// Адрес страницы собирается из заголовка автоматически, и ошибка здесь
// не видна до публикации: портал отвечает отказом по шаблону
// `^[a-z0-9]+(?:-[a-z0-9]+)*$`, а редактор к этому моменту уже написал
// материал и не понимает, при чём тут адрес.
//
// Функция обязана удовлетворять шаблону на любом входе — заголовки пишут
// люди, и кавычки, тире и двойные пробелы в них обычное дело.

const ШАБЛОН = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

describe("адрес из заголовка", () => {
  it("переводит кириллицу", () => {
    expect(slugify("Новый инкубатор")).toBe("novyy-inkubator");
  });

  it("не оставляет ведущих и хвостовых дефисов", () => {
    // «„Ведал“» дал бы «-vedal-», а такой адрес портал не примет.
    expect(slugify("«Ведал» — обзор")).toBe("vedal-obzor");
    expect(slugify("  Пробел  ")).toBe("probel");
  });

  it("схлопывает подряд идущие разделители", () => {
    expect(slugify("Ведал R1 — обзор")).toBe("vedal-r1-obzor");
  });

  it("сохраняет латиницу и цифры как есть", () => {
    expect(slugify("VEDAL R2 2026")).toBe("vedal-r2-2026");
  });

  it("выбрасывает мягкий и твёрдый знаки, а не превращает в апостроф", () => {
    // Апостроф в адресе требует экранирования в половине мест,
    // где адрес встречается.
    expect(slugify("Медаль подъезда")).toBe("medal-podezda");
  });

  it("из заголовка без букв даёт пустоту, а не строку из дефисов", () => {
    // Пустой адрес форма покажет пустым и попросит набрать; «---» уехал бы
    // на портал и получил отказ по шаблону.
    expect(slugify("«…» —")).toBe("");
  });

  it("что бы ни пришло, результат подходит порталу", () => {
    const заголовки = [
      "Новый инкубатор",
      "«Ведал» — обзор",
      "VEDAL R2 2026",
      "Ёлка, ёж и щука",
      "  двойные   пробелы  ",
      "Съезд подъёмников",
    ];

    for (const заголовок of заголовки) {
      const адрес = slugify(заголовок);
      expect(адрес, заголовок).toMatch(ШАБЛОН);
    }
  });
});

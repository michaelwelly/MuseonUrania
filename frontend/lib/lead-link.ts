import type { LeadForm } from "@/lib/submit";

// Ссылка на форму обращения с заранее выбранной темой. Одна на весь сайт.
//
// ───────────────────────────────────────────────────────────────────────────
// Зачем
//
// Кнопка «Запросить КП», «Запросить документ» или «Запросить подбор» вела
// на `/contacts/`. Человек попадал на верх страницы, сам искал форму внизу
// и сам вспоминал, что выбрать в списке тем, — то есть делал руками ровно
// ту работу, ради которой нажал кнопку. Промахнуться в этом списке нечем
// помешать: заявка уезжает не под той темой, и видно это только менеджеру
// в админке, уже после.
//
// ───────────────────────────────────────────────────────────────────────────
// Почему параметр адреса, а не якорь и не всплывающее окно
//
// Якорь `#quote` умеет только «привести к форме», но не «выбрать в ней
// тему»: хеш один, а тем пять, и заводить пять якорей на одну форму значит
// хранить соответствие «якорь → тема» вторым списком рядом с первым.
// Параметр несёт значение, и это значение — тот же код, что уедет в Forms
// API (`quote | catalog | consultation | service | partner`): между ссылкой
// и телом запроса нет перевода, который мог бы разойтись.
//
// Всплывающее окно отпадает по причине из карточки изделия: оно требует
// ловушки фокуса, блокировки прокрутки и своего поведения на «назад»,
// и ссылкой на него не поделишься.
//
// Якорь при этом остаётся — вторым слагаемым, а не заменой: параметр
// выбирает тему, хеш приводит глаз к самой форме.
//
// ───────────────────────────────────────────────────────────────────────────
// Чего это НЕ меняет
//
// Страница остаётся статической. Параметр читается в браузере из
// `window.location`, а не через `useSearchParams`: последний переводит всю
// страницу на отрисовку по запросу, а статика здесь — свойство архитектуры,
// сайт обязан открываться при упавшем бэкенде (та же причина у
// `components/Analytics.tsx`).

/** Страница с общей формой обращения. */
const CONTACTS = "/contacts/";

/**
 * Якорь блока с формой на странице контактов.
 *
 * Без него кнопка приводит на верх страницы, и форму человек ищет сам —
 * то самое, от чего кнопка должна избавлять.
 */
export const LEAD_ANCHOR = "lead";

/** Имена параметров. Набранные строкой по местам, они разъехались бы молча. */
export const TOPIC_PARAM = "topic";
export const PRODUCT_PARAM = "product";

/**
 * Коды тем. Тот же список, что в `LeadForm` и в спеке Forms API.
 *
 * Он нужен отдельным значением, а не только типом: тип проверяется на
 * сборке, а сюда значение приходит из адресной строки — то есть от
 * постороннего, — и проверять его надо во время работы.
 */
const TOPICS: readonly LeadForm[] = ["quote", "catalog", "consultation", "service", "partner"];

/**
 * Форма сервисного обращения. Она стоит на своей странице, и тема на ней
 * задана самой страницей — параметр не нужен, нужен только якорь: без него
 * кнопка «Сервисная заявка» приводит на верх «Сервиса», где формы ещё
 * не видно.
 */
export const SERVICE_HREF = `/service/#${LEAD_ANCHOR}`;

/**
 * Тема, под которой уезжает запрос документа.
 *
 * Отдельного кода «документ» в Forms API нет, и выдумать его здесь нельзя:
 * бэкенд принимает ровно пять значений. Из пяти запросу документа
 * соответствует `catalog` — «Запрос каталога», тема, под которой просят
 * материалы, а не цену, подбор или выезд инженера. Сам каталог продукции
 * тоже строка перечня документов, из «Коммерческих материалов».
 *
 * Названо константой, а не набрано по местам: подпись темы решает
 * заказчик (`content/contacts.ts`), и если под документы заведут отдельную,
 * менять придётся одно место, а не четыре кнопки на трёх страницах.
 */
export const DOCUMENT_TOPIC: LeadForm = "catalog";

/** Код темы, пришедший снаружи, — из тех, что бэкенд примет. */
export const isTopic = (value: string | null | undefined): value is LeadForm =>
  typeof value === "string" && (TOPICS as readonly string[]).includes(value);

/**
 * Адрес формы с выбранной темой и, если запрос про конкретное изделие,
 * с подставленным изделием.
 *
 * Слаг изделия сюда попадает только тот, что уже известен странице
 * (перечень документов, карточка). Форма всё равно сверит его со своим
 * списком: адрес — не источник истины о каталоге.
 */
export function leadHref(topic: LeadForm, product?: string | null): string {
  const params = new URLSearchParams({ [TOPIC_PARAM]: topic });
  if (product) params.set(PRODUCT_PARAM, product);
  return `${CONTACTS}?${params}#${LEAD_ANCHOR}`;
}

/**
 * Тема из адреса. Неизвестная и отсутствующая — одинаково `null`.
 *
 * Ошибки здесь нет намеренно: адрес приходит из чужой ссылки, старой
 * закладки или опечатки, и форма, отказавшаяся открыться из-за буквы
 * в адресе, хуже формы с темой по умолчанию.
 */
export function readTopic(search: string): LeadForm | null {
  const asked = new URLSearchParams(search).get(TOPIC_PARAM);
  return isTopic(asked) ? asked : null;
}

/**
 * Слаг изделия из адреса. Существует ли такое изделие — решает не здесь:
 * каталог знает форма, а этот модуль знает только про адрес.
 */
export function readProduct(search: string): string | null {
  const asked = new URLSearchParams(search).get(PRODUCT_PARAM)?.trim();
  return asked ? asked : null;
}

import { DEFAULT_LANG, type Lang } from "@/lib/i18n";
import { contentTranslations } from "@/content/translations";

// Содержательный текст: описания изделий, юридические формулировки, статусы
// регистрации, тексты страниц. Отдельно от интерфейса — и это не выдумка
// разработчика, а условие задачи (GitHub issue #54):
//
//     «Переводы интерфейса отдельно от переводов контента: интерфейс
//      переводим мы, контент — заказчик.»
//
// ───────────────────────────────────────────────────────────────────────────
// Чего здесь нет и не будет: машинного перевода
//
// Правила контента (CLAUDE.md) запрещают выдумывать характеристики,
// сертификаты, статус регистрации, сроки и клинические заявления. Перевод
// такой формулировки — это её новая редакция: «регистрационное
// удостоверение» и «registration certificate» юридически не одно и то же,
// а «ожидает уточнения», переведённое как «pending», читается как
// «оформляется», то есть как обещание.
//
// Поэтому непереведённое показывается по-русски. Не пустым местом,
// не «coming soon» и не машинным пересказом: русским оригиналом,
// помеченным `lang="ru"`, чтобы браузер, скринридер и встроенный
// переводчик знали, на каком языке этот кусок написан.
//
// ───────────────────────────────────────────────────────────────────────────
// Почему ключ — сам русский текст
//
// Словарь переводов — это `{ русский оригинал: перевод }`, без придуманных
// идентификаторов. Причина не в лени: идентификатор разъезжается молча.
// Заказчик правит русскую формулировку, ключ остаётся прежним, и старый
// перевод продолжает показываться — то есть на английской странице висит
// снятое с публикации утверждение.
//
// Ключ-оригинал закрывает это по устройству: изменился русский текст —
// перевода к нему нет, страница показывает новый русский. Обновление
// перевода становится видимым действием, а не тем, о чём забыли.

/** Словарь одного языка: русский оригинал → согласованный перевод. */
export type ContentDictionary = Readonly<Record<string, string>>;

/** Что показываем и на каком языке это написано. */
export type Said = {
  text: string;
  /** `undefined`, если текст на языке страницы; `"ru"` — если это оригинал. */
  lang: "ru" | undefined;
};

/**
 * Переводчик содержательного текста для одной страницы.
 *
 * Возвращает две функции, потому что у строки две судьбы. `t` идёт в текст
 * и в атрибуты (`alt`, `placeholder`), `mark` — в атрибут `lang` элемента,
 * который эту строку содержит.
 */
export function contentText(lang: Lang) {
  // У русского словаря нет и быть не может: он и есть оригинал.
  const dictionary: ContentDictionary =
    lang === DEFAULT_LANG ? {} : (contentTranslations[lang] ?? {});

  const say = (ru: string): Said => {
    if (lang === DEFAULT_LANG) return { text: ru, lang: undefined };
    const translated = dictionary[ru];
    return translated ? { text: translated, lang: undefined } : { text: ru, lang: "ru" };
  };

  return {
    /** Текст: перевод, если он согласован, иначе русский оригинал. */
    t: (ru: string): string => say(ru).text,

    /**
     * Значение атрибута `lang` для элемента с этим текстом.
     *
     * Несколько строк в одном элементе — передайте их все: элемент помечается
     * русским, если хоть одна из них осталась оригиналом.
     */
    mark: (...ru: string[]): "ru" | undefined =>
      ru.some((line) => say(line).lang === "ru") ? "ru" : undefined,

    /** Есть ли на странице хоть один непереведённый кусок — для примечания. */
    anyOriginal: (...ru: string[]): boolean => ru.some((line) => say(line).lang === "ru"),

    /** Язык страницы — чтобы не тащить его вторым аргументом. */
    lang,
  };
}

export type ContentText = ReturnType<typeof contentText>;

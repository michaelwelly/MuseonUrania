// Встроенная карта Яндекса на странице контактов. GitHub issue #74.
//
// ————— почему константа, а не переменная окружения —————
//
// Счётчик Метрики — свойство площадки: у боевого сайта свой номер, у стенда
// его быть не должно вовсе. Карта — свойство кода: ключа виджету не нужно,
// адрес собирается из адреса производства, и на всех трёх площадках он один
// и тот же. Разные вещи настраиваются по-разному, и заводить карте
// переменную окружения значило бы требовать её заполнения там, где выбора
// нет.
//
// Снять карту с сайта — правка одной этой строки. Вместе с картой исчезнет
// и вопрос в плашке про cookie: спрашивать станет не о чем, и плашка
// вернётся к тому, чтобы сообщать (lib/consent.ts). Источник в CSP
// останется лишним, но безвредным — его убирать отдельно,
// в backend/proxy/Caddyfile.
//
// Тип указан явно: без него TypeScript сузил бы константу до литерала
// `true`, и ветка «спрашивать не о чем» стала бы для него недостижимой.
export const mapEmbedded: boolean = true;

/**
 * Адрес кадра с картой.
 *
 * `map-widget` — единственная форма встраивания Яндекс.Карт, которая
 * обходится без ключа API: ключ нужен JS API и Static API, а виджет
 * открывается тем же адресом, что и сами Карты. Ключа у нас нет,
 * и выдумывать его нельзя.
 *
 * `text=` вместо координат — по той же причине, что и у {@link mapRouteHref}:
 * координат площадки в content/ нет, а подтверждённый адрес есть. Проверено
 * в браузере (сентябрь 2026): виджет находит по этому адресу дом «Совхозная
 * улица, 20В» в Екатеринбурге и ставит на него метку.
 */
export function mapEmbedSrc(address: string): string {
  return `https://yandex.ru/map-widget/v1/?text=${encodeURIComponent(address)}&z=17`;
}

/**
 * Адрес страницы Яндекс.Карт для кнопки «Построить маршрут».
 *
 * Одна функция на обе страницы — «Контакты» и «Производство». Раньше ссылка
 * была написана только в content/contacts.ts, а «Производство» с той же
 * подписью вело на /contacts/, то есть на общую страницу вместо обещанного
 * действия (issue #102). Второй экземпляр строки развёл бы адреса молча.
 *
 * Взят `?text=`, а не `?rtext=~<адрес>`: оба ведут на Яндекс.Карты без ключа
 * и без своего скрипта на странице — просто открывают yandex.ru в новой
 * вкладке, — но проверено вручную (браузер, сентябрь 2026), что `?text=`
 * сразу разворачивает карту на нужный дом и геокодирует адрес в реальные
 * координаты, а `?rtext=` с текстом вместо «широта,долгота» координаты
 * не подставляет и карту к точке не подводит — только кладёт строку в поле
 * «Куда» неразрешённой. На открывшейся странице у пользователя есть кнопка
 * «Маршрут» — от неё до готового маршрута ровно один клик.
 */
export function mapRouteHref(address: string): string {
  return `https://yandex.ru/maps/?text=${encodeURIComponent(address)}`;
}

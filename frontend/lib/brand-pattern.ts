import {
  ACCENT_STEPS,
  ACCENTS,
  BRANCHES_BIG,
  BRANCHES_SMALL,
  SHAPES,
} from "@/content/pattern-shapes";

// Раскладка фирменного узора.
//
// ───────────────────────────────────────────────────────────────────────────
// Что здесь считается правильным
//
// Образец — печатная брошюра VEDAL, её прислал владелец портала. Узор там
// держится не на «зелёных квадратиках», а на трёх вещах, и все три пришлось
// найти опытом: первая попытка выглядела конфетти, вторая — кляксами.
//
//  1. Формы с выемками. Ровный скруглённый квадрат — не тот знак. Характер
//     дают именно вырезы и уступы, поэтому фигуры взяты присланные, а не
//     нарисованы геометрией.
//  2. Сцепка углом. Квадраты стоят цепочкой по диагонали, каждое следующее
//     звено мельче предыдущего. Одиночная фигура в брошюре — редкость.
//  3. Два светлых тона. Одним тоном поле плоское; глубина держится
//     на разнице бледного и чуть более плотного.
//
// ───────────────────────────────────────────────────────────────────────────
// Почему генератор, а не готовая картинка
//
// Полоса узора стоит в местах разной ширины и высоты. Готовый снимок пришлось
// бы либо растягивать ((формы перестают быть квадратными)), либо обрезать
// (композиция теряет край). Генератор раскладывает поле под конкретный размер
// и всегда одинаково: зерно фиксировано, случайность псевдо.
//
// Одинаково — это не педантизм. Компонент серверный, разметка приезжает
// готовой; узор, который отличался бы на сервере и в браузере, дал бы
// расхождение при гидратации и предупреждение в консоли на каждой странице.

/** Псевдослучайность с зерном: одно и то же поле при каждой сборке. */
function seeded(seed: number): () => number {
  let s = seed >>> 0;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296;
  };
}

/** Фигура на поле: id формы, положение, размер, цвет и матрица. */
export type Placed = {
  id: string;
  x: number;
  y: number;
  w: number;
  h: number;
  /** Поворот на четверть оборота: 0, 90, 180 или 270. */
  turn: number;
  mirror: boolean;
  /** Какой краской: светлая форма или акцент. */
  ink: "pale" | "deep" | "accent";
};

export type FieldOptions = {
  width: number;
  height: number;
  seed: number;
  /**
   * Прямоугольники, куда фигуры не ставятся.
   *
   * Их два рода. Первый — место текста: попавшая туда фигура не
   * сдвигается, а не рисуется вовсе, потому что сдвинутая ломает ритм
   * сетки, а отсутствующая читается как воздух.
   *
   * Второй — полоса под шапкой сайта. Шапка прозрачна, и без этой зоны
   * узор просвечивает сквозь неё: на первой же сборке зелёный квадрат
   * встал ровно на логотип VEDAL, и логотипа не стало видно.
   */
  keepClear?: readonly { x1?: number; x2: number; y1: number; y2: number; /** Зона закрыта для всего, а не только для акцентов. */ strict?: boolean }[];
  /** Доля занятых гнёзд, 0…1. Ниже — больше воздуха. */
  density?: number;
  /**
   * Во сколько раз крупнее обычного идут фигуры.
   *
   * Единица — поле мелких знаков, как на развороте брошюры. Тройка —
   * несколько больших форм и воздух между ними: рисунок перестаёт быть
   * фактурой и становится композицией. Шаг гнёзд растёт вместе с ним,
   * иначе крупные формы не найдут свободного места и поле опустеет
   * само по себе, без всякого замысла.
   */
  boldness?: number;
};

type Box = { x: number; y: number; w: number; h: number };

/** Шаг сетки гнёзд, px. Подобран по плотности брошюры. */
const NEST = 62;

/** Крупные формы требуют не только масштаба, но и места вокруг. */
const nestFor = (boldness: number) => NEST * (1 + (boldness - 1) * 0.45);

export function buildField({
  width,
  height,
  seed,
  keepClear = [],
  density = 1,
  boldness = 1,
}: FieldOptions): Placed[] {
  const rnd = seeded(seed);
  const placed: Placed[] = [];
  const taken: Box[] = [];
  const pick = <T,>(list: readonly T[]): T => list[Math.floor(rnd() * list.length)];

  const free = (b: Box, gap: number) =>
    !taken.some(
      (t) =>
        b.x < t.x + t.w + gap &&
        b.x + b.w + gap > t.x &&
        b.y < t.y + t.h + gap &&
        b.y + b.h + gap > t.y,
    );

  function put(
    id: string,
    x: number,
    y: number,
    scale: number,
    ink: Placed["ink"],
    { turn = 0, mirror = false, gap = 6 + 4 * Math.sqrt(boldness) } = {},
  ): Box | null {
    const shape = SHAPES[id];
    let w = shape.w * scale;
    let h = shape.h * scale;
    // На четверть оборота коробка ложится набок. Без этого проверка занятости
    // считала бы место не там, где фигура на самом деле, и повёрнутые формы
    // наезжали бы на соседей.
    if (turn === 90 || turn === 270) [w, h] = [h, w];

    if (x + w < -20 || x > width + 20 || y + h < -20 || y > height + 20) return null;
    // Свободные зоны держат только акценты.
    //
    // Насыщенный квадрат за строкой — это пятно поверх текста: глаз цепляется
    // за него раньше, чем за слово. Бледная форма ведёт себя иначе, она
    // светлее бумаги под буквами и читать не мешает, — а если запретить
    // и её, крупным формам на первом экране просто негде стоять: текст
    // занимает три четверти колонки, и поле выходит пустым.
    //
    // Шапка — исключение из исключения: там прозрачный фон и логотип,
    // и под них не должно попадать ничего вовсе.
    const запретна = keepClear.some(
      (z) =>
        (ink === "accent" || z.strict) &&
        x < z.x2 &&
        x + w > (z.x1 ?? -Infinity) &&
        y + h > z.y1 &&
        y < z.y2,
    );
    if (запретна) return null;
    const box = { x, y, w, h };
    if (!free(box, gap)) return null;

    taken.push(box);
    placed.push({ id, x, y, w, h, turn, mirror, ink });
    return box;
  }

  const anyTurn = () => ({
    turn: [0, 90, 180, 270][Math.floor(rnd() * 4)],
    mirror: rnd() < 0.5,
  });

  // ─────────────────────────────────────────────────────────────────────
  // Крупный узор — композиция, а не поле
  //
  // Сетка гнёзд хороша, пока фигуры мелкие: их много, они заполняют
  // площадь и читаются фактурой. Для нескольких больших форм она не
  // работает вовсе, и это не подбор параметров, а свойство приёма: первая
  // же крупная фигура занимает пол-экрана, остальные не находят места
  // и отсеиваются. Сколько ни увеличивай крупность, на экране остаются
  // две фигуры — проверено четырьмя заходами.
  //
  // Поэтому при крупности от двойки раскладка другая: несколько форм
  // в назначенных местах, крупно, с уходом за обрез — как на развороте
  // брошюры, где знак заходит за край страницы, а не помещается целиком.
  if (boldness >= 2) {
    // ───────────────────────────────────────────────────────────────────
    // Крупная раскладка: каждая форма ровно один раз
    //
    // Заказчик прислал семнадцать фигур и хочет видеть их все, без
    // повторов. Поэтому здесь не случайный выбор из списка, а поимённая
    // расстановка: место, размер и поворот заданы каждой форме отдельно.
    //
    // Случайность тут была бы прямо во вред. При выборе наугад одни формы
    // выпадают дважды, другие не выпадают вовсе — а именно неповторяемость
    // и составляет смысл этой раскладки.
    //
    // Координаты — доли поля, а не пиксели: одна и та же композиция
    // ложится и в колонку первого экрана, и в широкую тёмную полосу.
    // Размер задан долей высоты: у форм разные пропорции, и общая мера
    // по ширине сделала бы вытянутую ветку вдвое выше квадрата.
    //
    // Порядок в списке — порядок отрисовки: то, что ниже, ложится поверх.
    const РАССТАНОВКА: readonly {
      id: string;
      x: number;
      y: number;
      size: number;
      ink: Placed["ink"];
      turn?: number;
      mirror?: boolean;
    }[] = [
      // ——— светлые формы: расходятся по всей площади, в том числе
      //     за текстом. Бледные настолько, что читать не мешают, — зато
      //     без них левая половина пустует, и композиция валится вправо.
      { id: "p1-1", x: -0.08, y: 0.16, size: 0.6, ink: "pale" },
      { id: "p1-2", x: 0.16, y: 0.14, size: 0.3, ink: "pale", mirror: true },
      { id: "p2-1", x: 0.79, y: 0.4, size: 0.5, ink: "pale" },
      { id: "p2-2", x: 0.44, y: 0.7, size: 0.28, ink: "deep", mirror: true },
      { id: "p1-3", x: 0.62, y: 0.15, size: 0.14, ink: "deep" },
      { id: "p2-4", x: 0.28, y: 0.54, size: 0.07, ink: "deep" },
      { id: "p1-4", x: 0.48, y: 0.3, size: 0.04, ink: "deep" },
      { id: "p2-3", x: 0.93, y: 0.19, size: 0.16, ink: "pale" },

      // ——— акценты: только вне текста — сверху, справа и по низу.
      //     Насыщенный квадрат за строкой перетягивает взгляд с первого
      //     слова заголовка, и никакая бледность его не спасает.
      { id: "p1-sq-1", x: 0.73, y: 0.25, size: 0.18, ink: "accent" },
      { id: "p2-sq-1", x: 0.24, y: 0.86, size: 0.18, ink: "accent", mirror: true },
      { id: "p1-sq-2", x: 0.9, y: 0.62, size: 0.09, ink: "accent" },
      { id: "p1-sq-3", x: 0.77, y: 0.76, size: 0.08, ink: "accent" },
      { id: "p2-sq-2", x: 0.86, y: 0.35, size: 0.075, ink: "accent" },
      { id: "p1-sq-4", x: 0.88, y: 0.14, size: 0.055, ink: "accent" },
      { id: "p1-sq-5", x: 0.71, y: 0.91, size: 0.055, ink: "accent" },
      { id: "p2-sq-3", x: 0.96, y: 0.86, size: 0.045, ink: "accent" },
      { id: "p1-sq-7", x: 0.67, y: 0.57, size: 0.035, ink: "accent" },
    ];

    // Зазор между фигурами. Не ноль: соприкасающиеся формы читаются одной
    // склеенной кляксой, а весь смысл набора — что фигур семнадцать разных.
    const ЗАЗОР = 10;

    /**
     * Ставит фигуру на назначенное место, а если оно занято — ищет рядом.
     *
     * Расстановка задана вручную, но места назначены на глаз, и фигуры
     * с разными пропорциями всё равно находят друг на друга: у ветки
     * высота вдвое больше ширины, у сцепки — квадрат, и то, что на бумаге
     * выглядело соседством, на экране оборачивается наложением.
     *
     * Поэтому место — пожелание, а не приказ. Сначала пробуем как задумано,
     * потом обходим окрестность по расширяющемуся кольцу: восемь
     * направлений, шаг за шагом. Так фигура остаётся там, где ей назначено
     * по композиции, и при этом ни на кого не ложится.
     *
     * Не нашлось места вовсе — уменьшаем фигуру и пробуем снова. Пропасть
     * она не имеет права: набор из семнадцати, и шестнадцать — это уже
     * другой набор.
     */
    function поставитьРядом(место: (typeof РАССТАНОВКА)[number]) {
      const shape = SHAPES[место.id];
      // Заход за обрез придержан: фигура обязана остаться в кадре хотя бы
      // третью.
      //
      // Место задано долей ширины, а размер — долей высоты, и в широкой
      // низкой полосе эти две меры расходятся. Крупная ветка назначена
      // на −0.08 по ширине: в колонке первого экрана (830 × 648) это
      // шестьдесят шесть пикселей влево при двухстах восьми ширины —
      // фигура заходит за край и читается продолжением большого поля,
      // как на развороте брошюры. В шапке внутренней страницы
      // (1400 × 330) те же −0.08 дают сто двенадцать пикселей влево
      // при ста шести ширины, и фигуры не остаётся вовсе: она стоит
      // за кадром целиком, а в наборе её при этом семнадцатая доля.
      //
      // Прижимаем только назначенное место. Кольцевой обход ниже сдвигает
      // фигуры сам и может вынести их к самому краю — это его право
      // и цена того, что все семнадцать находят себе место.
      const держатьВКадре = (v: number, размер: number, поле: number) =>
        Math.min(Math.max(v, размер / 4 - размер), поле - размер / 4);
      const scale0 = (height * место.size) / shape.h;
      const x0 = держатьВКадре(width * место.x, shape.w * scale0, width);
      const y0 = держатьВКадре(height * место.y, shape.h * scale0, height);
      const опции = {
        turn: место.turn ?? 0,
        mirror: место.mirror ?? false,
        gap: ЗАЗОР,
      };

      for (const усадка of [1, 0.85, 0.7, 0.55, 0.4]) {
        const scale = ((height * место.size) / shape.h) * усадка;
        const шаг = Math.max(14, height * место.size * 0.22);

        for (let кольцо = 0; кольцо <= 9; кольцо++) {
          const смещения: [number, number][] =
            кольцо === 0
              ? [[0, 0]]
              : [
                  [кольцо, 0], [-кольцо, 0], [0, кольцо], [0, -кольцо],
                  [кольцо, кольцо], [-кольцо, кольцо], [кольцо, -кольцо], [-кольцо, -кольцо],
                ];

          for (const [дх, ду] of смещения) {
            if (put(место.id, x0 + дх * шаг, y0 + ду * шаг, scale, место.ink, опции)) return true;
          }
        }
      }
      return false;
    }

    // Крупные первыми: им труднее найти место, и если их подвинет мелочь,
    // композиция развалится. Мелкие поместятся в оставшиеся промежутки —
    // им это ничего не стоит.
    const поПорядку = [...РАССТАНОВКА].sort((a, b) => b.size - a.size);
    for (const место of поПорядку) поставитьРядом(место);

    return placed;
  }

  const nest = nestFor(boldness);

  for (let gy = -40; gy < height + 40; gy += nest) {
    for (let gx = -40; gx < width + 40; gx += nest) {
      if (rnd() > density) continue;

      const x0 = gx + rnd() * 26 * boldness;
      const y0 = gy + rnd() * 26 * boldness;
      const roll = rnd();
      const pale: Placed["ink"] = rnd() < 0.6 ? "pale" : "deep";

      if (roll < 0.3) {
        // Крупная ветка. Редко и не крупнее ладони: на прошлой итерации
        // такие формы шли втрое больше и читались кляксами, а не узором.
        put(pick(BRANCHES_BIG), x0, y0, (0.17 + rnd() * 0.12) * boldness, pale, anyTurn());
      } else if (roll < 0.52) {
        put(pick(BRANCHES_SMALL), x0, y0, (0.34 + rnd() * 0.4) * boldness, pale, anyTurn());
      } else if (roll < 0.62) {
        // Цепочка уступом — главный мотив брошюры.
        const down = rnd() < 0.5;
        const id = rnd() < 0.35 ? pick(ACCENT_STEPS) : pick(ACCENTS);
        const mirror = rnd() < 0.5;
        let scale = (0.22 + rnd() * 0.16) * boldness;
        let x = x0;
        let y = y0;
        const links = 2 + (rnd() < 0.5 ? 1 : 0) + (rnd() < 0.2 ? 1 : 0);
        for (let i = 0; i < links; i++) {
          // Зазор почти нулевой: звенья цепочки соприкасаются углами,
          // это одна фигура, переломленная по диагонали, а не две рядом.
          const box = put(id, x, y, scale, "accent", { mirror, gap: 2 });
          if (!box) break;
          x += box.w * 0.97;
          y += down ? box.h * 0.97 : -box.h * 0.97;
          scale *= 0.82;
        }
      } else if (roll < 0.72) {
        // Акцент в выемке светлой формы — так они стоят на брошюре.
        const id = pick(BRANCHES_SMALL);
        const box = put(id, x0, y0, (0.45 + rnd() * 0.36) * boldness, pale, anyTurn());
        if (box) {
          put(
            pick(ACCENTS),
            x0 + box.w * (0.55 + rnd() * 0.4),
            y0 + box.h * (0.4 + rnd() * 0.45),
            (0.17 + rnd() * 0.13) * boldness,
            "accent",
            { gap: 2 },
          );
        }
      } else if (roll < 0.8) {
        const id = pick(ACCENTS);
        const scale = (0.3 + rnd() * 0.2) * boldness;
        const box = put(id, x0, y0, scale, "accent", { gap: 6 });
        if (box && rnd() < 0.7) {
          put(pick(ACCENTS), x0 + box.w * 1.25, y0 - box.h * (0.2 + rnd() * 0.5), scale * 0.45, "accent", { gap: 4 });
        }
      } else if (roll < 0.9) {
        put(pick(ACCENTS), x0, y0, (0.2 + rnd() * 0.18) * boldness, "accent", anyTurn());
      }
      // Остальные гнёзда остаются пустыми — это и есть воздух.
    }
  }

  return placed;
}

/** Матрица одной фигуры: перенос, поворот вокруг центра, зеркало. */
export function transformOf(p: Placed): string {
  const sideways = p.turn === 90 || p.turn === 270;
  const w = sideways ? p.h : p.w;
  const parts = [`translate(${Math.round(p.x)} ${Math.round(p.y)})`];
  if (p.turn) parts.push(`rotate(${p.turn} ${Math.round(p.w / 2)} ${Math.round(p.h / 2)})`);
  if (p.mirror) parts.push(`translate(${Math.round(w)} 0) scale(-1 1)`);
  return parts.join(" ");
}

/** Размер фигуры до поворота — его и получает `use`. */
export function sizeOf(p: Placed): { w: number; h: number } {
  const sideways = p.turn === 90 || p.turn === 270;
  return sideways ? { w: p.h, h: p.w } : { w: p.w, h: p.h };
}

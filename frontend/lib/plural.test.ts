import { describe, it, expect } from "vitest";
import { plural, models, directions } from "./plural";

describe("склонение по числу", () => {
  it("берёт единственное число на единице и на любом числе, оканчивающемся на неё", () => {
    expect(models(1)).toBe("модель");
    expect(models(21)).toBe("модель");
    expect(models(101)).toBe("модель");
  });

  it("берёт малую форму на двух, трёх и четырёх", () => {
    expect(models(2)).toBe("модели");
    expect(models(4)).toBe("модели");
    expect(models(22)).toBe("модели");
  });

  // Ровно тот случай, из-за которого функция и появилась: каталог сократили
  // до четырёх позиций, и подпись «моделей» перестала согласовываться.
  it("даёт «4 модели», а не «4 моделей»", () => {
    expect(`4 ${models(4)}`).toBe("4 модели");
  });

  it("берёт большую форму на пяти и дальше", () => {
    expect(models(5)).toBe("моделей");
    expect(models(12)).toBe("моделей");
    expect(directions(5)).toBe("направлений");
  });

  // Вторые десятки — исключение из правила «смотри на последнюю цифру».
  // Без него 11, 12, 13 и 14 ушли бы в единственное число и в малую форму.
  it("держит вторые десятки в большой форме, хотя они оканчиваются на 1–4", () => {
    expect(models(11)).toBe("моделей");
    expect(models(12)).toBe("моделей");
    expect(models(13)).toBe("моделей");
    expect(models(14)).toBe("моделей");
    expect(models(111)).toBe("моделей");
    expect(models(114)).toBe("моделей");
  });

  it("на нуле берёт большую форму", () => {
    expect(models(0)).toBe("моделей");
    expect(directions(0)).toBe("направлений");
  });

  it("не зависит от знака: минус в счётчике — это ошибка данных, а не форма слова", () => {
    expect(plural(-1, "модель", "модели", "моделей")).toBe("модель");
    expect(plural(-11, "модель", "модели", "моделей")).toBe("моделей");
  });
});

// Склонение существительного по числу.
//
// Понадобилось, когда каталог сократили с двенадцати позиций до четырёх:
// подписи «моделей» и «направлений» были написаны под двузначное число
// и молча превратились в «4 моделей». Числа в этих подписях считаются
// от каталога, то есть меняются вместе с ним, — значит и форма слова
// обязана считаться, а не стоять в разметке константой.
//
// Правило русского счётного согласования: 1 — единственное число, 2–4 —
// «мало», 5–20 и остальное — «много». Исключение — вторые десятки:
// 11–14 идут как «много», хотя оканчиваются на 1–4.
export function plural(n: number, one: string, few: string, many: string): string {
  const mod100 = Math.abs(n) % 100;
  if (mod100 >= 11 && mod100 <= 14) return many;

  const mod10 = mod100 % 10;
  if (mod10 === 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return few;
  return many;
}

export const models = (n: number) => plural(n, "модель", "модели", "моделей");
export const directions = (n: number) => plural(n, "направление", "направления", "направлений");

// Правило ссылки на документ. Одно на весь сайт.
//
// Документ показывается в двух местах — в перечне на /documents/ и на вкладке
// «Документы» карточки изделия, — и правило должно быть в обоих одинаковым.
// Пока оно было переписано в каждом месте по-своему, карточка изделия
// показывала три выдуманные строки со ссылкой на форму, а перечень —
// настоящие. Здесь общий источник этого решения.
//
// Правило: есть файл — ведём на файл; файла нет — ведём на форму запроса
// и говорим об этом словами. Кнопки, которая обещает файл и никуда не ведёт,
// быть не должно (issue #73).

import type { Doc } from "@/lib/api";

/** Куда ведёт документ, которого нет: форма запроса на странице контактов. */
export const REQUEST_HREF = "/contacts/";

/**
 * Документ можно открыть — он опубликован И файл загружен.
 *
 * Одного `published` мало: ссылку на файл ставит портал, и у документа без
 * файла её просто нет. Схема портала это же требует проверкой
 * `document_published_has_file`, но фронтенд не вправе полагаться на чужую
 * проверку — он получает JSON, а не таблицу.
 */
export const isOpen = (d: Doc): boolean => Boolean(d.published && d.file);

/**
 * Адрес строки: файл у открытых, форма запроса у остальных.
 *
 * Адрес формы приходит вторым аргументом, потому что у переведённых версий
 * сайта он с языковым префиксом (). Правило «куда ведёт
 * документ» про языки знать не должно — про них знает вызывающий экран.
 */
export const docHref = (d: Doc, requestHref: string = REQUEST_HREF): string =>
  isOpen(d) ? d.file! : requestHref;

/**
 * Атрибуты внешней ссылки — только у открываемых.
 *
 * Файл показывается в новой вкладке: документы смотрят подряд, и уводить
 * с перечня незачем. `rel` обязателен — без него открытая вкладка получает
 * доступ к `window.opener`.
 */
export const linkTarget = (d: Doc) =>
  isOpen(d) ? ({ target: "_blank", rel: "noopener" } as const) : {};

/**
 * Бейдж доступа. Показывает состояние файла, а не намерение редактора.
 *
 * «PDF» из макета здесь не используется намеренно. Портал принимает не только
 * PDF (StorageLimits.contentType знает про png, jpeg, webp, svg), а перечень
 * не отдаёт тип файла — значит, слово «PDF» было бы утверждением, которого
 * сайт проверить не может. «Файл» утверждает ровно то, что правда: он выложен
 * и откроется по нажатию.
 *
 * У строки без файла бейдж не обещает скачивание. «Уточняется» остаётся как
 * есть — это статус самого документа (V27: регистрационное удостоверение
 * не выдаётся, есть только реестровая запись), и он от наличия файла
 * не зависит. Всё остальное честно называется «По запросу»: именно это
 * и произойдёт по нажатию.
 */
export const accessBadge = (d: Doc): string => {
  if (isOpen(d)) return "Файл";
  return d.access === "Уточняется" ? "Уточняется" : "По запросу";
};

/** Бейдж говорит о выложенном файле — значит, он зелёный, а не приглушённый. */
export const badgeIsOk = (d: Doc): boolean => isOpen(d);

/**
 * Что произойдёт по нажатию. Пишется словами, а не подразумевается стрелкой.
 *
 * Подписи приходят аргументом: это интерфейс, и на переведённых версиях они
 * приезжают из . Умолчание русское — так функция остаётся
 * вызываемой одним аргументом, в том числе из тестов.
 */
export const actionLabel = (
  d: Doc,
  labels: { open: string; request: string } = { open: "Открыть", request: "Запросить" },
): string => (isOpen(d) ? labels.open : labels.request);

/**
 * Подпись под названием на карточке изделия: раздел перечня и судьба нажатия.
 */
export const docNote = (d: Doc): string => {
  if (isOpen(d)) return `${d.group} · открывается в новой вкладке`;
  if (d.access === "Уточняется") return `${d.group} · статус документа согласуется`;
  return `${d.group} · выдаётся по запросу`;
};

/**
 * Документы одного изделия.
 *
 * Отбор идёт по `productSlug` — связи, которую ставит портал, — а не по
 * человекочитаемой подписи. Подпись «VEDAL R1, R2» относится к строке,
 * привязанной к vedal-r1: разбирать её текстом значит показать на карточке R2
 * документ, которого у R2 может не быть (см. V27, §2).
 */
export const forProduct = (documents: Doc[], slug: string): Doc[] =>
  documents.filter((d) => d.productSlug === slug);

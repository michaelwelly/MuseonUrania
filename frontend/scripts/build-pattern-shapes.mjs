/**
 * Пересборка форм узора из исходников заказчика.
 *
 * Вход  — public/brand/pattern/svg/*.svg: силуэты, обведённые в вектор
 *         с растра. Контур в них идёт ступеньками по одному-двум пунктам.
 * Выход — content/pattern-shapes.ts: те же силуэты, но нарисованные заново.
 *
 * Идея. В брошюре фигуры сложены из квадратов на одной сетке: все стороны
 * прямые, все углы скруглены одним радиусом — и наружные, и внутренние.
 * Значит, в обводке нужен не сам контур, а только его длинные стороны:
 * они и есть стороны квадратов. Короткие звенья между ними — не форма,
 * а след растра, и восстанавливаются пересечением соседних длинных сторон.
 *
 * Порядок:
 *   1. взять из контура стороны длиннее ПОРОГа, строго горизонтальные
 *      или вертикальные;
 *   2. соседние сонаправленные, разошедшиеся на пункт-другой, слить в одну
 *      (это дрожание растра, а не уступ);
 *   3. пересечь соседние стороны — получить углы прямоугольного контура;
 *   4. скруглить каждый угол своей дугой.
 *
 * Радиус не на глаз и не один на всех: он замерен по каждому углу отдельно —
 * насколько две стороны не доходят до своего пересечения, на столько их
 * и увели в дугу. Так в брошюре и сделано: по краю углы срезаны скупо,
 * а внутренние сгибы, которыми квадраты переходят друг в друга, выведены
 * широкой дугой — у большой ветки в тридцать с лишним пунктов против девяти.
 * Общий радиус на всю фигуру рвёт как раз эти переходы: ветка рассыпается
 * на квадраты, между которыми белый волосок.
 *
 * Общая мера остаётся про запас — для углов, восстановленных вместо
 * потерянного уступа, мерить у которых нечего. Она привязана к толщине ветви:
 * габарит для этого не годится, у полоски 21×92 углы такие же, как
 * у квадрата 21, а не в четыре раза круче.
 *
 * Запуск: node scripts/build-pattern-shapes.mjs
 */

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const SRC = "public/brand/pattern/svg";
const OUT = "content/pattern-shapes.ts";

/** Короче этого сторона считается ступенькой растра, а не стороной фигуры. */
const ПОРОГ = 9;
/** Разошлись меньше этого — одна и та же сторона, дрожание обводки. */
const ДРОЖАНИЕ = 3.5;
/** Радиус скругления — доля толщины ветви. Снят с квадратов исходника. */
const ДОЛЯ_РАДИУСА = 0.12;

// ─── разбор исходника ────────────────────────────────────────────────────

function читатьSvg(файл) {
  const текст = readFileSync(файл, "utf8");
  const box = /viewBox="([\d.\s-]+)"/.exec(текст);
  const d = /\sd="([^"]+)"/.exec(текст);
  if (!box || !d) throw new Error(`${файл}: нет viewBox или пути`);
  const [, , w, h] = box[1].trim().split(/\s+/).map(Number);
  return { w, h, d: d[1] };
}

/** Путь исходника — только M, L и Z; ломаная, без кривых. */
function вЛоманые(d) {
  const части = [];
  let текущая = null;
  const токены = d.match(/[MLZ][^MLZ]*/gi) ?? [];
  for (const токен of токены) {
    const команда = токен[0].toUpperCase();
    const числа = токен
      .slice(1)
      .trim()
      .split(/[\s,]+/)
      .filter(Boolean)
      .map(Number);
    if (команда === "M") {
      if (текущая?.length) части.push(текущая);
      текущая = [{ x: числа[0], y: числа[1] }];
      for (let i = 2; i < числа.length; i += 2) текущая.push({ x: числа[i], y: числа[i + 1] });
    } else if (команда === "L") {
      for (let i = 0; i < числа.length; i += 2) текущая.push({ x: числа[i], y: числа[i + 1] });
    } else if (команда === "Z") {
      части.push(текущая);
      текущая = null;
    } else {
      throw new Error(`неожиданная команда ${команда}`);
    }
  }
  if (текущая?.length) части.push(текущая);
  return части;
}

// ─── длинные стороны ─────────────────────────────────────────────────────

/** Стороны длиннее порога, строго вдоль осей. Порядок обхода сохраняется. */
function длинныеСтороны(точки) {
  const стороны = [];
  for (let i = 0; i < точки.length; i += 1) {
    const a = точки[i];
    const b = точки[(i + 1) % точки.length];
    const dx = b.x - a.x;
    const dy = b.y - a.y;
    if (dx !== 0 && dy !== 0) continue;
    const длина = Math.abs(dx) + Math.abs(dy);
    if (длина < ПОРОГ) continue;
    стороны.push(
      dy === 0
        ? { ось: "h", коорд: a.y, от: a.x, до: b.x, длина }
        : { ось: "v", коорд: a.x, от: a.y, до: b.y, длина },
    );
  }
  return стороны;
}

/** Соседние сонаправленные стороны, разошедшиеся на дрожание, — одна сторона. */
function слитьДрожание(стороны) {
  let текущие = стороны;
  for (let проход = 0; проход < 4; проход += 1) {
    const слитые = [];
    let изменилось = false;
    for (const сторона of текущие) {
      const прошлая = слитые[слитые.length - 1];
      if (
        прошлая &&
        прошлая.ось === сторона.ось &&
        Math.abs(прошлая.коорд - сторона.коорд) <= ДРОЖАНИЕ
      ) {
        const вес = прошлая.длина + сторона.длина;
        прошлая.коорд =
          (прошлая.коорд * прошлая.длина + сторона.коорд * сторона.длина) / вес;
        прошлая.до = сторона.до;
        прошлая.длина = вес;
        изменилось = true;
        continue;
      }
      слитые.push({ ...сторона });
    }
    // Обход замкнут: последняя сторона соседствует с первой.
    const первая = слитые[0];
    const последняя = слитые[слитые.length - 1];
    if (
      слитые.length > 2 &&
      первая.ось === последняя.ось &&
      Math.abs(первая.коорд - последняя.коорд) <= ДРОЖАНИЕ
    ) {
      const вес = первая.длина + последняя.длина;
      первая.коорд = (первая.коорд * первая.длина + последняя.коорд * последняя.длина) / вес;
      первая.от = последняя.от;
      первая.длина = вес;
      слитые.pop();
      изменилось = true;
    }
    текущие = слитые;
    if (!изменилось) break;
  }
  return текущие;
}

/**
 * После слияния соседние стороны обязаны чередоваться. Если рядом остались
 * две сонаправленные — между ними настоящий уступ, короче порога: он
 * восстанавливается перемычкой посередине разрыва.
 */
function чередовать(стороны) {
  const итог = [];
  for (let i = 0; i < стороны.length; i += 1) {
    const сторона = стороны[i];
    итог.push(сторона);
    const следующая = стороны[(i + 1) % стороны.length];
    if (сторона.ось !== следующая.ось) continue;
    const середина = (сторона.до + следующая.от) / 2;
    итог.push({
      ось: сторона.ось === "h" ? "v" : "h",
      коорд: середина,
      от: сторона.коорд,
      до: следующая.коорд,
      длина: Math.abs(следующая.коорд - сторона.коорд),
      перемычка: true,
    });
  }
  return итог;
}

/**
 * Углы прямоугольного контура — пересечения соседних сторон. Заодно каждому
 * углу берётся свой радиус.
 *
 * Одной цифры на всю фигуру мало, и это главное, что видно при сравнении
 * с брошюрой: наружные углы там срезаны скупо, а внутренние сгибы, которыми
 * квадраты переходят друг в друга, выведены широкой дугой — у большой ветки
 * в тридцать с лишним пунктов против девяти по краю. С общим радиусом ветка
 * распадается на квадраты со стыком-волоском.
 *
 * Радиус угла виден по самой обводке: насколько каждая из двух сторон
 * не доходит до их пересечения — на столько её и увели в дугу.
 */
function углы(стороны) {
  const точки = [];
  for (let i = 0; i < стороны.length; i += 1) {
    const a = стороны[i];
    const b = стороны[(i + 1) % стороны.length];
    if (a.ось === b.ось) throw new Error("соседние стороны сонаправлены");
    const точка = a.ось === "h" ? { x: b.коорд, y: a.коорд } : { x: a.коорд, y: b.коорд };
    // У перемычки, восстановленной вместо потерянного уступа, мерить нечего:
    // радиус ей потом достанется общий по фигуре.
    if (a.перемычка || b.перемычка) {
      точки.push({ ...точка, r: null });
      continue;
    }
    const недоходА = a.ось === "h" ? Math.abs(точка.x - a.до) : Math.abs(точка.y - a.до);
    const недоходБ = b.ось === "h" ? Math.abs(точка.x - b.от) : Math.abs(точка.y - b.от);
    точки.push({ ...точка, r: (недоходА + недоходБ) / 2 });
  }
  return точки;
}

/**
 * Толщина ветви фигуры: сколько подряд идёт заливка по строке и по столбцу.
 *
 * Радиус в брошюре привязан не к габариту, а к квадрату, из которых фигура
 * сложена: у полоски двадцать один на девяносто два углы такие же, как
 * у квадрата двадцать один. Замерить радиус по самой обводке не выходит —
 * там, где два квадрата сходятся уголками, она идёт наискось, и такой угол
 * не отличить от скругления. Толщина же меряется однозначно.
 */
function толщина(точки) {
  const xs = точки.map((т) => т.x);
  const ys = точки.map((т) => т.y);
  const x0 = Math.min(...xs);
  const x1 = Math.max(...xs);
  const y0 = Math.min(...ys);
  const y1 = Math.max(...ys);
  const шаг = Math.min(x1 - x0, y1 - y0) / 60;

  const внутри = (x, y) => {
    let да = false;
    for (let i = 0, j = точки.length - 1; i < точки.length; j = i, i += 1) {
      const a = точки[i];
      const b = точки[j];
      if (a.y > y !== b.y > y && x < ((b.x - a.x) * (y - a.y)) / (b.y - a.y) + a.x) да = !да;
    }
    return да;
  };

  const пробеги = [];
  const пройти = (внешний0, внешний1, внутренний0, внутренний1, точкаВ) => {
    for (let a = внешний0 + шаг / 2; a < внешний1; a += шаг) {
      let бег = 0;
      for (let b = внутренний0 + шаг / 2; b < внутренний1; b += шаг) {
        const { x, y } = точкаВ(a, b);
        if (внутри(x, y)) бег += шаг;
        else {
          if (бег > шаг) пробеги.push(бег);
          бег = 0;
        }
      }
      if (бег > шаг) пробеги.push(бег);
    }
  };
  пройти(y0, y1, x0, x1, (a, b) => ({ x: b, y: a }));
  пройти(x0, x1, y0, y1, (a, b) => ({ x: a, y: b }));
  return пробеги;
}

function убратьЛишние(точки) {
  const чистые = [];
  for (const точка of точки) {
    const прошлая = чистые[чистые.length - 1];
    if (прошлая && Math.abs(прошлая.x - точка.x) < 0.01 && Math.abs(прошлая.y - точка.y) < 0.01) {
      continue;
    }
    чистые.push(точка);
  }
  // Три подряд на одной прямой — средняя не нужна.
  const итог = [];
  for (let i = 0; i < чистые.length; i += 1) {
    const до = чистые[(i - 1 + чистые.length) % чистые.length];
    const это = чистые[i];
    const после = чистые[(i + 1) % чистые.length];
    const наОднойX = Math.abs(до.x - это.x) < 0.01 && Math.abs(это.x - после.x) < 0.01;
    const наОднойY = Math.abs(до.y - это.y) < 0.01 && Math.abs(это.y - после.y) < 0.01;
    if (наОднойX || наОднойY) continue;
    итог.push(это);
  }
  return итог;
}

// ─── обводка со скруглением ──────────────────────────────────────────────

const окр = (n) => Number(n.toFixed(2));

function обвести(точки, общийРадиус) {
  const n = точки.length;
  const части = [];

  // Радиус угла — свой, замеренный; у восстановленных перемычек его нет,
  // им достаётся общий по фигуре.
  const радиусы = точки.map((т) => (т.r === null || т.r === undefined ? общийРадиус : т.r));

  // Два соседних скругления не могут съесть общую сторону больше, чем она
  // есть: где не помещаются, ужимаются оба, сохраняя соотношение.
  for (let i = 0; i < n; i += 1) {
    const это = точки[i];
    const после = точки[(i + 1) % n];
    const длина = Math.hypot(после.x - это.x, после.y - это.y);
    const занято = радиусы[i] + радиусы[(i + 1) % n];
    if (занято > длина) {
      const доля = длина / занято;
      радиусы[i] *= доля;
      радиусы[(i + 1) % n] *= доля;
    }
  }

  for (let i = 0; i < n; i += 1) {
    const до = точки[(i - 1 + n) % n];
    const это = точки[i];
    const после = точки[(i + 1) % n];

    const длинаДо = Math.hypot(это.x - до.x, это.y - до.y);
    const длинаПосле = Math.hypot(после.x - это.x, после.y - это.y);
    const r = Math.min(радиусы[i], длинаДо / 2, длинаПосле / 2);

    const u = { x: (это.x - до.x) / длинаДо, y: (это.y - до.y) / длинаДо };
    const v = { x: (после.x - это.x) / длинаПосле, y: (после.y - это.y) / длинаПосле };
    const вход = { x: это.x - u.x * r, y: это.y - u.y * r };
    const выход = { x: это.x + v.x * r, y: это.y + v.y * r };

    if (i === 0) части.push(`M${окр(вход.x)} ${окр(вход.y)}`);
    else части.push(`L${окр(вход.x)} ${окр(вход.y)}`);

    if (r > 0.05) {
      // Ось y смотрит вниз: положительное векторное произведение — поворот
      // по часовой стрелке на экране, а это и есть sweep-flag 1.
      const поворот = u.x * v.y - u.y * v.x > 0 ? 1 : 0;
      части.push(`A${окр(r)} ${окр(r)} 0 0 ${поворот} ${окр(выход.x)} ${окр(выход.y)}`);
    }
  }
  части.push("Z");
  return части.join("");
}

// ─── сборка ──────────────────────────────────────────────────────────────

const файлы = readdirSync(SRC)
  .filter((имя) => имя.endsWith(".svg"))
  .sort();

const медиана = (числа) => {
  const ряд = [...числа].sort((a, b) => a - b);
  return ряд[Math.floor(ряд.length / 2)];
};

const формы = [];

for (const имя of файлы) {
  const ключ = имя.replace(/\.svg$/, "");
  const { w, h, d: исходный } = читатьSvg(join(SRC, имя));
  const заготовки = [];
  const пробеги = [];
  for (const ломаная of вЛоманые(исходный)) {
    const стороны = чередовать(слитьДрожание(длинныеСтороны(ломаная)));
    if (стороны.length < 4) continue;
    const точки = убратьЛишние(углы(стороны));
    if (точки.length < 4) continue;
    пробеги.push(...толщина(точки));
    заготовки.push(стороны);
  }
  const ветвь = медиана(пробеги);
  const радиус = ДОЛЯ_РАДИУСА * ветвь;
  const d = заготовки
    .map((стороны) => обвести(убратьЛишние(углы(стороны)), радиус))
    .join("");
  формы.push({ ключ, w, h, d, радиус });
}


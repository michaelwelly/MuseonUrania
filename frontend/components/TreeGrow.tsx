"use client";

import { useEffect, useRef } from "react";
import styles from "./TreeGrow.module.css";

/**
 * Знак-дерево, который прорастает. Загрузочный экран.
 *
 * Было: одна картинка, открывавшаяся снизу вверх маской-градиентом. Стало:
 * вектор из пакета «Анимация для дерева» — земля раскрывается от центра,
 * из неё поднимаются ствол и ветви, потом всплывают 74 грозди листьев,
 * и у корней проходит рябь. Последний кадр совпадает с исходным знаком
 * пиксель в пиксель, поэтому дерево остаётся стоять готовым.
 *
 * Почему вектор лучше маски: маска открывала готовую картинку, то есть
 * показывала не рост, а проявление. Здесь ветви действительно вырастают
 * из земли, а крона набирается гроздьями — движение объясняет, из чего
 * собран знак, а не просто занимает время загрузки.
 */

// Цвет знака сайта, а не зелёный из исходника (#419f3b). Причина записана
// в content/brand.ts: у печатного файла свой оттенок, и два похожих зелёных
// на одной странице читаются как ошибка, а не как два оттенка.
const GREEN = "#149c3c";

// Прелоадер уходит с экрана на 2.8 с (см. LogoPreloader.module.css), а
// анимация на скорости 1 длится 3.5 с — дерево не успевало бы дорасти
// до того, как экран начнёт гаснуть. 1.35 укладывает её в 2.6 с.
const SPEED = 1.35;

export default function TreeGrow({ size = 176 }: { size?: number | string }) {
  const host = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const el = host.current;
    if (!el) return;

    let handle: import("@/vendor/tree-growth").TreeGrowthHandle | null = null;
    let cancelled = false;

    // Библиотека грузится динамически, а не обычным импортом наверху файла.
    // Она устроена как IIFE и в последней строке обращается к window — при
    // статическом импорте этот код выполняется и на сервере, где window нет,
    // и пререндер страниц падает с ReferenceError. Прелоадер лежит в общем
    // layout, поэтому падала любая страница, а не только главная.
    //
    // Задержка на загрузку чанка невелика: это тот же сборочный бандл, а не
    // внешний адрес. Экран загрузки живёт 2.8 с — запаса хватает.
    void import("@/vendor/tree-growth.js").then(() => {
      if (cancelled || !window.treeGrowth) return;

      // Продукт медицинский, движение сдержанное: под prefers-reduced-motion
      // знак стоит собранным с первого кадра. Перематываем в конец вместо
      // проигрывания — картинка та же, движения нет.
      const still = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
      handle = window.treeGrowth(el, { color: GREEN, speed: SPEED, autoplay: !still });
      if (still) handle.seek(handle.duration);
    });

    // Прелоадер снимается таймером, а не размонтированием React, но при
    // навигации назад компонент всё же уходит — тогда SVG остаётся в DOM
    // висеть с работающим requestAnimationFrame. Чистим за собой.
    return () => {
      cancelled = true;
      handle?.reset();
      el.replaceChildren();
    };
  }, []);

  return (
    <div
      ref={host}
      className={styles.wrap}
      style={{ width: size, height: size }}
      aria-hidden="true"
    />
  );
}

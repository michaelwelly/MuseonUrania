"use client";

import { useEffect } from "react";

/**
 * Усложняет сохранение фотографий: перетаскивание и контекстное меню
 * на изображениях. §12.2 плана.
 *
 * ————— что это НЕ делает —————
 *
 * Не запрещает сохранить картинку. Снимок экрана, DevTools, вкладка «Сеть»,
 * прямой адрес файла — всё это остаётся, и закрыть его в браузере нечем.
 * План это признаёт прямым текстом. Меры здесь ровно на то, чтобы картинку
 * нельзя было утащить одним движением мыши, — на случайное копирование,
 * не на намеренное.
 *
 * ————— почему слушатели на документе, а не атрибуты у каждой картинки —————
 *
 * Изображений на сайте под сотню, они приходят из next/image, из галереи
 * производства и из карточек. Атрибут draggable={false} пришлось бы ставить
 * в полутора десятках мест и не забывать при каждой новой картинке.
 * Забудут на первой же — и защита станет выборочной, чего никто не заметит.
 *
 * ————— почему только изображения —————
 *
 * Контекстное меню на всей странице не отключается намеренно. Оно нужно
 * живым людям: открыть ссылку в новой вкладке, проверить орфографию
 * в поле формы, скопировать телефон. Снабженец, который переносит
 * характеристики в тендерную заявку, — наш читатель, а не вор.
 */
export default function ImageGuard() {
  useEffect(() => {
    const onImage = (event: Event) => {
      const target = event.target as HTMLElement | null;
      if (target?.tagName === "IMG") event.preventDefault();
    };

    document.addEventListener("dragstart", onImage);
    document.addEventListener("contextmenu", onImage);
    return () => {
      document.removeEventListener("dragstart", onImage);
      document.removeEventListener("contextmenu", onImage);
    };
  }, []);

  return null;
}

"use client";

import type { ReactNode } from "react";
import { useSyncExternalStore } from "react";
import { readConsent, readServerConsent, subscribe } from "@/lib/consent";
import styles from "./VedalMapEmbed.module.css";

/**
 * Встроенная карта Яндекса — после согласия. GitHub issue #74.
 *
 * Кадр карты ставит сторонние cookie и сообщает Яндексу, что этот браузер
 * открыл эту страницу. Это ровно то же, что делает счётчик Метрики, поэтому
 * и признак тот же: `consent === "analytics"` — одно согласие на все
 * сторонние ресурсы Яндекса (см. `lib/consent.ts`). Отдельного вопроса
 * про карту нет намеренно: человек отвечает на одно и то же.
 *
 * Пока согласия нет, на месте карты рисуется `children` — схема проезда
 * на CSS, а рядом, в панели слева, остаются адрес и рабочая ссылка
 * «Построить маршрут». Это не заглушка «включите cookie», а полноценный
 * запасной вариант: посетитель, отказавшийся от передачи данных, получает
 * адрес и маршрут, а не пустой прямоугольник с упрёком.
 *
 * ————— почему запасной вариант приходит children, а не импортом —————
 *
 * Схема проезда — серверный компонент, и приезжает она сюда готовой
 * разметкой из статики. Импортируй её этот файл сам, она уехала бы
 * в клиентский бандл целиком и пропала бы из HTML: у «use client»
 * импортированное дерево тоже становится клиентским.
 *
 * ————— почему useSyncExternalStore, а не useEffect —————
 *
 * Та же причина, что и у плашки: страницы отдаются статикой, и разметка
 * одна на всех. Серверный снимок — «ответ неизвестен», и при нём рисуется
 * запасной вариант. Значит, в HTML всегда лежит схема с адресом — её видят
 * и поисковик, и браузер с выключенным JS, — а кадр карты появляется уже
 * после гидратации и только у того, кто согласился.
 */
export default function VedalMapEmbed({
  src,
  title,
  children,
}: {
  src: string;
  title: string;
  children: ReactNode;
}) {
  const consent = useSyncExternalStore(subscribe, readConsent, readServerConsent);

  if (consent !== "analytics") return <>{children}</>;

  return (
    <iframe
      className={styles.frame}
      src={src}
      title={title}
      // Карта не должна задерживать остальную страницу: кадр грузится
      // тогда, когда до него доходит очередь.
      //
      // Ни sandbox, ни пустого allow здесь нет намеренно. Виджет — живая
      // карта: ей нужны свои скрипты, своё хранилище и кнопка «где я»,
      // и обрезанный кадр сломался бы молча, отрисовав серый прямоугольник.
      // Ограничение здесь другое и оно сильнее любого атрибута: кадра нет
      // вовсе, пока человек не согласился.
      loading="lazy"
    />
  );
}

/**
 * Сколько звеньев рисовать.
 *
 * Шесть при звене в 340 пикселей — это две тысячи с лишним: выше любой
 * полосы сайта, включая первый экран главной (648) с запасом на крупные
 * экраны. Лишние обрезаются, картинки под ними не грузятся.
 */
const LINK_COUNT = 6;

type Props = {
  /** Какая из двух присланных композиций. */
  variant?: Variant;
  /**
   * Тёмная полоса: ветки приглушаются, квадраты не рисуются вовсе.
   * На почти чёрном фоне бледные ветки и так заметны, а насыщенный
   * зелёный квадрат превращается в световое пятно и тянет взгляд
   * сильнее, чем текст рядом.
   */
  tone?: "light" | "dark";
  /**
   * Где стоит лента.
   *
   * `edge` — у правого края полосы. Годится там, где правая часть свободна:
   * первые экраны внутренних страниц.
   *
   * `seam` — в стыке между текстом и фотографией, правым краем под снимок.
   * Для полос, где правую половину занимает фото: у края там встать негде,
   * лента ушла бы под снимок целиком. Ширину стыка страница передаёт
   * через CSS-переменную --pattern-seam.
   */
  placement?: "edge" | "seam";
};

/**
 * Показывать ли фоновый узор.
 *
 * Выключен 8 сентября по просьбе владельца портала: «лепестки везде пока
 * убери, они плохо смотрятся». Слово «пока» здесь существенно — это не
 * отказ от приёма, а пауза, поэтому узор выключен одной строкой, а не
 * вырезан из шести мест, где стоит: главная (два), производство, сервис,
 * блоки, шапка внутренней страницы и окно чата.
 *
 * Вернуть — поставить `true`. Удалять вызовы `<LivePattern />` со страниц
 * не нужно и не следует: расстановка по стыкам и краям подобрана под
 * раскладку каждой страницы, и восстанавливать её потом заново значило бы
 * делать работу дважды.
 */
const ПОКАЗЫВАТЬ = false;

export default function LivePattern({
  variant = 1,
  tone = "light",
  placement = "edge",
}: Props) {
  const links = LINKS[variant];
  const dark = tone === "dark";

  if (!ПОКАЗЫВАТЬ) return null;

  return (
    <span
      className={`${styles.pattern} ${dark ? styles.dark : ""} ${
        placement === "seam" ? styles.seam : ""
      }`}
      aria-hidden="true"
      data-variant={variant}
    >
      {Array.from({ length: LINK_COUNT }, (_, index) => {
        const link = links[index % links.length];

        return (
          <span className={styles.link} key={index}>
            {link.pieces.map((piece, at) => (
              <span
                key={`${piece.file}-${at}`}
                className={styles.piece}
                style={
                  {
                    left: `${piece.left}%`,
                    top: `${piece.top}%`,
                    width: `${piece.width}%`,
                    aspectRatio: `${piece.ratio}`,
                    "--period": `${piece.period}s`,
                    // Задержка своя у каждого звена: одинаковая на всех
                    // превратила бы дрейф в общий пульс ленты.
                    "--delay": `${-((index * 3 + at * 5) % 13)}s`,
                    "--dx": `${piece.dx}px`,
                    "--dy": `${piece.dy}px`,
                    "--rot": `${piece.rot}deg`,
                  } as React.CSSProperties
                }
              >
                {/* eslint-disable-next-line @next/next/no-img-element -- см. шапку
                    файла: фрагменты уже мелкие, оптимизатор давал 500 через шлюз */}
                <img
                  src={`/brand/pattern/leaf/${piece.file}.png`}
                  alt=""
                  loading="lazy"
                  decoding="async"
                />
              </span>
            ))}

            {!dark &&
              link.squares.map((square, at) => (
                <span
                  key={`${square.file}-${at}`}
                  className={styles.square}
                  style={
                    {
                      left: `${square.left}%`,
                      top: `${square.top}%`,
                      width: `${square.width}%`,
                      aspectRatio: "1",
                      "--period": `${square.period}s`,
                      "--delay": `${-((index * 2 + at * 3) % 7)}s`,
                      "--sc": square.scale,
                    } as React.CSSProperties
                  }
                >
                  {/* eslint-disable-next-line @next/next/no-img-element -- см. шапку файла */}
                  <img
                    src={`/brand/pattern/leaf/${square.file}.png`}
                    alt=""
                    loading="lazy"
                    decoding="async"
                  />
                </span>
              ))}
          </span>
        );
      })}
    </span>
  );
}

/**
 * Живой паттерн VEDAL — фоновая графика полос.
 *
 * Заменил прежнюю фактуру из крестиков (утилита crossField в globals.css):
 * та тайлила один знак в три слоя на 6% прозрачности и читалась серой рябью.
 * Здесь другой приём — не текстура, а композиция: бледные ветки #e0f9dc
 * и несколько насыщенных квадратов #17af2c, стоящих в их вырезах. Формы те
 * же, что у знака VEDAL, — это по-прежнему одна система знаков, просто
 * нарисованная нормально.
 *
 * ————— почему лента, а не одна картинка —————
 *
 * Раньше паттерн был единым снимком композиции (p1-network.png) с жёсткой
 * пропорцией 501 × 442. Из-за неё он не мог занять полосу по высоте:
 * растянешь по вертикали — во столько же раз вырастет ширина, и поле
 * наедет на текст. Поэтому он стоял пятном, а над ним и под ним оставалась
 * пустота — на первом экране главной больше трёхсот пикселей сверху.
 *
 * Теперь поле собирается из отдельных фрагментов (`/brand/pattern/leaf/`),
 * вырезанных по маске из тех же двух композиций. Ветки складываются
 * в вертикальную ленту звеньями, и лента тянется от верхней границы полосы
 * до нижней при любой её высоте.
 *
 * ————— почему звенья, а не плитка —————
 *
 * Плитка одной картинки даёт видимый стык: у решётки фиксированные
 * относительные позиции, повтор читается ступенькой. Звено здесь — не копия
 * соседнего: чередуются три набора фрагментов, у каждого свой сдвиг
 * по горизонтали и свой квадрат. Соседние звенья не совпадают ни формой,
 * ни ритмом, и лента читается сплошным полем, а не столбиком одинаковых
 * картинок.
 *
 * Звеньев рисуется с запасом на самую высокую полосу; лишние обрезает
 * `overflow: hidden` у ленты, и грузиться они не начинают — `loading="lazy"`
 * тянет картинку, когда она подходит к экрану.
 *
 * ————— почему обычный img, а не next/image —————
 *
 * Фрагменты — прозрачные PNG по 6–11 килобайт, ужимать их нечем: выигрыш
 * от пережатия меньше накладных расходов на запрос к оптимизатору. А запросов
 * лента даёт полтора десятка разом, и на стенде это сразу дало по четыре
 * ошибки 500 на загрузку страницы: шлюз рвал соединение к Next
 * (PrematureCloseException), не дождавшись оптимизированной картинки.
 * Прямая ссылка на файл в /public таких проблем не создаёт вовсе.
 *
 * ————— почему без JS —————
 *
 * Движение целиком на CSS-анимациях: компонент серверный, в браузер не едет
 * ни байта скрипта. Расфазировка сделана отрицательным animation-delay —
 * каждая ветка и каждый квадрат стартуют с середины своего цикла, поэтому
 * лента не пульсирует в такт с первого кадра и без синхронизации таймеров.
 *
 * Темп из motion-спеки пакета: ветки дрейфуют 2–3 px с поворотом до 1°
 * (период 13–26 с), квадраты пульсируют ×1.03–1.04 за 8–11 с. Считывается,
 * если задержать взгляд на несколько секунд, а не при беглом скролле.
 */

type Variant = 1 | 2;

/** Фрагмент внутри звена. Координаты — в процентах от коробки звена. */
type Piece = {
  /** Имя файла в /brand/pattern/leaf/ без расширения. */
  file: string;
  left: number;
  top: number;
  /** Ширина в процентах от ширины ленты; высота — из пропорций файла. */
  width: number;
  /** Пропорция файла, чтобы задать высоту без второго измерения. */
  ratio: number;
  /** Период дрейфа, с. */
  period: number;
  /** Сдвиг по горизонтали и вертикали на пике, px. */
  dx: number;
  dy: number;
  /** Поворот на пике, градусы. */
  rot: number;
};

/** Квадрат-акцент: пульсирует, а не дрейфует. */
type Square = {
  file: string;
  left: number;
  top: number;
  width: number;
  period: number;
  scale: number;
};

/**
 * Звено ленты: ветки плюс, если повезло, квадрат.
 *
 * Высота звена задана в CSS (`--link-height`), позиции внутри — в процентах,
 * поэтому лента одинаково ложится и в узкий стык главной, и в широкий край
 * внутренней страницы.
 */
type Link = { pieces: Piece[]; squares: Square[] };


import Image from "next/image";
import { mediaSrc } from "@/lib/media";

/**
 * Плеер для ролика на странице сайта.
 *
 * Один набор правил на все ролики, потому что ошибиться здесь можно молча
 * и одинаково в каждом месте:
 *
 * - `preload="none"` — файл не тянется у каждого, кто открыл страницу,
 *   только у того, кто нажал «play». Ролики тут по 8–10 МБ.
 * - `poster` обязателен и берётся кадром из самого ролика: без обложки
 *   при `preload="none"` на странице стоит чёрный прямоугольник.
 * - Файла ещё нет — плеера нет вовсе. На его месте статичный кадр-постер:
 *   ни кнопки «play», ни подписи, ни «скоро». Кнопка, которая ничего
 *   не запускает, обещает то, чего нет, а пустой `<video>` в разных
 *   браузерах выглядит по-разному — от чёрного поля до перечёркнутой
 *   кнопки.
 *
 * Разметку вокруг — рамку, пропорции, подпись — задаёт вызывающая сторона
 * своим CSS: на новости ролик вертикальный и стоит в сетке из двух колонок,
 * на «Производстве» он во всю ширину полосы. Общее здесь — поведение, а не
 * размеры.
 *
 * Постер рисуется через `fill`, поэтому у родителя должен быть
 * `position: relative`.
 */
export default function VideoPlayer({
  src,
  poster,
  title,
  sizes,
  caption = false,
}: {
  /** Путь к ролику в хранилище. `null` — файла ещё нет. */
  src: string | null;
  /** Кадр из ролика. Обязателен — см. разбор выше. */
  poster: string;
  /** Чем ролик подписан для читалки экрана, и текст подписи, если она нужна. */
  title: string;
  /** Подсказка `next/image` для постера. */
  sizes?: string;
  /** Показывать ли подпись под плеером. Без файла подписи нет никогда. */
  caption?: boolean;
}) {
  if (!src) {
    return <Image src={mediaSrc(poster)} alt={title} fill quality={90} sizes={sizes} />;
  }

  return (
    <>
      <video
        src={mediaSrc(src)}
        poster={mediaSrc(poster)}
        controls
        playsInline
        preload="none"
        aria-label={title}
      />
      {caption && <figcaption>{title}</figcaption>}
    </>
  );
}

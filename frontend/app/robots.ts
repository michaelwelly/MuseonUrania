import type { MetadataRoute } from "next";

import { publicSite } from "@/lib/seo";

// robots.txt.
//
// Два состояния, и переключает их одна переменная — NEXT_PUBLIC_SITE_URL,
// боевой адрес сайта.
//
// Она пуста — значит это стенд или машина разработчика, и индексирование
// закрыто целиком. Стенд с черновыми текстами в выдаче хуже, чем отсутствие
// сайта: клиент находит несогласованные формулировки, а поисковик потом
// годами держит их в кеше.
//
// Она задана — сайт открыт для обхода, кроме двух мест: `/admin/` — рабочее
// место сотрудника, `/api/` — двери портала. Ни то ни другое не страница
// и в выдаче не нужно.
//
// Запрет в robots.txt — это просьба, а не защита: он не мешает открыть адрес
// напрямую. Доступ к админке закрывается в другом месте — правилом на проксе
// и входом через Keycloak.

export default function robots(): MetadataRoute.Robots {
  if (!publicSite) {
    return { rules: [{ userAgent: "*", disallow: "/" }] };
  }

  return {
    rules: [{ userAgent: "*", allow: "/", disallow: ["/admin/", "/api/"] }],
    sitemap: `${publicSite}/sitemap.xml`,
    host: publicSite,
  };
}

// Три шрифта редизайна. Файлы лежат рядом, в app/fonts, и в репозитории.
//
// Unbounded — заголовки, крупные числа, телефоны, названия изделий. Геометрия
// созвучна начертанию слова VEDAL в логотипе, это и есть причина выбора.
// Commissioner — весь текст, интерфейс, кнопки, поля, навигация.
// JetBrains Mono — служебные подписи: eyebrow, номера, крошки, даты.
//
// ————— почему файлами, а не next/font/google —————
//
// Раньше здесь стоял next/font/google, и это выглядело безобидно: Next скачивает
// шрифты на сборке, в рантайме запросов наружу нет. Но собирается сайт при
// ЗАПУСКЕ контейнера, а не при сборке образа, — значит скачивание происходило
// на каждом старте.
//
// 16 августа 2026 это положило сайт. Google развёл адреса: CSS API стал отдавать
// одни ссылки, а по тем, что просил Next, fonts.gstatic.com начал возвращать 404.
// Сборка падала, контейнер не поднимался, страницы отдавали 500 — при том что
// портал и API отвечали нормально. Внешняя сторона поменяла ссылку, и сайт
// перестал существовать.
//
// Отсюда три следствия, каждое из которых само по себе достаточно:
//
//   * запуск не должен зависеть от чужого CDN. В развёрнутой среде за закрытым
//     периметром интернета может не быть вовсе, и тогда это отказ по построению,
//     а не случайность;
//   * исходящий запрос в Google на каждом старте — вопрос, который лучше снять
//     заранее, чем отвечать на него в министерстве;
//   * воспроизводимость. Сборка, дающая разный результат в зависимости от того,
//     что сегодня лежит на чужом сервере, — не сборка.
//
// ————— почему переменные шрифты —————
//
// Одиннадцать начертаний тремя семействами статикой — это двадцать два файла
// (latin и cyrillic отдельно). Переменный шрифт покрывает весь диапазон весов
// одним файлом со всеми глифами: три файла, 600 КБ вместе, и ни одного
// сабсета, который однажды окажется без нужной буквы.
//
// Файлы взяты из репозитория google/fonts (лицензия OFL) и пережаты в woff2:
// TTF оттуда весят 1,7 МБ на троих, woff2 — 600 КБ.

import localFont from "next/font/local";

export const unbounded = localFont({
  src: "./fonts/Unbounded.woff2",
  // Диапазон, а не список: файл переменный, промежуточные веса берутся из него
  // же. Указан тот диапазон, которым пользуется вёрстка, — заявить весь
  // 100–900 значило бы разрешить браузеру веса, которых дизайн не знает.
  weight: "300 600",
  style: "normal",
  variable: "--font-display",
  display: "swap",
});

export const commissioner = localFont({
  src: "./fonts/Commissioner.woff2",
  weight: "300 700",
  style: "normal",
  variable: "--font-body",
  display: "swap",
});

export const mono = localFont({
  src: "./fonts/JetBrainsMono.woff2",
  weight: "400 500",
  style: "normal",
  variable: "--font-mono",
  display: "swap",
});

export const fontVariables = `${unbounded.variable} ${commissioner.variable} ${mono.variable}`;

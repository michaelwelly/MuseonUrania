"use client";

// Тумблер публикации.
//
// Кнопка «Опубликовать» / «Снять» отвечала на вопрос «что случится», а глазами
// список читают на вопрос «что сейчас»: чтобы узнать, опубликовано ли изделие,
// приходилось прочитать кнопку и вывернуть её наизнанку. Тумблер показывает
// состояние, а меняет его нажатием.
//
// Подпись рядом обязательна и не декоративна. Положение тумблера — это одна
// примета, и притом чисто зрительная: на чёрно-белом экране, при слабом
// зрении и в дереве доступности она не читается. Подпись словом читается
// везде.
//
// Отмена живёт не здесь, а в полосе-сообщении: снятое с публикации
// возвращается дольше, чем публикуется, и путь назад должен быть под рукой,
// а не в журнале.

export function Toggle({
  on,
  busy,
  what,
  onChange,
}: {
  on: boolean;
  busy?: boolean;
  /** Что именно переключается — попадает в подпись для чтения вслух. */
  what: string;
  onChange: (on: boolean) => void;
}) {
  return (
    <span className="toggle">
      <button
        type="button"
        role="switch"
        aria-checked={on}
        aria-label={`${on ? "Снять с публикации" : "Опубликовать"}: ${what}`}
        className={`toggle__box${on ? " toggle__box--on" : ""}`}
        disabled={busy}
        onClick={() => onChange(!on)}
      >
        <span className="toggle__dot" />
      </button>
      <span className={`toggle__word${on ? " toggle__word--on" : ""}`}>
        {on ? "опубликовано" : "черновик"}
      </span>
    </span>
  );
}

// Кружок с инициалами.
//
// Фотографий сотрудников в портале нет и, скорее всего, не будет: заводит
// людей консоль системы входа, а не админка, и снимок туда никто не грузит.
// Инициалы — не заглушка под фото, а то, чем список сотрудников читается
// на самом деле: в строке журнала имя стоит рядом, и кружок нужен, чтобы
// глаз находил повтор одного и того же человека, не перечитывая строку.
//
// Размер задаётся ступенями, а не числом: кружок стоит в пяти местах —
// карточка сделки, строка журнала, шапка, карточка сотрудника, профиль, —
// и каждое «тут чуть побольше» числом возвращает ту самую россыпь кеглей,
// которую сводили прошлой сессией.
//
// ───────────────────────────────────────────────────────────────────────────
// Точка присутствия
//
// В макете она означает «в сети / отошёл / отключён». Портал такого не знает:
// в `StaffMember` есть только `enabled` — заведена ли учётная запись, — и это
// не присутствие. Зелёная точка у человека, ушедшего вчера, — выдуманный факт
// в интерфейсе, где рядом стоят настоящие суммы сделок.
//
// Поэтому точка рисуется серой, а подпись говорит, чего именно не хватает.
// Появится дверь присутствия — поменяется цвет, а не разметка.

export type Presence = "unknown" | "off";

const РАЗМЕР = { s: "avatar--s", m: "avatar--m", l: "avatar--l", xl: "avatar--xl" } as const;

export function Avatar({
  name,
  size = "m",
  presence,
  tone = "person",
}: {
  /** Имя или логин. Пусто не бывает: у учётной записи всегда есть хотя бы логин. */
  name: string;
  size?: keyof typeof РАЗМЕР;
  /** Без пропа точки нет вовсе — в журнале и на карточке сделки она лишняя. */
  presence?: Presence;
  /** Ведалина и портал — не люди, и красить их фирменным зелёным незачем. */
  tone?: "person" | "machine";
}) {
  return (
    <span className={`avatar ${РАЗМЕР[size]} avatar--${tone}`} aria-hidden="true">
      {initials(name)}
      {presence && (
        <span
          className={`avatar__dot avatar__dot--${presence}`}
          title={
            presence === "off"
              ? "учётная запись отключена"
              : "присутствие ожидает уточнения: портал его не хранит"
          }
        />
      )}
    </span>
  );
}

/**
 * Инициалы из имени или логина.
 *
 * Разделители — всё, что не буква и не цифра: имя приходит и как
 * «Ирина Кольцова», и как `i.koltsova`, и как `deal-bot`. Берём первые буквы
 * первых двух кусков; из одного слова — одну букву, а не две первых буквы
 * слова: «Ир» читается как обрезанное имя, «И» — как инициал.
 *
 * Регистр приводится явно: логины приходят строчными, и «ик» в кружке
 * выглядит опечаткой.
 */
export function initials(name: string): string {
  const куски = name.split(/[^\p{L}\p{N}]+/u).filter(Boolean);
  if (куски.length === 0) return "?";
  return куски
    .slice(0, 2)
    .map((кусок) => [...кусок][0].toUpperCase())
    .join("");
}

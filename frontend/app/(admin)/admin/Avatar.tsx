"use client";

import { usePortrait } from "./portraits";

// Кружок: портрет, если он есть, иначе инициалы.
//
// Здесь раньше стояло: «фотографий сотрудников в портале нет и, скорее
// всего, не будет — заводит людей консоль системы входа, а не админка».
// Рассуждение было верным про то, КТО заводит учётную запись, и неверным
// про портрет: владелец портала попросил дать сотруднику поставить себе
// лицо (issue #93), и портал завёл для этого собственное хранение —
// в токене портрета нет.
//
// Инициалы при этом никуда не делись и заглушкой не стали. Портрет есть
// не у всех и не появится у всех: в строке журнала имя стоит рядом,
// и кружок нужен, чтобы глаз находил повтор одного и того же человека,
// не перечитывая строку. Букву эту работу делает не хуже лица.
//
// Портрет приезжает по логину, а не приходит пропом. Причина в том, где
// стоят кружки: журнал, карточка сделки, справочник и шапка — четыре
// разных экрана с четырьмя разными источниками данных, и провести портрет
// через каждый значило бы добавить его в четыре типа ответа портала.
// Логин в этих ответах уже есть.
//
// Размер задаётся ступенями, а не числом: кружок стоит в пяти местах —
// карточка сделки, строка журнала, шапка, карточка сотрудника, профиль, —
// и каждое «тут чуть побольше» числом возвращает ту самую россыпь кеглей,
// которую сводили прошлой сессией.
//
// ───────────────────────────────────────────────────────────────────────────
// Точка присутствия
//
// В макете она означает «в сети / отошёл / отключён». Портал такого не знает:
// в `StaffMember` есть только `enabled` — заведена ли учётная запись, — и это
// не присутствие. Зелёная точка у человека, ушедшего вчера, — выдуманный факт
// в интерфейсе, где рядом стоят настоящие суммы сделок.
//
// Поэтому точка рисуется серой, а подпись говорит, чего именно не хватает.
// Появится дверь присутствия — поменяется цвет, а не разметка.

export type Presence = "unknown" | "off";

const РАЗМЕР = { s: "avatar--s", m: "avatar--m", l: "avatar--l", xl: "avatar--xl" } as const;

export function Avatar({
  name,
  login,
  size = "m",
  presence,
  tone = "person",
}: {
  /** Имя или логин. Пусто не бывает: у учётной записи всегда есть хотя бы логин. */
  name: string;
  /**
   * Чей это кружок. Без него портрета не будет вовсе — только буква:
   * у Ведалины и у портала логина нет, и спрашивать за них нечего.
   */
  login?: string | null;
  size?: keyof typeof РАЗМЕР;
  /** Без пропа точки нет вовсе — в журнале и на карточке сделки она лишняя. */
  presence?: Presence;
  /** Ведалина и портал — не люди, и красить их фирменным зелёным незачем. */
  tone?: "person" | "machine";
}) {
  const портрет = usePortrait(login);

  return (
    <span
      className={`avatar ${РАЗМЕР[size]} avatar--${tone}${портрет ? " avatar--photo" : ""}`}
      aria-hidden="true"
    >
      {/* alt пустой намеренно: кружок целиком скрыт от чтения с экрана
          (aria-hidden), потому что имя всегда стоит рядом текстом.
          Портрет, объявленный «фотографией такого-то», заставил бы
          прочитать имя дважды. */}
      {портрет ? (
        // eslint-disable-next-line @next/next/no-img-element
        <img className="avatar__photo" src={портрет} alt="" width={256} height={256} />
      ) : (
        initials(name)
      )}
      {presence && (
        <span
          className={`avatar__dot avatar__dot--${presence}`}
          title={
            presence === "off"
              ? "учётная запись отключена"
              : "присутствие не отслеживается"
          }
        />
      )}
    </span>
  );
}

/**
 * Инициалы из имени или логина.
 *
 * Разделители — всё, что не буква и не цифра: имя приходит и как
 * «Ирина Кольцова», и как `i.koltsova`, и как `deal-bot`. Берём первые буквы
 * первых двух кусков; из одного слова — одну букву, а не две первых буквы
 * слова: «Ир» читается как обрезанное имя, «И» — как инициал.
 *
 * Регистр приводится явно: логины приходят строчными, и «ик» в кружке
 * выглядит опечаткой.
 */
export function initials(name: string): string {
  const куски = name.split(/[^\p{L}\p{N}]+/u).filter(Boolean);
  if (куски.length === 0) return "?";
  return куски
    .slice(0, 2)
    .map((кусок) => [...кусок][0].toUpperCase())
    .join("");
}

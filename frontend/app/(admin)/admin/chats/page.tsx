// Разговоры посетителей.
//
// Единственный экран портала, где на том конце ждёт человек. Отсюда две вещи
// на экране: очередь — кому отвечать, и разговор — что говорили и что
// ответить. Всё остальное подчинено этим двум.
//
// ───────────────────────────────────────────────────────────────────────────
// Почему две колонки, а не три
//
// Третьей колонкой были «сведения о посетителе», и на живом стенде она
// оказалась худшим местом на экране: при незанятом разговоре в ней стояла
// надпись «здесь будет то, что известно», а при занятом — пять строк,
// ради которых держалась треть ширины. Переписка в это время ломалась
// на четыре строки в средней колонке, потому что ширины ей не досталось.
//
// Сведения никуда не делись — они переехали в шапку разговора, к которому
// относятся. Там они занимают две строки вместо колонки и появляются ровно
// тогда, когда разговор открыт.
//
// ───────────────────────────────────────────────────────────────────────────
// Почему очередь прокручивается вместе со страницей
//
// Раньше у неё была своя полоса прокрутки высотой в экран минус шапка:
// на мониторе 1440×900 в неё помещалось четыре карточки из двадцати одной,
// на ноутбуке 1024×800 — три. Очередь, которую нельзя окинуть взглядом, —
// это не очередь, а замочная скважина: дежурный не видит, сколько людей
// ждёт, и не может выбрать, кому ответить первым.
//
// Теперь список — часть страницы, а колонка разговора липкая. Прокрутка
// одна на весь экран, разговор при этом остаётся на месте: выбранный
// человек не уезжает вверх, пока листаешь очередь.
//
// ───────────────────────────────────────────────────────────────────────────
// Почему первый ждущий открывается сам
//
// Пустой экран с надписью «выберите разговор слева» — это работа, которую
// интерфейс переложил на человека, зная ответ. Дежурный заходит сюда, чтобы
// ответить тому, кто ждёт дольше всех; ровно этот разговор и открывается.
// Выбор при этом остаётся за человеком — открытое можно сменить одним
// щелчком, и адресная ссылка `?id=…` сильнее самооткрытия.
//
// ───────────────────────────────────────────────────────────────────────────
// Почему первая строка обращения читается отдельно
//
// `ChatCard` несёт статус, страницу и время, но не текст: список разговоров
// не тащит переписку. А очередь без первой строки — это столбик одинаковых
// карточек, из которого нельзя выбрать, кому ответить первым.
//
// Строка вытягивается лентой по каждой карточке и запоминается: первое
// сообщение посетителя не меняется никогда, и перечитывать его на каждое
// событие потока незачем.
//
// ───────────────────────────────────────────────────────────────────────────
// Чего здесь нет и почему
//
// Заполнения графика. Плашка «ДЕЖУРИТ СЕГОДНЯ» с кнопкой «Передать» здесь
// есть (компонент Duty), а вот кто дежурит на следующей неделе — работа
// экрана «Дежурство». Дублировать её в шапке чужого раздела значит завести
// второе место, где меняется одно и то же.
//
// Присутствие при этом остаётся отдельным фактом и никуда не делось:
// в виджете посетителя написано, есть ли сейчас кто-то на связи, — открыто
// ли хоть одно рабочее место. Считает его ChatStream, и открытая эта
// страница как раз и означает «человек смотрит в экран». Часы работы
// поддержки лежат в настройках портала (vedal.support.*), и по ним же
// портал решает, считать ли отсутствие дежурного расхождением.
//
// Фильтра «с Ведалиной». Портал отдаёт две выборки — очередь ждущих и все
// разговоры. Третью пришлось бы собирать в браузере из загруженной страницы,
// и счётчик у неё считал бы страницу, а не разговоры.
//
// Кнопки «В заявку». Двери, которая заводит заявку из разговора, у портала
// нет: заявка несёт согласие с версией текста, а разговор его не несёт.
// Это не кнопка, а решение — что считать согласием.

/** Сколько разговоров просить за раз. Дальше — кнопкой «Показать ещё». */
const ЗА_РАЗ = 50;

export default function ChatsPage() {
  // Разговор адресуем: `/admin/chats/?id=…` открывает ленту сразу.
  // Понадобилось виджету в оболочке, но польза шире: разговор стал вещью,
  // на которую можно дать ссылку в переписке между сотрудниками.
  //
  // Suspense обязателен: без границы useSearchParams уводит страницу
  // в отрисовку на клиенте целиком, и сборка об этом предупреждает.
  return (
    <Suspense fallback={<p className="muted">Загружаем…</p>}>
      <Chats />
    </Suspense>
  );
}

function Chats() {
  const params = useSearchParams();
  // По умолчанию — ВСЕ разговоры, свежие сверху, а не очередь ожидающих.
  //
  // Сначала было наоборот, и это была ошибка замысла: очередь показывает
  // только тех, кому Ведалина не смогла ответить. Разговор, который идёт
  // прямо сейчас и по которому она справляется, в неё не попадает — и экран,
  // сделанный чтобы видеть посетителей вживую, ровно их и прятал.
  const [tab, setTab] = useState<"all" | "queue">("all");
  // Разговор из адреса — только начальное значение: дальше выбор ведёт
  // состояние. Иначе кнопка «назад» в браузере возвращала бы не на прошлый
  // разговор, а на прошлый адрес, и они разъехались бы на первом же щелчке.
  const [open, setOpen] = useState<string | null>(() => params.get("id"));
  // Разговор, названный адресом, самооткрытием не сбивается: по такой ссылке
  // приходят из виджета и из переписки между сотрудниками, и подменять его
  // «первым ждущим» значит открывать не то, за чем пришли.
  const адресный = useRef<string | null>(params.get("id"));
  // Ответственный приходит адресом — с карточки сотрудника. В очереди этого
  // отбора нет и не будет: в ней по определению лежат невзятые разговоры.
  const owner = params.get("owner") ?? "";
  // Меняется на каждое событие из потока — по нему перезагружаются и список,
  // и лента. Отдельный счётчик, а не время: время сравнивается неточно, если
  // два события пришли в одну миллисекунду.
  const [beat, setBeat] = useState(0);
  const [now, setNow] = useState(() => Date.now());
  const [size, setSize] = useState(ЗА_РАЗ);

  const { data, error } = useLoad<Page<ChatCard>>(
    () => (tab === "queue" && !owner ? chatQueue(0, size) : chatsAll(owner, 0, size)),
    `${tab}:${owner}:${size}:${beat}`,
  );

  // Число ждущих нужно и когда открыта вкладка «Все»: это единственный
  // счётчик экрана, который означает работу прямо сейчас. Под отбором
  // по сотруднику он не спрашивается вовсе — вкладок там нет, а число
  // «сколько ждут во всём портале» рядом с чужим именем читается неверно.
  const { data: queue } = useLoad<Page<ChatCard> | null>(
    () => (owner ? Promise.resolve(null) : chatQueue(0, 1)),
    `queue-count:${owner}:${beat}`,
  );

  // Кто печатает прямо сейчас: идентификатор разговора и когда пришло событие.
  // Надпись живёт секунды и гаснет сама — сообщения «перестал печатать» нет
  // и быть не может: человек может просто закрыть вкладку.
  const [typingIn, setTypingIn] = useState<string | null>(null);
  const fade = useRef<ReturnType<typeof setTimeout> | null>(null);

  const onTyping = useCallback((conversationId: string) => {
    setTypingIn(conversationId);
    if (fade.current) clearTimeout(fade.current);
    fade.current = setTimeout(() => setTypingIn(null), 5000);
  }, []);

  useEffect(() => () => {
    if (fade.current) clearTimeout(fade.current);
  }, []);

  // Время ожидания тикает раз в минуту: «4 мин» иначе застывает на том
  // значении, что было при открытии экрана, а экран открыт весь день.
  useEffect(() => {
    const timer = setInterval(() => setNow(Date.now()), 60_000);
    return () => clearInterval(timer);
  }, []);

  // Поток теперь общий на всю админку (LiveHost в оболочке): раздел
  // «Разговоры» — один из его слушателей, а не владелец. Свой поток
  // рядом с общим означал бы два соединения с одной вкладки, а у портала
  // на них стоят пределы.
  useLive({
    changed: () => setBeat((b) => b + 1),
    typing: onTyping,
  });

  const rows = useMemo(() => data?.items ?? [], [data]);
  const first = useFirstLines(rows);

  // Первый ждущий открывается сам. Пустые две трети экрана с надписью
  // «выберите разговор слева» — это вопрос, на который интерфейс знает
  // ответ: дежурный пришёл сюда ответить тому, кто ждёт дольше всех.
  useEffect(() => {
    if (rows.length === 0) return;
    setOpen((было) => {
      if (было && (было === адресный.current || rows.some((c) => c.id === было))) return было;
      // Ждущие уже отсортированы порталом — дольше всех ждущий первый.
      return (rows.find((c) => c.status === "waiting") ?? rows[0]).id;
    });
  }, [rows]);

  const выбран = rows.find((c) => c.id === open) ?? null;

  // Выбор карточки подводит к разговору, если его не видно целиком.
  //
  // Два случая, и оба настоящие. Узкий экран: колонка разговора лежит под
  // очередью, и щелчок по карточке без подводки выглядит как «ничего не
  // произошло». Широкий: колонка липкая и ростом в экран, но у самого верха
  // страницы она ещё не прилипла — над ней стоит шапка раздела, и поле
  // ответа оказывается ниже сгиба. Одна прокрутка ставит рабочее место
  // на место, и делать её руками при каждом заходе незачем.
  const лента = useRef<HTMLElement>(null);

  function выбрать(id: string) {
    адресный.current = null;
    setOpen(id);
    const узел = лента.current;
    if (!узел) return;
    const место = узел.getBoundingClientRect();
    const видна_целиком = место.top >= 0 && место.bottom <= window.innerHeight;
    if (!видна_целиком) узел.scrollIntoView({ block: "start", behavior: "smooth" });
  }

  return (
    <>
      <div className="admin-head">
        <h1>Разговоры</h1>
        {/* Предупреждение о персональных данных стоит в самой шапке, а не
            строкой под ней. Оно обязано быть на виду — человек должен видеть
            его до того, как сделает снимок экрана для переписки, — но своя
            строка стоила сорока шести пикселей высоты, а высота здесь идёт
            переписке и полю ответа. */}
        <p className="admin-pd">На экране могут быть персональные данные</p>
        {/* Дежурство: имя, присутствие и передача смены. Раньше здесь стояло
            «ожидает уточнения» — портал не знал, кто сегодня на линии,
            и выдумать это было нельзя: по имени передают разговоры. */}
        <Duty />
      </div>

      {owner && (
        <p className="admin-hint">
          {/* «-» — это «никто не взял», а не логин с таким именем. */}
          {owner === "-" ? (
            <>Показаны разговоры, которых никто не взял. </>
          ) : (
            <>
              Показаны разговоры одного сотрудника: <span className="mono">{owner}</span>.{" "}
            </>
          )}
          <Link href="/admin/chats/">Показать все</Link>
        </p>
      )}

      <Note kind="error">{error}</Note>

      <div className="chats3">
        <aside className="chats3__queue">
          {/* Под отбором по сотруднику вкладок нет. Очередь — это невзятые
              разговоры, у них ответственного нет по определению, и вкладка
              «Ждут ответа» рядом с отобранным списком либо показывала бы
              не то, что выделено, либо считала бы всех подряд: «1» на ней
              означало бы одного ждущего в портале, а прочитано было бы как
              «один ждёт у этого сотрудника». */}
          {!owner && (
          <div className="chips">
            <span className={`chip${tab === "queue" ? " chip--on" : ""}`}>
              <button
                type="button"
                className="chip__pick"
                aria-pressed={tab === "queue"}
                onClick={() => setTab("queue")}
              >
                Ждут ответа
                {queue && <span className="chip__count mono">{queue.total}</span>}
              </button>
            </span>
            <span className={`chip${tab === "all" ? " chip--on" : ""}`}>
              <button
                type="button"
                className="chip__pick"
                aria-pressed={tab === "all"}
                onClick={() => setTab("all")}
              >
                Все
                {data && tab === "all" && <span className="chip__count mono">{data.total}</span>}
              </button>
            </span>
          </div>
          )}

          {rows.length === 0 && (
            <p className="admin-hint">
              {owner === "-"
                ? "Невзятых разговоров нет."
                : owner
                ? "На этом сотруднике разговоров нет."
                : tab === "queue"
                  ? "Никто не ждёт ответа."
                  : "Разговоров пока не было."}
            </p>
          )}

          <ul className="talks">
            {rows.map((c) => {
              const мин = Math.max(0, Math.floor((now - new Date(c.lastAt).valueOf()) / 60_000));
              const ждёт = c.status === "waiting";
              return (
                <li key={c.id}>
                  <button
                    type="button"
                    className={`talk${open === c.id ? " talk--on" : ""}`}
                    aria-current={open === c.id}
                    onClick={() => выбрать(c.id)}
                  >
                    {/* Точка — это то же, что и слово справа, а не вместо него:
                        цветом состояние читается краем глаза при беглом
                        просмотре очереди, словом — тем, кто цвета не
                        различает. */}
                    <span className={`talk__mark talk__mark--${c.status}`} aria-hidden="true" />
                    <span className="talk__body">
                      <span className="talk__first">{first[c.id] ?? "обращение читается…"}</span>
                      <span className="talk__where mono">{where(c.page)}</span>
                    </span>
                    <span className="talk__meta">
                      <span className="talk__state">{label(CHAT_STATUS, c.status)}</span>
                      {/* Дольше пяти минут — это уже не «сейчас ответят». */}
                      <span
                        className={`talk__waited mono${ждёт && мин >= 5 ? " talk__waited--late" : ""}`}
                      >
                        {waited(мин)}
                      </span>
                    </span>
                  </button>
                </li>
              );
            })}
          </ul>

          {/* Список постраничный, и молчать об этом нельзя: «показано 50»
              без числа всего читается как «всего 50», и дежурный не узнает
              о тех, кто за краем. */}
          {data && data.total > rows.length && (
            <button
              type="button"
              className="btn btn--small talks__more"
              onClick={() => setSize((было) => было + ЗА_РАЗ)}
            >
              Показать ещё — здесь {rows.length} из {data.total}
            </button>
          )}
        </aside>

        <section className="chats3__thread" ref={лента}>
          {open ? (
            <>
              {/* Сведения о посетителе — шапкой разговора, а не колонкой:
                  они относятся к открытому разговору и без него не значат
                  ничего. */}
              {выбран && <Про card={выбран} onDone={() => setBeat((b) => b + 1)} />}
              <Thread
                key={open}
                id={open}
                beat={beat}
                typing={typingIn === open}
                onDone={() => setBeat((b) => b + 1)}
              />
            </>
          ) : (
            <p className="chats3__idle">
              {rows.length === 0
                ? "Разговоров нет — открывать нечего."
                : "Выберите разговор в очереди слева."}
            </p>
          )}
        </section>
      </div>
    </>
  );
}

/**
 * Первые строки обращений — по одной на разговор, и только по разу.
 *
 * Первое сообщение посетителя не меняется никогда, поэтому прочитанное
 * запоминается. Без этого поток событий — а он приходит на каждое сообщение
 * в любом разговоре — перечитывал бы двадцать лент на каждое чужое «спасибо».
 *
 * Читается по двенадцать за заход, и заходов столько, сколько нужно.
 * Раньше заход был один: эффект зависел от списка идентификаторов, а он
 * после загрузки страницы не менялся — и карточки с тринадцатой по двадцать
 * первую навсегда оставались с надписью «обращение читается…». Не видел
 * этого никто ровно потому, что в узкую колонку помещалось четыре карточки
 * и до тринадцатой никто не долистывал.
 */
function useFirstLines(rows: readonly ChatCard[]): Record<string, string> {
  const [lines, setLines] = useState<Record<string, string>>({});
  const known = useRef(new Set<string>());
  // Счётчик заходов: список идентификаторов после загрузки не меняется,
  // и без него эффект не повторился бы ни разу.
  const [заход, setЗаход] = useState(0);
  const ids = rows.map((c) => c.id).join(",");

  useEffect(() => {
    const свежие = ids
      .split(",")
      .filter(Boolean)
      .filter((id) => !known.current.has(id))
      .slice(0, 12);
    if (свежие.length === 0) return;

    свежие.forEach((id) => known.current.add(id));
    let alive = true;

    void Promise.allSettled(свежие.map((id) => chatThread(id))).then((ленты) => {
      if (!alive) return;
      const добавка: Record<string, string> = {};
      ленты.forEach((лента, i) => {
        if (лента.status !== "fulfilled") {
          // Не прочиталось — пусть попробует ещё раз со следующим заходом.
          known.current.delete(свежие[i]);
          return;
        }
        const первое = лента.value.messages.find((m) => m.author === "visitor");
        добавка[свежие[i]] = первое ? первое.body : "посетитель пока молчит";
      });
      setLines((было) => ({ ...было, ...добавка }));
      // Следующая дюжина — только если эта дюжина хоть что-то дала.
      //
      // Условие держит заходы конечными. Отказавшиеся ленты возвращаются
      // в непрочитанные, и без него портал, отвечающий отказом на всё,
      // получал бы двенадцать запросов по кругу и навсегда. Заход без
      // единой прочитанной ленты — это и есть «портал сейчас не отвечает»:
      // следующая попытка будет со следующим обновлением списка.
      if (Object.keys(добавка).length > 0) setЗаход((n) => n + 1);
    });

    return () => {
      alive = false;
    };
  }, [ids, заход]);

  return lines;
}

/**
 * Что известно о посетителе — шапкой над перепиской.
 *
 * Всё из карточки разговора: больше портал не знает. Раньше это была третья
 * колонка во всю высоту экрана ради пяти строк; теперь две строки над лентой,
 * которой досталась освободившаяся ширина.
 */
function Про({ card, onDone }: { card: ChatCard; onDone: () => void }) {
  return (
    <header className="talk-head">
      <div className="talk-head__top">
        <span className={`badge ${БЕЙДЖ[card.status] ?? ""}`}>
          {label(CHAT_STATUS, card.status)}
        </span>
        <span className="talk-head__owner">
          {card.owner ? (
            <>
              ведёт <span className="mono">{card.owner}</span>
            </>
          ) : (
            <span className="nobody">никто не взял</span>
          )}
        </span>
      </div>

      {/* У каждой пустоты своё слово, и это не украшение.
          «Ожидает уточнения» означает «данные должны быть, но их нет
          и кто-то должен внести». Разговор без ответственного не ждёт
          уточнения — его просто никто не взял, и это состояние, а не
          пробел. Разговор без кампании пришёл сам, и уточнять там
          нечего. Пометив всё одним словом, метка перестаёт значить
          что-либо, а вместе с ней и «ожидает уточнения» на карточке
          изделия. */}
      <dl className="talk-head__facts">
        <Факт name="Страница" value={card.page} empty="не записана" />
        <Факт
          name="Язык"
          value={card.language ? label(LEAD_LANGUAGE, card.language) : null}
          empty="не записан"
        />
        <Факт name="Кампания" value={card.campaign} empty="пришёл сам, без кампании" />
        <Факт name="Начат" value={when(card.startedAt)} />
      </dl>

      {/* Обращение по переписке исполняется здесь: посетитель мог написать
          своё имя и телефон прямо в чат, и обычно именно так и делает.
          Свёрнуто намеренно: необратимое действие не должно стоять
          в одном ряду с «Ответить». */}
      <details className="talk-head__pd">
        <summary>Персональные данные</summary>
        <p className="triage__note">
          Больше портал о посетителе не знает: имя и телефон он называет сам, в переписке.
          Двери, которая завела бы из разговора заявку, нет — заявка несёт согласие
          с версией текста, а разговор его не несёт.
        </p>
        <EraseData
          what="тексты всех сообщений — и посетителя, и Ведалины, и сотрудника"
          erase={() => eraseChatData(card.id)}
          onDone={onDone}
        />
      </details>
    </header>
  );
}

const БЕЙДЖ: Record<string, string> = {
  waiting: "badge--warn",
  attended: "badge--on",
  closed: "badge--off",
};

/** Пара «ключ — значение». Незаполненное названо своими словами. */
function Факт({
  name,
  value,
  empty = "не указано",
}: {
  name: string;
  value: string | null;
  empty?: string;
}) {
  return (
    <div className="talk-head__fact">
      <dt>{name}</dt>
      <dd className={value ? "mono" : "nobody"}>{value ?? empty}</dd>
    </div>
  );
}

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

// Сторож сброса у кнопок, которые притворяются строками списка.
//
// У `<button>` есть собственное оформление браузера, и снимать его надо
// целиком: фон ButtonFace, рамка 2px outset, шрифт Arial 13.3px,
// `text-align: center` и ширина по содержимому. Пропустить одно свойство
// значит получить не «почти строку», а нечто третье — и ошибка эта тихая,
// потому что в вёрстке всё на месте, а в браузере строка выглядит бугорком.
//
// Замер на живом стенде 8 сентября: у `.widget__row` не было сброшено ничего,
// кроме нижней рамки. Разговоры в панели выглядели столбиком серых кнопок
// с текстом по центру — владелец назвал это лесенкой, и был прав.
//
// Список селекторов ведётся руками намеренно. Найти «кнопки, которые должны
// выглядеть строкой» по одному CSS нельзя: это решение разметки, а не стиля,
// и автоматический обход либо пропустил бы половину, либо требовал бы сброса
// от кнопок, которые обязаны выглядеть кнопками.

const СТРОКИ_КНОПКАМИ = [".talk", ".widget__row"];

// Что обязано быть сброшено и почему именно это.
const СБРОС: Record<string, string> = {
  background: "фон ButtonFace — серый бугорок вместо строки списка",
  border: "рамка 2px outset — рант вокруг каждой строки",
  font: "Arial 13.3px вместо шрифта портала",
  color: "цвет ButtonText вместо цвета текста",
  "text-align": "текст по центру — та самая лесенка",
  width: "ширина по содержимому: у каждой строки своя",
  cursor: "стрелка вместо руки: строка не выглядит нажимаемой",
};

function rule(css: string, selector: string): string {
  // Только объявление самого селектора, без модификаторов и вложений.
  const found = new RegExp(`(^|\\})\\s*\\${selector}\\s*\\{([^}]*)\\}`, "m").exec(css);
  if (!found) throw new Error(`правила ${selector} нет в admin.css`);
  return found[2];
}

describe("кнопки, которые притворяются строками списка", () => {
  const css = readFileSync(
    join(import.meta.dirname ?? ".", "admin.css"),
    "utf8",
  );

  for (const selector of СТРОКИ_КНОПКАМИ) {
    it(`${selector} снимает с кнопки всё её собственное оформление`, () => {
      const block = rule(css, selector);
      const пропущено = Object.entries(СБРОС)
        .filter(([property]) => !new RegExp(`(^|;|\\s)${property}\\s*:`, "m").test(block))
        .map(([property, why]) => `${property} — ${why}`);

      expect(пропущено, `${selector}: сброс неполон`).toEqual([]);
    });
  }
});

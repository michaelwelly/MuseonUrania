// Человеческие названия для значений, которые в базе английские.
//
// ————— зачем один файл —————
//
// Словари были и раньше, но по одному на страницу: свой в сделках, свой
// в разговорах, свой в истории. От этого они и расходятся — «в работе»
// на одном экране и «in_progress» на соседнем, потому что второй словарь
// забыли дописать. Сотрудник видит два разных слова про одно и то же
// и перестаёт доверять обоим.
//
// Здесь один источник. Значения не переводятся вольно: они взяты из
// ограничений схемы (deal_stage_check, lead status, form) — если в базе
// появится новое, оно проявится сырым, и это правильно: лучше увидеть
// «qualified» и дописать строку, чем показать пустое место.
//
// ————— почему не на сервере —————
//
// Портал отдаёт значения как есть, потому что они часть контракта: по ним
// фильтруют, сортируют и считают аналитику. Перевод — забота интерфейса,
// и разные интерфейсы вольны называть их по-разному. Отдай сервер сразу
// «В работе» — и фильтр по статусу пришлось бы строить по русской строке.

/** Значение неизвестно словарю — показываем как есть, а не пустоту. */
export function label(dictionary: Record<string, string>, value: string | null): string {
  if (!value) return "—";
  return dictionary[value] ?? value;
}


"use client";

import { useEffect, useState } from "react";
import { avatarOf } from "@/lib/admin";

// Портреты сотрудников — один запрос на человека, а не на кружок.
//
// ————— зачем кеш вообще —————
//
// Кружок стоит в пяти местах, и в двух из них он повторяется десятками:
// страница журнала показывает восемь записей подряд, список сделок —
// столько же. Без общего хранилища каждый кружок ходил бы в портал сам,
// и открытие журнала стоило бы двадцати запросов за одним и тем же лицом.
//
// ————— почему blob:, а не адрес в src —————
//
// Дверь портрета закрыта токеном, а браузер, идя по адресу в src, токена
// не прикладывает: закрытая дверь ответила бы отказом, а открытая означала
// бы портрет сотрудника, доступный по ссылке. Поэтому байты приезжают
// обычным запросом с заголовком Authorization и превращаются в blob: —
// адрес, который живёт в этой вкладке и никуда не уходит.
//
// ————— почему модуль, а не контекст —————
//
// Провайдер над оболочкой давал бы то же самое, но требовал бы, чтобы
// каждый кружок стоял под ним. Кружок в журнале, в сделке и в шапке —
// три разных дерева; общий провайдер пришлось бы поднимать до корня
// админки и помнить об этом при каждом переносе компонента.

/** Логин → адрес blob: или null, если портрета нет. */
const кеш = new Map<string, string | null>();

/** Запросы в полёте: два кружка одного человека не спрашивают дважды. */
const вПути = new Map<string, Promise<void>>();

/** Смонтированные кружки — им сообщают, что кеш изменился. */
const подписчики = new Set<() => void>();

function разослать() {
  for (const сообщить of [...подписчики]) сообщить();
}

async function спросить(login: string): Promise<void> {
  if (кеш.has(login)) return;

  const идёт = вПути.get(login);
  if (идёт) return идёт;

  const запрос = avatarOf(login)
    .then((blob) => {
      кеш.set(login, blob ? URL.createObjectURL(blob) : null);
    })
    .catch(() => {
      // Портал не ответил. Это не «портрета нет», но в кружке разница
      // не выражается ничем: остаётся буква. Запоминаем отказ как
      // отсутствие намеренно — иначе подписчики, разбуженные неудачей,
      // спросили бы снова, и снова, и снова. Обновление страницы
      // спрашивает заново.
      кеш.set(login, null);
    })
    .finally(() => {
      вПути.delete(login);
      разослать();
    });

  вПути.set(login, запрос);
  return запрос;
}

/**
 * Забыть портрет: он только что заменён или убран.
 *
 * Зовётся со страницы профиля после загрузки и удаления. Без этого кружок
 * в шапке показывал бы прежнее лицо до перезагрузки страницы — то есть
 * человек нажал бы кнопку и не увидел результата.
 */
export function forgetPortrait(login: string) {
  const прежний = кеш.get(login);
  if (прежний) URL.revokeObjectURL(прежний);
  кеш.delete(login);
  вПути.delete(login);
  разослать();
}

/**
 * Портрет сотрудника или null, пока его нет или он ещё едет.
 *
 * Ожидание не отличается от отсутствия, и это сделано нарочно: на месте
 * портрета всё это время стоит кружок с буквой — то, что человек и увидел
 * бы, не будь у него портрета. Показывать вместо него мигающую заглушку
 * значит рисовать загрузку там, где нечего ждать.
 */
export function usePortrait(login?: string | null): string | null {
  // Хранится пара «чей — какой», а не один адрес. Кружок в журнале
  // переиспользуется под другого человека при перелистывании страницы,
  // и голый адрес показал бы лицо предыдущего до прихода нового.
  const [запись, положить] = useState<{ кто: string; адрес: string | null } | null>(
    () => (login ? { кто: login, адрес: кеш.get(login) ?? null } : null),
  );

  useEffect(() => {
    if (!login) return;

    let жив = true;
    const обновить = () => {
      if (!жив) return;
      положить({ кто: login, адрес: кеш.get(login) ?? null });
      // Не только читаем кеш, но и просим заполнить его: после
      // forgetPortrait запись пропала, и без этой строки кружок остался
      // бы пустым до перезагрузки. Повторно спрашивать не будет —
      // спросить() выходит сразу, если запись уже есть.
      void спросить(login);
    };

    подписчики.add(обновить);
    обновить();

    return () => {
      жив = false;
      подписчики.delete(обновить);
    };
  }, [login]);

  return login && запись?.кто === login ? запись.адрес : null;
}

/** Только для тестов: между ними кеш не должен протекать. */
export function __resetPortraits() {
  for (const адрес of кеш.values()) if (адрес) URL.revokeObjectURL(адрес);
  кеш.clear();
  вПути.clear();
  подписчики.clear();
}

"use client";

import { createContext, useCallback, useContext, useEffect, useRef } from "react";
import { accessToken } from "@/lib/auth";
import { apiUrl } from "@/lib/submit";

// Живые обновления разговоров — один поток на вкладку.
//
// ───────────────────────────────────────────────────────────────────────────
// Почему поток переехал сюда из раздела «Разговоры»
//
// Он там и был, и работал. Но работал ровно на одной странице: сотрудник,
// правивший карточку изделия, о новом обращении не узнавал никак — а именно
// он и есть тот, кого надо позвать. Разговор — единственная запись портала,
// у которой на том конце человек ждёт прямо сейчас.
//
// Второй поток рядом с первым заводить нельзя: у портала на разговоры стоят
// пределы по числу открытых соединений, и вкладка, держащая два вместо
// одного, съедает их вдвое быстрее. Поэтому поток один, а слушателей
// сколько угодно — счётчик в шапке, виджет очереди, сама страница разговоров.
//
// ───────────────────────────────────────────────────────────────────────────
// Переподключение — то, чего не было и из-за чего всё выглядело сломанным
//
// Соединение живёт полчаса: так задано на портале (ChatStream.TIMEOUT).
// В документации двери написано «после чего браузер переподключается сам»,
// и для сайта это правда — там EventSource, он умеет сам.
//
// Админка читает поток обычным fetch: EventSource не умеет слать заголовок,
// а админская дверь без токена не пускает. И вот fetch переподключаться
// НЕ умеет: через полчаса чтение просто заканчивается, и вкладка тихо
// перестаёт получать события. Снаружи это выглядит как «показывает только
// после обновления страницы» — что и было.
//
// Здесь поток переоткрывается: после чистого окончания сразу, после обрыва —
// с нарастающей паузой, чтобы упавший портал не получал шквал попыток.

type Слушатель = {
  /** В разговоре что-то изменилось. Текста в событии нет — только его номер. */
  changed?: (id: string) => void;
  /** Посетитель печатает прямо сейчас. */
  typing?: (id: string) => void;
};

const Ctx = createContext<{ subscribe: (l: Слушатель) => () => void }>({
  subscribe: () => () => {},
});

/** Подписаться на события разговоров. Отписка — сама, при снятии компонента. */
export function useLive(слушатель: Слушатель) {
  const { subscribe } = useContext(Ctx);

  // Слушатель пересоздаётся на каждом рендере вызывающего, и класть его
  // в зависимости эффекта значит переподписываться по десять раз в секунду.
  // Держим последний в ссылке, а подписка живёт всё время жизни компонента.
  const свежий = useRef(слушатель);
  // Обновляется после отрисовки, а не во время: запись в ссылку по ходу
  // рендера React считает ошибкой, и он прав — тот же рендер могут
  // выбросить и повторить.
  useEffect(() => {
    свежий.current = слушатель;
  });

  useEffect(
    () =>
      subscribe({
        changed: (id) => свежий.current.changed?.(id),
        typing: (id) => свежий.current.typing?.(id),
      }),
    [subscribe],
  );
}

const ПАУЗА_МИН = 1000;
const ПАУЗА_МАКС = 30_000;

export function LiveHost({ children }: { children: React.ReactNode }) {
  const слушатели = useRef(new Set<Слушатель>());

  const subscribe = useCallback((l: Слушатель) => {
    слушатели.current.add(l);
    return () => {
      слушатели.current.delete(l);
    };
  }, []);

  useEffect(() => {
    if (!apiUrl) return;

    let жив = true;
    let abort: AbortController | null = null;

    const пауза = (мс: number) => new Promise((r) => setTimeout(r, мс));

    const разослать = (вид: "changed" | "typing", id: string) => {
      // Копия набора: слушатель вправе отписаться прямо в обработчике,
      // а менять набор во время обхода — значит пропустить соседа.
      for (const l of [...слушатели.current]) {
        try {
          l[вид]?.(id);
        } catch {
          // Ошибка одного слушателя не должна рвать поток остальным.
        }
      }
    };

    const крутить = async () => {
      let попытка = 0;

      while (жив) {
        abort = new AbortController();
        let читалось = false;

        try {
          const token = await accessToken();
          if (!token) {
            // Токена нет — вошли не мы. Ждать бессмысленно и вредно:
            // цикл превратился бы в опрос двери, которая всё равно откажет.
            return;
          }

          const ответ = await fetch(`${apiUrl}/api/admin/v1/chats/stream`, {
            headers: { Authorization: `Bearer ${token}` },
            signal: abort.signal,
          });
          if (!ответ.ok || !ответ.body) throw new Error(`поток не открылся: ${ответ.status}`);

          читалось = true;
          попытка = 0;

          const reader = ответ.body.getReader();
          const decoder = new TextDecoder();
          // Кусок может прийти разрезанным посередине события, поэтому хвост
          // без завершающей пустой строки остаётся до следующего чтения.
          let хвост = "";

          while (жив) {
            const { done, value } = await reader.read();
            if (done) break;

            хвост += decoder.decode(value, { stream: true });
            const события = хвост.split("\n\n");
            хвост = события.pop() ?? "";

            for (const событие of события) {
              if (!событие.includes("data:")) continue;
              const data = событие.slice(событие.indexOf("data:") + 5).trim();

              if (событие.includes("event:typing")) {
                try {
                  const разобрано = JSON.parse(data) as { conversationId: string; who: string };
                  // «Сотрудник печатает» — это мы сами, и себе об этом
                  // сообщать незачем.
                  if (разобрано.who === "visitor") разослать("typing", разобрано.conversationId);
                } catch {
                  // Событие незнакомого вида — не повод рвать поток.
                }
                continue;
              }

              разослать("changed", data.replace(/^"|"$/g, ""));
            }
          }
        } catch {
          // Обрыв, отказ двери, снятие компонента — разбираются ниже одинаково.
        }

        if (!жив) return;

        // Чистое окончание (портал закрыл соединение по сроку) — переоткрываем
        // сразу: полчаса ожидания уже прошли. Обрыв, не успевший ничего
        // прочитать, — с нарастающей паузой.
        if (читалось) {
          попытка = 0;
        } else {
          попытка += 1;
          await пауза(Math.min(ПАУЗА_МИН * 2 ** (попытка - 1), ПАУЗА_МАКС));
        }
      }
    };

    void крутить();

    return () => {
      жив = false;
      abort?.abort();
    };
  }, []);

  return <Ctx.Provider value={{ subscribe }}>{children}</Ctx.Provider>;
}

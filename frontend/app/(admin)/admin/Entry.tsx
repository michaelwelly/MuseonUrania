// Слева — куда он попал, справа — что делать. Голая карточка «Войти через
// Keycloak» посреди пустого экрана не отвечает ни на один вопрос того, кто
// видит систему впервые, а вопросов у него три: что это, почему пароль
// спрашивают не здесь и что делать, если не пускает.
//
// `state` называет случай словами. Их четыре, и лечатся они по-разному:
// не настроено — задать переменные, не вошли — войти, токен не принят —
// получить роль, обмен кода не удался — начать заново. Одинаковая надпись
// «ошибка входа» на все четыре отправляет человека по кругу.
//
// Правила оформления глобальные и живут в admin.css — они общие для всех
// экранов админки, и модуль здесь завёл бы вторую копию тех же классов.


import { notFound } from "next/navigation";

// Перехватывающий маршрут для адресов, которых на сайте нет. Issue #104.
//
// ————— зачем он вообще —————
//
// У сайта два корневых layout'а — `(site)` и `(admin)`, — и это документированный
// приём Next (см. components/SiteShell.tsx). Плата за него вылезает ровно здесь:
// обычный `app/not-found.tsx` в такой раскладке оборачивать нечем, и Next
// на несопоставленный адрес отдаёт встроенную заглушку «404 · This page could
// not be found.» — по-английски, без шапки, подвала и единой ссылки.
//
// Перехват решает это без экспериментальных флагов: адрес попадает в группу
// `(site)`, получает её оболочку и `notFound()` приводит к `app/(site)/not-found.tsx`.
// Ответ остаётся 404 — `notFound()` ставит код сам.
//
// ————— почему он не съедает настоящие страницы —————
//
// Статический сегмент у Next всегда сильнее перехвата: `/products/`,
// `/documents/` и `/admin/` разбираются своими маршрутами, сюда попадает
// только то, что не совпало ни с одним. `/products/<неизвестный слаг>` тоже
// сюда не попадает — его ловит `[slug]`, который сам зовёт `notFound()`.
//
// Публичные файлы (`/favicon.ico`, `/photos/...`) отдаются раньше маршрутов
// и перехватом не задеваются.

/**
 * Перехват не должен становиться готовой страницей на сборке: адресов
 * у него бесконечно много, и предгенерировать нечего.
 */
export const dynamic = "force-dynamic";

export default function CatchAll() {
  notFound();
}

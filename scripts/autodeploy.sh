#!/usr/bin/env bash
#
# Автодеплой стенда: машина сама забирает изменения из main.
#
# ————— почему тянем, а не пушим —————
#
# Обычный CI-деплой ходит с раннера GitHub на сервер по SSH. Здесь так нельзя
# по двум причинам сразу:
#
#   1. Репозиторий публичный. Self-hosted раннер на публичном репозитории
#      GitHub прямо не рекомендует: workflow из форка выполняется на машине,
#      и присланный кем угодно PR превращается в выполнение чужого кода.
#   2. Диапазон адресов GitHub-раннеров огромен и меняется. Открывать под
#      него SSH на машине, где живёт боевой c3ag.ru, — несоразмерная плата
#      за удобство.
#
# Инверсия снимает обе: наружу не открыт ни один порт, в GitHub не лежит ни
# одного секрета, чужой код на машине не выполняется. Скрипт только сравнивает
# два хеша и запускает уже существующий деплой.
#
# ————— что делает —————
#
# Спрашивает у GitHub хеш main, сравнивает с последним развёрнутым и, если они
# разошлись, зовёт /opt/vedal-portal/scripts/deploy-stand-prod.sh main.
#
# Запускается таймером systemd. Установка — docs/operations/autodeploy.md.

set -euo pipefail

REPO="${VEDAL_REPO:-https://github.com/michaelwelly/MuseonUrania.git}"
BRANCH="${VEDAL_BRANCH:-main}"
DEPLOY="${VEDAL_DEPLOY:-/opt/vedal-portal/scripts/deploy-stand-prod.sh}"
STATE="${VEDAL_STATE:-/var/lib/vedal-autodeploy/deployed-sha}"
LOCK="${VEDAL_LOCK:-/var/lock/vedal-autodeploy.lock}"

log() { printf '%s  %s\n' "$(date --iso-8601=seconds)" "$*"; }

# Отсутствие flock — отказ, а не «занято». Проверка отдельной строкой, и вот
# почему: без неё `if ! flock -n 9` не отличает «лок занят» от «команды нет»,
# обе ветки дают ненулевой код. Скрипт писал бы в журнал «предыдущий деплой
# ещё идёт» и выходил с нулём — то есть навсегда перестал бы разворачивать
# стенд, ежеминутно отчитываясь об успехе. Поймано на прогоне.
if ! command -v flock >/dev/null 2>&1; then
  log "ОШИБКА: flock не найден, параллельные запуски защитить нечем"
  exit 1
fi

# Блокировка на весь запуск. Таймер может сработать, пока предыдущая сборка
# ещё идёт: деплой занимает минуты, а интервал таймера меньше. В самом
# deploy-stand-prod.sh лок тоже есть, но он оборвёт второй запуск ошибкой —
# а здесь это штатная ситуация, не сбой, и в журнале ей место как строке
# «занято», а не как падению.
exec 9>"$LOCK"
if ! flock -n 9; then
  log "предыдущий деплой ещё идёт — пропускаю"
  exit 0
fi

# Хеш ветки спрашиваем без клонирования: ls-remote отдаёт его одним запросом
# и не тащит историю. Публичный репозиторий, авторизация не нужна.
remote="$(git ls-remote "$REPO" "refs/heads/$BRANCH" | cut -f1)"
if [ -z "$remote" ]; then
  log "не удалось узнать хеш $BRANCH — GitHub недоступен, пробую в следующий раз"
  exit 1
fi

mkdir -p "$(dirname "$STATE")"
current="$(cat "$STATE" 2>/dev/null || true)"

if [ "$remote" = "$current" ]; then
  log "$BRANCH не менялся (${remote:0:8}) — деплой не нужен"
  exit 0
fi

log "новый $BRANCH: ${current:0:8} → ${remote:0:8}, разворачиваю"

# Отметка о развёрнутом хеше ставится ТОЛЬКО после успешного деплоя.
# Запиши её раньше — упавшая сборка считалась бы развёрнутой, и следующий
# запуск не стал бы повторять попытку: стенд остался бы на старом коде,
# а журнал сообщал бы, что всё в порядке.
if "$DEPLOY" "$BRANCH"; then
  printf '%s\n' "$remote" >"$STATE"
  log "готово: развёрнут ${remote:0:8}"
else
  code=$?
  log "деплой упал с кодом $code — отметка не обновлена, повторю в следующий раз"
  exit "$code"
fi

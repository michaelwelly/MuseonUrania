#!/usr/bin/env bash
#
# Выкатка стенд-прода на общей ВМ 51.250.31.97.
#
# ————— почему этот файл наконец лежит в репозитории —————
#
# До сих пор он жил только на машине, в /opt/vedal-portal/scripts/, как
# untracked-файл. Ровно тот кусок системы, который роняет сайт на несколько
# минут при каждой выкатке, нельзя было ни прочитать, ни отревьюить, ни
# откатить: чтобы узнать, что делает деплой, надо было зайти по SSH.
#
# Теперь он тут. Установка на машину — одной строкой, см.
# docs/operations/autodeploy.md.
#
# ————— что чинится (issue #89) —————
#
# Домен отдаёт внешний nginx соседа; его upstream — 172.17.0.1:18080, то есть
# порт, опубликованный контейнером шлюза. Пока контейнер шлюза пересоздаётся,
# порт не держит никто: docker-proxy снят вместе со старым контейнером и ещё
# не поднят с новым. Сосед получает connection refused и отдаёт посетителю
# 502.
#
# Прежняя версия делала это одной командой:
#
#     docker compose ... up -d --build --remove-orphans
#
# и окно получалось не «пока пересоздаётся шлюз», а «пока поднимается весь
# стек». Причина — в том, в каком порядке compose делает две половины
# пересоздания. СТАРЫЙ контейнер он снимает сразу, в начале `up`, а НОВЫЙ
# запускает в порядке зависимостей: шлюз ждёт portal: service_healthy,
# portal — db, kafka и keycloak. Между этими двумя моментами порт 18080
# не держит никто, и длится это ровно столько, сколько портал накатывает
# миграции и поднимает Spring. Минуты, а не секунды — 8 сентября владелец
# портала попал ровно в это окно и полчаса искал поломку, которой не было.
#
# Замерено на модели (две службы, зависимая публикует порт, зависимость
# становится здоровой за десяток секунд): одной командой `up -d` — окно 11 c,
# то есть весь `up`; по шагам с --no-deps — 1 c, только своё пересоздание;
# по шагам, когда зависимая служба не менялась, — окна нет вовсе.
#
# Здесь порядок разобран руками, и каждый шаг идёт с --no-deps, то есть
# без каскада:
#
#   1. Собрать образы. Ни один контейнер при этом не трогается: сборка
#      падает — стек остаётся тем, что работал.
#   2. Поднять инфраструктуру (db, kafka, keycloak, connect), если что-то
#      из неё изменилось. Шлюза это не касается.
#   3. Пересоздать portal и дождаться здоровья. Шлюз всё это время жив
#      и ДЕРЖИТ ПОРТ: сосед получает от него 503, а не connection refused,
#      и это разница между «сайт обновляется» и «сайта нет».
#   4. Пересоздать site и дождаться здоровья. Порт по-прежнему держит шлюз.
#   5. И только теперь тронуть сам шлюз — и то не всегда. `up -d` пересоздаёт
#      контейнер, только если изменился образ или конфигурация сервиса;
#      правка в backend/app или frontend/ шлюза не касается, и compose
#      честно ничего не делает. То есть в типичной выкатке порт 18080
#      не освобождается ВООБЩЕ.
#
# Чего это НЕ чинит, честно. Когда меняется сам api-gateway, окно остаётся:
# один порт нельзя отдать двум контейнерам сразу, и подмена без разрыва
# требует своего прокси перед шлюзом. Но окно это — старт одного Spring
# Boot, десятки секунд, а не минуты. И пока сайт с админкой обновляются
# (шаги 3–4), посетитель видит ответ шлюза, а не отказ соединения.
#
# Выкатку можно заморозить на время показа заказчику — см. scripts/autodeploy.sh
# и docs/operations/autodeploy.md.

set -euo pipefail

BRANCH="${1:-main}"

# Пути параметризованы не ради гибкости, а ради проверяемости: прогнать
# скрипт на подставных путях с заглушками вместо docker и git — единственный
# способ проверить порядок шагов, не выкатывая ничего на боевую машину.
ROOT="${VEDAL_ROOT:-/opt/vedal-portal}"
LOCK_DIR="${VEDAL_VAR:-$ROOT/var}"
LOCK_FILE="$LOCK_DIR/deploy.lock"
LOG_FILE="$LOCK_DIR/deploy.log"
HEALTH_URL="${VEDAL_HEALTH_URL:-http://127.0.0.1:18080/actuator/health}"

# Сколько ждём здоровья каждого контейнера. Портал накатывает миграции,
# сайт собирает страницы на старте — минуты, а не секунды.
WAIT_PORTAL="${VEDAL_WAIT_PORTAL:-300}"
WAIT_SITE="${VEDAL_WAIT_SITE:-420}"
WAIT_GATEWAY="${VEDAL_WAIT_GATEWAY:-180}"

# ————— перезапуск с копии —————
#
# Ниже идёт `git reset --hard`, и с этого коммита скрипт лежит в репозитории
# по тому же пути, по которому установлен на машине. То есть reset перепишет
# файл, который прямо сейчас выполняется. bash читает скрипт по мере
# выполнения, по смещению в файле: подмена на ходу — это выполнение середины
# нового файла с середины старого, то есть синтаксическая ошибка в лучшем
# случае и половина деплоя в худшем.
#
# Поэтому первым делом уходим в копию во временном каталоге и работаем
# оттуда. Признак — переменная окружения, чтобы копия не копировала себя
# снова.
if [ -z "${VEDAL_DEPLOY_REEXEC:-}" ]; then
  self_copy="$(mktemp -t vedal-deploy.XXXXXX)"
  cat "$0" >"$self_copy"
  chmod +x "$self_copy"
  export VEDAL_DEPLOY_REEXEC=1
  trap 'rm -f "$self_copy"' EXIT
  "$self_copy" "$@"
  exit $?
fi

mkdir -p "$LOCK_DIR"

exec 9>"$LOCK_FILE"
if ! flock -n 9; then
  echo "Another VEDAL deploy is already running. Try again later."
  exit 75
fi

exec > >(tee -a "$LOG_FILE") 2>&1

COMPOSE=(docker compose --env-file backend/.env -p vedal \
  -f backend/compose.yaml \
  -f backend/compose.host.yaml \
  -f backend/compose.stand-prod.yaml \
  --profile app)

say() { printf '%s  %s\n' "$(date -Is)" "$*"; }

# Ждём не «контейнер создан», а «контейнер здоров». Своим циклом, а не
# `up --wait`: тот появился не во всех версиях compose, а здесь важнее,
# чтобы в журнале осталось, сколько именно секунд занял каждый шаг, —
# без этих чисел спор об окне недоступности снова станет спором о
# впечатлениях.
wait_healthy() {
  local name="$1" limit="$2" started deadline state
  started=$(date +%s)
  deadline=$(( started + limit ))
  while :; do
    state=$(docker inspect \
      -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' \
      "$name" 2>/dev/null || echo missing)
    case "$state" in
      healthy|running)
        say "$name здоров за $(( $(date +%s) - started )) c"
        return 0
        ;;
      unhealthy|exited|dead)
        say "ОШИБКА: $name в состоянии $state"
        docker logs --tail 60 "$name" 2>&1 || true
        return 1
        ;;
    esac
    if [ "$(date +%s)" -ge "$deadline" ]; then
      say "ОШИБКА: $name не стал здоровым за $limit c (состояние: $state)"
      docker logs --tail 60 "$name" 2>&1 || true
      return 1
    fi
    sleep 3
  done
}

echo
say "==== VEDAL stand-prod deploy ===="
say "branch: $BRANCH"

cd "$ROOT"

git fetch origin
git checkout "$BRANCH"
git reset --hard "origin/$BRANCH"

"${COMPOSE[@]}" config --quiet

# ————— 1. сборка —————
#
# Отдельным шагом, до того как тронут хоть один контейнер. `up --build`
# делает то же самое, но разница видна в журнале: упавшая сборка теперь
# сообщает «стек не тронут», а не оставляет гадать, успел деплой что-нибудь
# пересоздать или нет.
say "собираю образы (контейнеры не трогаю)"
if ! "${COMPOSE[@]}" build; then
  say "ОШИБКА: сборка не прошла — стек не тронут, работает прежняя версия"
  exit 1
fi

# ————— холодный старт —————
#
# Если шлюза нет вовсе (машина после перезагрузки, стек снят руками),
# защищать нечего: порт и так не занят, и городить порядок незачем.
# Поднимаем всё разом, как раньше.
if ! docker inspect -f '{{.State.Running}}' vedal-gateway 2>/dev/null | grep -qx true; then
  say "шлюз не запущен — холодный старт, поднимаю стек целиком"
  "${COMPOSE[@]}" up -d --remove-orphans
else
  # ————— 2. инфраструктура —————
  #
  # --no-deps здесь и дальше не украшение: без него compose тянет за собой
  # зависимые сервисы и мы возвращаемся к каскаду, ради устранения которого
  # всё это написано.
  #
  # --remove-orphans здесь намеренно НЕТ, хотя в прежней версии он был.
  # На тёплом пути стек живой и отдаёт домен; уборка лишних контейнеров —
  # не та работа, ради которой стоит рисковать зацепить что-то из своего же
  # проекта. Она осталась на холодном старте, где терять нечего.
  say "инфраструктура: db, kafka, keycloak, connect"
  "${COMPOSE[@]}" up -d --no-deps db kafka keycloak connect connect-init

  # ————— 3. портал —————
  say "портал: пересоздаю (шлюз жив, порт 18080 занят)"
  "${COMPOSE[@]}" up -d --no-deps portal
  wait_healthy vedal-portal "$WAIT_PORTAL"

  # ————— 4. сайт —————
  say "сайт: пересоздаю (шлюз жив, порт 18080 занят)"
  "${COMPOSE[@]}" up -d --no-deps site
  wait_healthy vedal-site "$WAIT_SITE"

  # ————— 5. шлюз —————
  #
  # Единственный шаг, который может освободить порт, и он последний. Если
  # образ и конфигурация шлюза не менялись, compose не станет пересоздавать
  # контейнер — то есть порт не освободится вовсе. Отсюда и замер: в журнале
  # видно, было окно или нет.
  gateway_before=$(docker inspect -f '{{.Id}}' vedal-gateway 2>/dev/null || echo none)
  say "шлюз: проверяю, нужно ли пересоздавать"
  "${COMPOSE[@]}" up -d --no-deps api-gateway
  gateway_after=$(docker inspect -f '{{.Id}}' vedal-gateway 2>/dev/null || echo none)

  if [ "$gateway_before" = "$gateway_after" ]; then
    say "шлюз не менялся — порт 18080 не освобождался, окна недоступности не было"
  else
    say "шлюз пересоздан — было окно на время старта Spring Boot"
    wait_healthy vedal-gateway "$WAIT_GATEWAY"
  fi
fi

# MinIO из стека убран; контейнеры от прежних запусков остаются висеть,
# и --remove-orphans их не берёт — сервиса нет ни в одном профиле.
docker rm -f vedal-minio vedal-minio-init >/dev/null 2>&1 || true

# ————— проверка снаружи контейнеров —————
#
# По 127.0.0.1, а не по внешнему адресу: снаружи ответ портала смешан
# с состоянием канала, и таймаут чужого маршрутизатора выглядит как
# упавший деплой (см. scripts/healthcheck.sh).
say "жду ответа шлюза на $HEALTH_URL"
deadline=$(( "$(date +%s)" + 240 ))
while :; do
  if curl -fsS --connect-timeout 3 --max-time 10 "$HEALTH_URL" >/dev/null; then
    break
  fi
  if [ "$(date +%s)" -ge "$deadline" ]; then
    say "ОШИБКА: шлюз не ответил за 240 c"
    "${COMPOSE[@]}" ps
    exit 1
  fi
  sleep 5
done

"${COMPOSE[@]}" ps
say "public: http://51.250.31.97:18080"
say "health: $(curl -fsS "$HEALTH_URL")"
say "done: $(git rev-parse --short HEAD)"
